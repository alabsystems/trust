use std::path::PathBuf;
use std::process::Command;

#[test]
fn verify_cargo_cache_help_lists_release_materializer() {
    let output = Command::new(targo_trust_binary())
        .args(["trust", "verify", "cargo-cache", "--help"])
        .output()
        .expect("run verify cargo-cache help");

    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert_eq!(
        output.status.code(),
        Some(0),
        "verify cargo-cache help should succeed\nstdout:\n{stdout}\nstderr:\n{stderr}"
    );
    assert!(stdout.contains("Usage: targo trust verify cargo-cache"));
    assert!(stdout.contains("--cargo-home <path>"));
    assert!(stdout.contains("registry-only Cargo seed cache"));
}

// The materializer binds every required stage2 tool by one version probe each.
// Those are files a build has just written, so on a loaded host their first exec
// waits behind macOS's machine-wide syspolicyd scan (docs/KNOWN_HAZARDS.md
// EXEC-ASSESS-STALL-1). The trustfmt stand-in answers `--version` after 15 s, past
// the old 10 s bound on any host, so the result does not depend on load; it is
// far inside the hang guard the probe now has.
#[cfg(unix)]
#[test]
fn verify_cargo_cache_binds_a_required_tool_whose_version_answer_comes_after_ten_seconds() {
    use std::os::unix::fs::PermissionsExt;

    let unique = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .expect("clock after epoch")
        .as_nanos();
    let temp = std::env::temp_dir()
        .join(format!("targo-trust-cargo-cache-late-version-{}-{unique}", std::process::id()));
    let repo = temp.join("repo");
    let bin = repo.join("build/host/stage2/bin");
    std::fs::create_dir_all(&bin).expect("stage2 bin");
    std::fs::write(
        repo.join("Cargo.toml"),
        "[package]\nname='demo'\nversion='0.0.0'\nedition='2021'\n",
    )
    .expect("manifest");
    // sha256 of the stand-in fetch's "demo dep crate\n" payload.
    std::fs::write(
        repo.join("Cargo.lock"),
        r#"# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "demo-dep"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "106d5d1dfb6b67562758550ffb5147a19bef05e4b616a3c6a4d9fa26f73f300c"
"#,
    )
    .expect("lock");
    let stand_in = r#"#!/bin/sh
name="$(basename "$0")"
if [ "$name" = "targo" ] && [ "${1:-}" = "fetch" ]; then
    mkdir -p "$CARGO_HOME/registry/index/fake" "$CARGO_HOME/registry/cache/fake"
    printf 'demo dep crate\n' > "$CARGO_HOME/registry/cache/fake/demo-dep-1.0.0.crate"
    echo "fetch ok"
    exit 0
fi
case "$1" in
    --version|-Vv)
        if [ "$name" = "trustfmt" ]; then /bin/sleep 15; fi
        echo "$name fake stage2"
        exit 0
        ;;
    *)
        echo "unexpected $name invocation: $*" >&2
        exit 3
        ;;
esac
"#;
    for tool in [
        "trustc",
        "rustc",
        "targo",
        "cargo",
        "targo-trust",
        "trustd",
        "trustdoc",
        "rustdoc",
        "trustfmt",
        "targo-fmt",
        "tippy",
        "targo-tippy",
        "tippy-driver",
        "trust-analyzer",
    ] {
        let path = bin.join(tool);
        std::fs::write(&path, stand_in).expect("write stage2 stand-in");
        let mut permissions = std::fs::metadata(&path).expect("stand-in metadata").permissions();
        permissions.set_mode(0o755);
        std::fs::set_permissions(&path, permissions).expect("chmod stage2 stand-in");
    }

    let cargo_home = temp.join("seed-home");
    let json_output = temp.join("report.json");
    let started = std::time::Instant::now();
    let output = Command::new(targo_trust_binary())
        .args(["trust", "verify", "cargo-cache", "--repo-root"])
        .arg(&repo)
        .arg("--cargo-home")
        .arg(&cargo_home)
        .arg("--json-output")
        .arg(&json_output)
        .output()
        .expect("run verify cargo-cache with a late stage2 stand-in");
    let elapsed = started.elapsed();

    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    let report = std::fs::read_to_string(&json_output).unwrap_or_else(|error| {
        panic!(
            "read report {}: {error}\nstdout:\n{stdout}\nstderr:\n{stderr}",
            json_output.display()
        )
    });
    let proof: serde_json::Value = serde_json::from_str(&report).expect("report json");
    assert_eq!(
        proof["toolchain"]["trustfmt"]["status"], "passed",
        "the late trustfmt answer must be bound\nreport:\n{report}\nstderr:\n{stderr}"
    );
    assert_eq!(proof["toolchain"]["trustfmt"]["version_stdout"], "trustfmt fake stage2");
    assert_eq!(proof["toolchain"]["status"], "passed", "report:\n{report}");
    assert_eq!(
        output.status.code(),
        Some(0),
        "the materializer should pass\nstdout:\n{stdout}\nstderr:\n{stderr}\nreport:\n{report}"
    );
    assert!(
        elapsed >= std::time::Duration::from_secs(15),
        "the late stand-in was probed ({elapsed:?})"
    );

    let _ = std::fs::remove_dir_all(&temp);
}

fn targo_trust_binary() -> PathBuf {
    if let Some(path) = option_env!("CARGO_BIN_EXE_targo-trust") {
        return PathBuf::from(path);
    }

    let mut path = std::env::current_exe().expect("current test executable path");
    path.pop();
    if path.ends_with("deps") {
        path.pop();
    }
    path.push(format!("targo-trust{}", std::env::consts::EXE_SUFFIX));
    path
}
