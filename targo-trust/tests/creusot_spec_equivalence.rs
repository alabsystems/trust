//! Blob-equivalence acceptance harness for the creusot reader.
//!
//! ARCHITECTURE — independent sides (adversarial verdict 2026-08-21, defect 1
//! amendment): the harness never derives an expected goal through the mapper
//! being tested. Both goals come from the compiler's own spec-emit artifact
//! (`targo trust spec --emit clean --json`, the v6/D1 instrument), on two
//! packages with two different authorships:
//!
//!   BEFORE  fixtures/creusot-equiv/proposed/  — the tippy mapper's
//!           machine-applied output (lint `trust_creusot_spec_sugar`; the
//!           rewrite is pinned by the lint's rustfix ui test, and
//!           `proposed_side_carries_the_mapper_output` keeps the fixture in
//!           lockstep with that pin);
//!   AFTER   fixtures/creusot-equiv/native/    — a native clause authored BY
//!           HAND from the pearlite semantics of
//!           fixtures/creusot-equiv/pearlite/, never generated by the mapper.
//!
//! The goals are then compared BYTE-WISE. A mapper mistranslation changes only
//! the proposed side, so it must surface as a divergence — this is what the
//! round-trip design the verdict rejected could not do (both of its sides were
//! elaborations of one mapper-authored string).
//!
//! Deferrals honestly recorded (same verdict):
//! - defect 2 (cited-only walk): the v1 artifact renders goal rows for CITED
//!   ensures only, so both sides carry byte-identical citation furniture
//!   (`clean { .. }` island + `by u64_ge_refl`), which cancels in the
//!   comparison. Uncited requires/ensures coverage — and with it arithmetic
//!   subjects that have no hand-provable island theorem — waits for the
//!   kernel-ungraded denotation-row producer (a compiler-side extension, not
//!   part of this increment). When those rows land, the smoke subject should
//!   additionally include an UNCITED clause per the verdict's amendment.
//! - defect 3: the fixture subjects reference only immutable by-value machine
//!   parameters — the same restriction the lint enforces
//!   (MutablePostStateAmbiguity refusal otherwise).
//! - defect 4: no quantifier subject exists at any grade; the R4 §2 doctrine
//!   defers quantifier auto-application until the bounded-domain encoding.
//!
//! What runs where: the goal-map/diff layer and every fixture-integrity pin
//! below run in the ordinary cargo test lane. The end-to-end two-run test
//! needs the built Trust toolchain and is `#[ignore]`d with the exact command
//! in its reason string (written-not-run in this increment).

use std::collections::BTreeMap;
use std::path::PathBuf;
use std::process::Command;

fn fixture_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests").join("fixtures").join("creusot-equiv")
}

fn read_fixture(relative: &str) -> String {
    let path = fixture_root().join(relative);
    std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("fixture {} must be readable: {error}", path.display()))
}

/// One kernel-graded goal row from `targo trust spec --emit clean --json`.
#[derive(Debug, Clone, PartialEq)]
struct Goal {
    clause: String,
    goal_clean: Option<String>,
}

/// Key: (def_path, per-def ordinal). The ordinal keeps repeated identical
/// clauses on one function distinct, so a dropped duplicate cannot hide
/// (count-exactness; the verdict's minor note on `ClauseKey` dedup).
type GoalMap = BTreeMap<(String, u64), Goal>;

fn goal_map(json_rows: &str) -> Result<GoalMap, String> {
    let mut map = GoalMap::new();
    let mut ordinals: BTreeMap<String, u64> = BTreeMap::new();
    for line in json_rows.lines() {
        if line.trim().is_empty() {
            continue;
        }
        let value: serde_json::Value = serde_json::from_str(line)
            .map_err(|error| format!("invalid artifact row `{line}`: {error}"))?;
        if value.get("row").and_then(|v| v.as_str()) != Some("goal") {
            continue;
        }
        let def_path = value
            .get("def_path")
            .and_then(|v| v.as_str())
            .ok_or_else(|| format!("goal row without def_path: {line}"))?
            .to_string();
        let clause = value
            .get("clause")
            .and_then(|v| v.as_str())
            .ok_or_else(|| format!("goal row without clause: {line}"))?
            .to_string();
        let goal_clean = value.get("goal_clean").and_then(|v| v.as_str()).map(str::to_string);
        let ordinal = ordinals.entry(def_path.clone()).or_insert(0);
        map.insert((def_path, *ordinal), Goal { clause, goal_clean });
        *ordinal += 1;
    }
    Ok(map)
}

/// Byte-wise goal comparison. Only a key present on BOTH sides with a PRESENT
/// and byte-identical `goal_clean` confirms; everything else — a missing row,
/// an elaboration refusal on either side, a single differing byte — is a
/// divergence. Fail-closed: an empty proposed artifact confirms nothing.
fn diff_goals(before: &GoalMap, after: &GoalMap) -> Vec<String> {
    let mut divergences = Vec::new();
    for (key, expected) in after {
        match before.get(key) {
            None => divergences.push(format!(
                "{key:?}: the proposed clause produced no kernel-graded goal (NotInSession); \
                 independent clause `{}`",
                expected.clause
            )),
            Some(proposed) => match (&proposed.goal_clean, &expected.goal_clean) {
                (Some(b), Some(a)) if b == a => {}
                (b, a) => divergences.push(format!(
                    "{key:?}: goals differ\n  proposed clause `{}` goal {:?}\n  independent \
                     clause `{}` goal {:?}",
                    proposed.clause, b, expected.clause, a
                )),
            },
        }
    }
    for key in before.keys() {
        if !after.contains_key(key) {
            divergences.push(format!(
                "{key:?}: the proposed side grew a goal the independent side never authored"
            ));
        }
    }
    divergences
}

const GOAL_BEFORE: &str = r#"{"format":"trust-spec-clean","v":1,"row":"goal","crate":"creusot-equiv-subject","session":"s1","def_path":"creusot_equiv_subject::observe","origin":"ensures-citation","clause":"x >= x","theorem":"u64_ge_refl","goal_clean":"∀ (x : UInt64), Nat.le (UInt64.toNat x) (UInt64.toNat x)","elab_error":null,"verdict":"certified","detail":null}"#;
const GOAL_AFTER: &str = r#"{"format":"trust-spec-clean","v":1,"row":"goal","crate":"creusot-equiv-subject","session":"s2","def_path":"creusot_equiv_subject::observe","origin":"ensures-citation","clause":"x >= x","theorem":"u64_ge_refl","goal_clean":"∀ (x : UInt64), Nat.le (UInt64.toNat x) (UInt64.toNat x)","elab_error":null,"verdict":"certified","detail":null}"#;

#[test]
fn identical_goals_confirm() {
    let before = goal_map(GOAL_BEFORE).expect("proposed side parses");
    let after = goal_map(GOAL_AFTER).expect("independent side parses");
    assert!(diff_goals(&before, &after).is_empty(), "byte-identical goals must confirm");
}

/// SPLIT-LANE MUTATION CONTROL (verdict defect 1(b) as respecified): the
/// mistranslation is applied to the PROPOSED side only — the independent side
/// is fixture-authored and is NOT regenerated by the mutated mapper. A
/// `<=`→`<` mapper bug therefore reaches the comparison as two different
/// goals and MUST diverge. In the rejected round-trip design this exact
/// mutation changed both sides identically and confirmed.
#[test]
fn a_mapper_mistranslation_diverges() {
    let mutated = GOAL_BEFORE
        .replace(r#""clause":"x >= x""#, r#""clause":"x > x""#)
        .replace("Nat.le", "Nat.lt");
    let before = goal_map(&mutated).expect("mutated proposed side parses");
    let after = goal_map(GOAL_AFTER).expect("independent side parses");
    let divergences = diff_goals(&before, &after);
    assert_eq!(divergences.len(), 1, "the mistranslation must be caught: {divergences:?}");
    assert!(divergences[0].contains("Nat.lt"), "both byte strings shown: {}", divergences[0]);
    assert!(divergences[0].contains("Nat.le"), "both byte strings shown: {}", divergences[0]);
}

#[test]
fn a_missing_proposed_goal_is_a_divergence_not_a_pass() {
    let before = goal_map("").expect("empty artifact parses");
    let after = goal_map(GOAL_AFTER).expect("independent side parses");
    let divergences = diff_goals(&before, &after);
    assert_eq!(divergences.len(), 1);
    assert!(divergences[0].contains("NotInSession"), "{}", divergences[0]);
}

/// An elaboration refusal on either side is a divergence: only PRESENT,
/// byte-identical goals confirm. Two matching refusals are still not a
/// confirmation — there is no goal to stand behind.
#[test]
fn an_elaboration_refusal_never_confirms() {
    const REFUSED: &str = r#"{"format":"trust-spec-clean","v":1,"row":"goal","crate":"creusot-equiv-subject","session":"s3","def_path":"creusot_equiv_subject::observe","origin":"ensures-citation","clause":"x >= x","theorem":"u64_ge_refl","goal_clean":null,"elab_error":"refused","verdict":"unknown","detail":null}"#;
    let before = goal_map(REFUSED).expect("refusal row parses");
    let after = goal_map(REFUSED).expect("refusal row parses");
    assert_eq!(
        diff_goals(&before, &after).len(),
        1,
        "matching refusals must not read as equivalence — there is no goal to stand behind"
    );
}

/// The duplicate-clause hazard from the verdict's minor note: two identical
/// clauses on one function must occupy two keys, so dropping one cannot hide.
#[test]
fn duplicate_identical_clauses_stay_distinct() {
    let doubled = format!("{GOAL_BEFORE}\n{GOAL_BEFORE}");
    let map = goal_map(&doubled).expect("parses");
    assert_eq!(map.len(), 2, "ordinal keying must keep duplicates distinct");
}

/// Fixtures author CLAUSES, never goals: the expected side of the comparison
/// is always a live spec-emit run, so no fixture may carry a pasted artifact
/// row or rendered goal. (The clean-island theorem STATEMENT is furniture,
/// not a rendered goal — it is byte-identical on both sides and cancels.)
#[test]
fn fixtures_author_clauses_never_goals() {
    for file in ["pearlite/src/lib.rs", "proposed/src/lib.rs", "native/src/lib.rs"] {
        let text = read_fixture(file);
        assert!(
            !text.contains("goal_clean") && !text.contains("\"row\""),
            "{file} must not carry artifact rows or rendered goals"
        );
    }
    let pearlite = read_fixture("pearlite/src/lib.rs");
    assert!(
        pearlite.contains("#[creusot_contracts::ensures"),
        "the input side must be the pearlite original"
    );
    assert!(
        !pearlite.contains(" by u64_ge_refl"),
        "the input side carries no native citation — creusot has no such notion"
    );
    let native = read_fixture("native/src/lib.rs");
    assert!(
        native.contains("INDEPENDENT"),
        "the independent side must carry its authorship provenance"
    );
    assert!(
        native.contains("NOT") && native.contains("generated by the tippy mapper"),
        "the independent side must forbid regeneration by the mapper"
    );
}

/// BEFORE-side provenance: the proposed fixture's predicates are the tippy
/// mapper's machine-applied output, pinned in tippy's own lane by the rustfix
/// ui test. This test binds the fixture to that pin byte-wise, so nobody can
/// silently hand-edit the proposed side into an independent authorship (which
/// would recreate the co-authorship defect in the other direction).
#[test]
fn proposed_side_carries_the_mapper_output() {
    let fixed = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../src/tools/tippy/tests/ui/trust_creusot_spec_sugar_fixable.fixed");
    let fixed = std::fs::read_to_string(&fixed).unwrap_or_else(|error| {
        panic!(
            "the mapper's pinned rustfix output must exist at {} (it is the lint's ui \
             golden): {error}",
            fixed.display()
        )
    });
    // The mapper-pinned rewrites for the harness twins.
    let observe_mapped = "fn observe(x: u64) -> u64 ensures x >= x {";
    let keep_mapped = "fn keep(lo: u64) -> u64 ensures lo <= lo {";
    assert!(
        fixed.contains(observe_mapped) && fixed.contains(keep_mapped),
        "the ui golden must pin the harness twins' rewrites; if the mapper's rendering \
         changed, re-bless the ui test AND re-run the end-to-end equivalence before \
         updating the proposed fixture"
    );
    let proposed = read_fixture("proposed/src/lib.rs");
    assert!(
        proposed.contains("fn observe(x: u64) -> u64 ensures x >= x by u64_ge_refl {"),
        "proposed/observe must be the mapper output plus the shared citation furniture"
    );
    assert!(
        proposed.contains("fn keep(lo: u64) -> u64 ensures lo <= lo by u64_ge_refl {"),
        "proposed/keep must be the mapper output plus the shared citation furniture"
    );
}

/// The citation furniture must be byte-identical across sides so it cancels
/// in the comparison; a furniture skew would masquerade as (or mask) a
/// predicate divergence.
#[test]
fn citation_furniture_is_byte_identical_across_sides() {
    let island = "clean {\n    theorem u64_ge_refl : forall (x : UInt64),\n        Nat.le \
                  (UInt64.toNat x) (UInt64.toNat x) :=\n        fun x => Nat.le.refl \
                  (UInt64.toNat x)\n}";
    let proposed = read_fixture("proposed/src/lib.rs");
    let native = read_fixture("native/src/lib.rs");
    assert!(proposed.contains(island), "proposed island drifted from the shared furniture");
    assert!(native.contains(island), "native island drifted from the shared furniture");
    assert_eq!(
        proposed.matches(" by u64_ge_refl").count(),
        native.matches(" by u64_ge_refl").count(),
        "both sides must cite the same number of clauses"
    );
}

/// Goal rows key on def_path; a shared crate name keeps the two sides'
/// def_paths (and any crate-name leakage into rendered goals) byte-comparable.
#[test]
fn both_sides_share_one_crate_name() {
    for side in ["proposed/Cargo.toml", "native/Cargo.toml"] {
        let manifest = read_fixture(side);
        assert!(
            manifest.contains("name = \"creusot-equiv-subject\""),
            "{side} must declare the shared subject crate name"
        );
    }
}

fn targo_trust_binary() -> PathBuf {
    // The pipeline discovers trustc as a SIBLING of the targo-trust binary, so
    // a freshly built test binary in target/debug has no compiler next to it.
    // Prefer an explicitly named installed binary (e.g.
    // TRUST_SPEC_EQUIV_TARGO_TRUST=$REPO/build/host/stage2/bin/targo-trust),
    // then fall back to the cargo-built one.
    if let Ok(path) = std::env::var("TRUST_SPEC_EQUIV_TARGO_TRUST") {
        return PathBuf::from(path);
    }
    if let Some(path) = option_env!("CARGO_BIN_EXE_targo-trust") {
        return PathBuf::from(path);
    }
    let mut path = std::env::current_exe().expect("current test executable path");
    path.pop();
    if path.ends_with("deps") {
        path.pop();
    }
    path.push(format!("targo-trust{}", std::env::consts::EXE_SUFFIX));
    path
}

/// Drive `targo trust spec --emit clean --json` in one fixture package and
/// return the raw artifact rows. The goals print even when the verified build
/// itself fails (the v6/D1 debugging case), so a non-zero exit is tolerated
/// ONLY when goal rows were actually printed; zero rows means the fail-closed
/// refusal fired and the harness aborts loudly with the refusal text.
fn spec_emit_rows(package: &str) -> String {
    let dir = fixture_root().join(package);
    let output = Command::new(targo_trust_binary())
        .current_dir(&dir)
        .args(["trust", "spec", "--emit", "clean", "--json"])
        .output()
        .unwrap_or_else(|error| panic!("run targo trust spec in {}: {error}", dir.display()));
    let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
    if !stdout.lines().any(|line| line.contains("\"row\":\"goal\"")) {
        panic!(
            "no goal rows for {package}; the spec surface refused (fail-closed) or graded \
             nothing.\nstderr:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    stdout
}

/// The end-to-end gate: two live spec-emit runs, byte-wise goal diff. The
/// mapper authored only the proposed package's predicates; the independent
/// package's predicates were authored by hand from the pearlite semantics;
/// every goal came from the compiler.
#[test]
#[ignore = "needs the installed Trust toolchain (trustc lives beside targo-trust); run: cd targo-trust && TRUST_SPEC_EQUIV_TARGO_TRUST=$PWD/../build/host/stage2/bin/targo-trust targo --unverified test --test creusot_spec_equivalence -- --ignored"]
fn blob_equivalence_end_to_end() {
    let before = goal_map(&spec_emit_rows("proposed")).expect("proposed artifact rows parse");
    let after = goal_map(&spec_emit_rows("native")).expect("native artifact rows parse");
    assert!(!after.is_empty(), "the independent side must grade at least one goal");
    let divergences = diff_goals(&before, &after);
    assert!(
        divergences.is_empty(),
        "blob-equivalence DIVERGED — the proposal is refused, not applied:\n{}",
        divergences.join("\n")
    );
}
