//! R-5 groundwork: trust-cg's own whole-module consumer,
//! `trust_cg_codegen::Compiler::compile(&trust_ir::Module)`, reached from the
//! superproject — a MEASUREMENT AND TEST API, NOT A SHIPPING LANE.
//!
//! Plan `docs/plans/2026-09-29-trust-ir-sole-compile-path.md` R-5 names
//! `Compiler::compile` the one backend consumer and freezes
//! [`crate::module_to_lir`]'s coverage; its proven-output gate logic "moves with
//! the lane". Nothing here moves F1: `compiler/rustc_codegen_trust_cg` does not
//! call this module, and a tripwire test (`census::no_compiler_caller`) fails
//! the build's tests the moment it, or any other crate under `crates/` or
//! `targo-trust/`, does. What this module gives is the first
//! place both consumers can be run over the SAME `trust_ir::Module` and
//! compared, so step 2 increment 5's retarget starts from a measurement
//! (`docs/audits/2026-09-30-f1-consumer-census.md`, generated by the census
//! test) instead of a guess.
//!
//! # What it refuses, before trust-cg sees the module
//!
//! The two refusals that are F1's codegen boundary today and are not
//! trust-cg's own, so that the measurement never credits trust-cg with a
//! function F1 would refuse on principle:
//!
//! * any function carrying an `Inst::Assert` — part 1's predicate
//!   [`crate::module_to_lir::unfaithful_assert_site`] (plan §5 fail-open item
//!   1: trust-cg lowers `Assert` to `Opcode::Assert`, a trap, which is no more
//!   Rust's panic than `module_to_lir`'s `Brif`/`Trap` was);
//! * any `Producer::Clean` function — the same binding boundary
//!   `ModuleLirError::CleanOriginBelowCodegenGate` enforces (plan step 3).
//!
//! # The codegen license is the caller's to state
//!
//! Every entry point takes the `CodegenLicensePolicy` trust-cg compiles under,
//! and none supplies one of its own. trust-cg's default
//! (`CodegenLicensePolicy::default()`) refuses a body that carries no license
//! claim (`body_gate: None`; trust-cg decision gate DG-73, roadmap WS7.5), so a
//! caller that hands in claim-less modules either passes that default and gets
//! the refusal, or states the policy that admits them. The census (a child test
//! module) states `UnlicensedBodyPolicy::Permit` for its claim-less subjects and
//! pins that the default refuses them; the shipping consumer (`f1_compile`,
//! feature `ay-proofs`) compiles under the D31 license
//! (`f1_compile::f1_codegen_license`), never under anything set here.
//!
//! # What it does NOT give
//!
//! * **No proof.** Every configuration here has `emit_proofs: false` (set
//!   explicitly for objects; `CompilerConfig::for_host_jit` sets it for the
//!   JIT), and no proven-output gate runs over the bytes. This crate depends on
//!   `trust-cg-codegen` with `default-features = false` (`Cargo.toml`), so
//!   `-p trust-cg-bridge` builds it without `verify`; a workspace build can
//!   still unify `verify` on through other dependents (trust-spec-temporal,
//!   targo-trust), which is why the no-proof property rests on the explicit
//!   `emit_proofs: false`, not on the feature set. Every object and every JIT
//!   buffer this module returns is UNVERIFIED code.
//! * **No ABI authority.** The module's `struct_passing` policy and recorded
//!   slot facts are trust-cg's to read; no pass-mode cross-check against
//!   rustc's `FnAbi` is attached, unlike F1's lowering.
//! * **The JIT is the host's.** [`jit_trust_ir_module_via_compiler`] executes
//!   only on the target the process runs on, and on AArch64 trust-cg's JIT
//!   default is its `Unchecked` validation mode (uncertified bytes, announced
//!   on stderr by trust-cg).
//!
//! Author: Andrew Yates <andrewyates.name@gmail.com>
//! Copyright 2026 Andrew Yates | License: Apache 2.0

use std::collections::HashMap;

use trust_cg_codegen::pipeline::OptLevel;
use trust_cg_codegen::target::TargetSpec;
use trust_cg_codegen::{
    CodegenLicensePolicy, CompilationResult, CompileError, Compiler, CompilerConfig,
    JitCompilationResult, Target,
};
use trust_ir::Module;

use crate::module_to_lir::unfaithful_assert_site;

/// The targets this measurement API compiles for: the two AArch64 triples the
/// F1 corpus is minted on (the `direct_shadow` fixtures say
/// `aarch64-unknown-linux-gnu`; this host is `aarch64-apple-darwin`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ViaCompilerTarget {
    /// Mach-O, Apple AArch64 ABI.
    Aarch64AppleDarwin,
    /// ELF, AAPCS64.
    Aarch64UnknownLinuxGnu,
}

impl ViaCompilerTarget {
    /// Every target, in census order.
    pub const ALL: [Self; 2] = [Self::Aarch64AppleDarwin, Self::Aarch64UnknownLinuxGnu];

    /// The spelled-out triple handed to trust-cg (explicit, so the object
    /// format never comes from the host).
    #[must_use]
    pub const fn triple(self) -> &'static str {
        match self {
            Self::Aarch64AppleDarwin => "aarch64-apple-darwin",
            Self::Aarch64UnknownLinuxGnu => "aarch64-unknown-linux-gnu",
        }
    }

    /// The target this process runs on, when it is one of [`Self::ALL`].
    #[must_use]
    pub fn host() -> Option<Self> {
        if cfg!(all(target_arch = "aarch64", target_vendor = "apple", target_os = "macos")) {
            Some(Self::Aarch64AppleDarwin)
        } else if cfg!(all(target_arch = "aarch64", target_os = "linux", target_env = "gnu")) {
            Some(Self::Aarch64UnknownLinuxGnu)
        } else {
            None
        }
    }
}

/// Why [`compile_trust_ir_module_via_compiler`] or
/// [`jit_trust_ir_module_via_compiler`] produced no code.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum ViaCompilerError {
    /// A function carries an `Inst::Assert`, refused exactly as
    /// `ModuleLirError::ImplicitPanicUnfaithful` refuses it on F1.
    #[error(
        "function `{function}` [implicit-panic-unfaithful]: its body carries an `Assert` (block \
         {block}, node {index}); a failed `Assert` is an implicit Rust panic with no faithful \
         lowering on any trust-ir codegen consumer yet (plan §5 fail-open item 1)"
    )]
    ImplicitPanicUnfaithful {
        /// The refused function.
        function: String,
        /// The block carrying the first `Assert`.
        block: u32,
        /// The `Assert` node's index in that block's body.
        index: usize,
    },
    /// A `Producer::Clean` function reached the consumer; refused exactly as
    /// `ModuleLirError::CleanOriginBelowCodegenGate` refuses it on F1.
    #[error(
        "Clean-origin trust-ir function `{function}` is not admitted to codegen: no lane honors \
         the `clean-carrier-gate` carrier before plan step 3.6's Clean admission"
    )]
    CleanOriginBelowCodegenGate {
        /// The refused function.
        function: String,
    },
    /// trust-cg did not accept the explicit triple.
    #[error("trust-cg rejected target `{triple}`: {detail}")]
    TargetSpec {
        /// The triple handed to trust-cg.
        triple: &'static str,
        /// trust-cg's parse error, rendered.
        detail: String,
    },
    /// A JIT was requested on a host that is not one of [`ViaCompilerTarget::ALL`].
    #[error("the trust-cg JIT runs only on the host, and this host is not an admitted target")]
    JitHostUnsupported,
    /// trust-cg's `Compiler` refused or failed. Boxed: `CompileError` is large.
    #[error("trust-cg `Compiler` refused the module: {0}")]
    Compiler(Box<CompileError>),
}

impl ViaCompilerError {
    /// A stable class label for censuses: the variant name, and for a
    /// [`Self::Compiler`] error trust-cg's own variant name (its `Debug`
    /// spelling up to the first field delimiter).
    #[must_use]
    pub fn class_name(&self) -> String {
        match self {
            Self::ImplicitPanicUnfaithful { .. } => "ImplicitPanicUnfaithful".to_string(),
            Self::CleanOriginBelowCodegenGate { .. } => "CleanOriginBelowCodegenGate".to_string(),
            Self::TargetSpec { .. } => "TargetSpec".to_string(),
            Self::JitHostUnsupported => "JitHostUnsupported".to_string(),
            Self::Compiler(error) => {
                let debug = format!("{error:?}");
                let end = debug.find(['(', ' ', '{']).unwrap_or(debug.len());
                format!("Compiler::{}", &debug[..end])
            }
        }
    }
}

impl From<CompileError> for ViaCompilerError {
    fn from(error: CompileError) -> Self {
        Self::Compiler(Box::new(error))
    }
}

/// Refuse the module when any function with a body crosses F1's codegen
/// boundary (an `Assert`, or Clean origin). Declarations carry no code and are
/// not inspected.
///
/// # Errors
///
/// The first offending function, in module order, as
/// [`ViaCompilerError::ImplicitPanicUnfaithful`] or
/// [`ViaCompilerError::CleanOriginBelowCodegenGate`].
pub fn refuse_f1_boundary(module: &Module) -> Result<(), ViaCompilerError> {
    for function in module.functions.iter().filter(|f| !f.blocks.is_empty()) {
        if function.producer == Some(trust_ir::Producer::Clean) {
            return Err(ViaCompilerError::CleanOriginBelowCodegenGate {
                function: function.name.clone(),
            });
        }
        if let Some(site) = unfaithful_assert_site(function) {
            return Err(ViaCompilerError::ImplicitPanicUnfaithful {
                function: function.name.clone(),
                block: site.block.index(),
                index: site.index,
            });
        }
    }
    Ok(())
}

/// The `CompilerConfig` both entry points use: `O2`, proofs OFF (see the module
/// doc), sequential, no debug info.
fn measurement_config(target: Target) -> CompilerConfig {
    CompilerConfig {
        opt_level: OptLevel::O2,
        target,
        emit_proofs: false,
        parallel: false,
        ..CompilerConfig::default()
    }
}

/// Compile `module` to an object for `target` through trust-cg's
/// `Compiler::compile` under `license`, after [`refuse_f1_boundary`].
///
/// MEASUREMENT / TEST API: the object is unverified (no proof certificates, no
/// proven-output gate) and no rustc lane calls this.
///
/// # Errors
///
/// [`refuse_f1_boundary`]'s refusals, a rejected triple, or trust-cg's own
/// [`CompileError`] (under `CodegenLicensePolicy::default()`, a claim-less body
/// is refused by its license).
pub fn compile_trust_ir_module_via_compiler(
    module: &Module,
    target: ViaCompilerTarget,
    license: CodegenLicensePolicy,
) -> Result<CompilationResult, ViaCompilerError> {
    refuse_f1_boundary(module)?;
    compile_unchecked_boundary(module, target, license)
}

/// [`compile_trust_ir_module_via_compiler`] WITHOUT the F1 boundary: what
/// trust-cg itself does with the module under `license`. Private; besides the
/// public entry point only the census (a child test module) calls it, to
/// measure the consumer behind the refusal. Never a lane.
fn compile_unchecked_boundary(
    module: &Module,
    target: ViaCompilerTarget,
    license: CodegenLicensePolicy,
) -> Result<CompilationResult, ViaCompilerError> {
    let triple = target.triple();
    let spec = TargetSpec::parse(triple)
        .map_err(|e| ViaCompilerError::TargetSpec { triple, detail: e.to_string() })?;
    let compiler = Compiler::new_for_target_spec(measurement_config(Target::Aarch64), spec)
        .with_codegen_license(license);
    Ok(compiler.compile(module)?)
}

/// Compile `module` into executable memory on THIS host through trust-cg's
/// `Compiler::compile_module_to_jit` under `license`, after
/// [`refuse_f1_boundary`]. No external symbols are supplied.
///
/// MEASUREMENT / TEST API: the buffer holds unverified code (see the module
/// doc); it exists so a test can run trust-cg's output against trust-ir's
/// reference interpreter.
///
/// # Errors
///
/// [`refuse_f1_boundary`]'s refusals, [`ViaCompilerError::JitHostUnsupported`],
/// or trust-cg's own [`CompileError`].
pub fn jit_trust_ir_module_via_compiler(
    module: &Module,
    license: CodegenLicensePolicy,
) -> Result<JitCompilationResult, ViaCompilerError> {
    refuse_f1_boundary(module)?;
    if ViaCompilerTarget::host().is_none() {
        return Err(ViaCompilerError::JitHostUnsupported);
    }
    let mut config = CompilerConfig::for_host_jit();
    config.opt_level = OptLevel::O2;
    Ok(Compiler::new(config)
        .with_codegen_license(license)
        .compile_module_to_jit(module, &HashMap::new())?)
}

