/// Whether Trust already COVERS this call — either the separation engine models
/// it (`sep_engine::call_is_modeled`, emitting an obligation / tracking it) or the
/// unsafe-fn name heuristic recognizes it (block obligation). Exposed so the
/// compiler can cross-check against rustc's AUTHORITATIVE function safety
/// (`fn_sig().safety()`) and emit a fail-closed obligation for any rustc-unsafe
/// call Trust does NOT already cover — making unsafe-call detection complete (no
/// unsafe call silently escapes) instead of relying on the name lists alone.
#[must_use]
pub fn call_has_unsafe_model(callee: &str) -> bool {
    let lower = callee.to_lowercase();
    // T5A parity note: "::ffi::" was DELETED from `is_unsafe_fn_call`'s name
    // list (it matched a NAMESPACE and falsely flagged safe std::ffi paths in
    // unsafe-block detection), but it is retained HERE. This predicate only
    // reaches rustc-UNSAFE, non-foreign calls (the compiler gates on
    // `fn_sig().safety()` first), and every such call under a `::ffi::` path
    // (`CStr::from_ptr`, `CString::from_raw`, …) IS still covered by Trust's
    // block-obligation lane — now via the authoritative
    // `Terminator::Call::is_unsafe_sig` instead of the name. Claiming coverage
    // keeps the compiler from double-flagging those calls with an
    // always-refuting [unsafe:unmodeled-call] VC; safe ::ffi:: paths never get
    // here, so the old false-positive surface cannot return through this door.
    sep_engine::call_is_modeled(&lower)
        || unsafe_verify::detection::is_unsafe_fn_call(callee)
        || lower.contains("::ffi::")
}

/// Trust: Filter VCs by verification level.
