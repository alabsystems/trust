/// Mint an SMT/theory symbol owned by a verifier subsystem.  The double
/// underscore boundary is reserved by MIR extraction for generated metadata,
/// so these leaves cannot alias a retained Rust source identifier when both
/// occur in one [`Formula`].
pub(crate) fn generated_formula_symbol(namespace: &str, unqualified: &str) -> String {
    format!("__trust_{namespace}__{unqualified}")
}

/// Canonical theory variable for the discriminant of a MIR place.  Both the
/// default VC lane and CHC lowering must use this exact spelling or range/tag
/// facts generated by one lane become inert in the other.
pub(crate) fn discriminant_formula_var_name(place_name: &str) -> String {
    generated_formula_symbol("mir", &format!("discr_{place_name}"))
}

