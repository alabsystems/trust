/// Crate-derived callee facts for one VC-generation entry.
///
/// These facts can license assumptions at call sites, so they must travel with
/// the explicit generation context rather than live in independently mutable
/// thread-locals. A legacy/default generation entry receives an empty context
/// and therefore cannot inherit a caller or an earlier compiler session's
/// summaries.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CalleeSummaryContext {
    facts: std::sync::Arc<CalleeSummaryFacts>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct CalleeSummaryFacts {
    certified_backing_structs: trust_types::fx::FxHashSet<String>,
    return_bounds: trust_types::fx::FxHashMap<String, i128>,
    return_lower_bounds: trust_types::fx::FxHashMap<String, i128>,
    return_const_sets: trust_types::fx::FxHashMap<String, Vec<i128>>,
    return_disc_summaries: trust_types::fx::FxHashMap<String, generate::ReturnDiscSummary>,
    setter_summaries: trust_types::fx::FxHashMap<String, generate::SetterSummary>,
    return_bool_preds: trust_types::fx::FxHashMap<String, generate::ReturnBoolPredSummary>,
}

impl CalleeSummaryContext {
    /// Whether this context carries NO crate-derived callee facts at all.
    ///
    /// Used as a conservative telemetry/population eligibility guard by the
    /// compiler's quarantined VC-artifact container. A generation whose context
    /// carries ANY callee fact must not even be grouped under a function-content
    /// observation key alone (the facts are derived from OTHER functions and
    /// can change without this function's digest moving). Emptiness does not
    /// authorize cached-vector reuse; other generator inputs remain outside the
    /// experimental key and fresh generation is always required.
    /// Exhaustively destructured so adding a field here fails compilation and
    /// forces this guard to account for it.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        let CalleeSummaryFacts {
            certified_backing_structs,
            return_bounds,
            return_lower_bounds,
            return_const_sets,
            return_disc_summaries,
            setter_summaries,
            return_bool_preds,
        } = &*self.facts;
        certified_backing_structs.is_empty()
            && return_bounds.is_empty()
            && return_lower_bounds.is_empty()
            && return_const_sets.is_empty()
            && return_disc_summaries.is_empty()
            && setter_summaries.is_empty()
            && return_bool_preds.is_empty()
    }

    #[must_use]
    pub fn with_certified_backing_structs(
        mut self,
        names: trust_types::fx::FxHashSet<String>,
    ) -> Self {
        std::sync::Arc::make_mut(&mut self.facts).certified_backing_structs = names;
        self
    }

    #[must_use]
    pub fn with_return_bounds(mut self, bounds: trust_types::fx::FxHashMap<String, i128>) -> Self {
        std::sync::Arc::make_mut(&mut self.facts).return_bounds = bounds;
        self
    }

    #[must_use]
    pub fn with_return_lower_bounds(
        mut self,
        bounds: trust_types::fx::FxHashMap<String, i128>,
    ) -> Self {
        std::sync::Arc::make_mut(&mut self.facts).return_lower_bounds = bounds;
        self
    }

    #[must_use]
    pub fn with_return_const_sets(
        mut self,
        sets: trust_types::fx::FxHashMap<String, Vec<i128>>,
    ) -> Self {
        std::sync::Arc::make_mut(&mut self.facts).return_const_sets = sets;
        self
    }

    #[must_use]
    pub fn with_return_disc_summaries(
        mut self,
        summaries: trust_types::fx::FxHashMap<String, generate::ReturnDiscSummary>,
    ) -> Self {
        std::sync::Arc::make_mut(&mut self.facts).return_disc_summaries = summaries;
        self
    }

    #[must_use]
    pub fn with_setter_summaries(
        mut self,
        summaries: trust_types::fx::FxHashMap<String, generate::SetterSummary>,
    ) -> Self {
        std::sync::Arc::make_mut(&mut self.facts).setter_summaries = summaries;
        self
    }

    #[must_use]
    pub fn with_return_bool_preds(
        mut self,
        summaries: trust_types::fx::FxHashMap<String, generate::ReturnBoolPredSummary>,
    ) -> Self {
        std::sync::Arc::make_mut(&mut self.facts).return_bool_preds = summaries;
        self
    }
}

/// Function-owned proof policy for one VC-generation entry.
///
/// This is explicit at the compiler-to-vcgen boundary. Deep generation code
/// reads it through a dynamically scoped, owner-checked stack because threading
/// it through every internal visitor would add hundreds of plumbing parameters.
/// The stack is implementation detail: callers cannot mutate ambient policy.
/// Nested query forcing therefore installs the callee's policy only for the
/// callee scope and restores the caller exactly on return or unwind.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct VcgenContext {
    def_path: String,
    single_writer: bool,
    backing: bool,
    contract_panic_annotations: Vec<String>,
    callee_summaries: CalleeSummaryContext,
}

impl VcgenContext {
    /// Start a fail-closed context owned by exactly `def_path`.
    #[must_use]
    pub fn for_function(def_path: impl Into<String>) -> Self {
        Self { def_path: def_path.into(), ..Self::default() }
    }

    /// Enable or disable the `#[trust::single_writer]` mmap policy.
    #[must_use]
    pub fn with_single_writer(mut self, on: bool) -> Self {
        self.single_writer = on;
        self
    }

    /// Enable or disable the `#[trust::backing]` relational invariant policy.
    #[must_use]
    pub fn with_backing(mut self, on: bool) -> Self {
        self.backing = on;
        self
    }

    /// Install this function's extraction-validated contract-panic payloads.
    #[must_use]
    pub fn with_contract_panic_annotations(mut self, payloads: Vec<String>) -> Self {
        self.contract_panic_annotations = payloads;
        self
    }

    /// Attach the crate-derived callee facts owned by this generation entry.
    #[must_use]
    pub fn with_callee_summaries(mut self, summaries: CalleeSummaryContext) -> Self {
        self.callee_summaries = summaries;
        self
    }
}

thread_local! {
    static VCGEN_CONTEXT_STACK: std::cell::RefCell<Vec<VcgenContextFrame>> =
        const { std::cell::RefCell::new(Vec::new()) };
    static VCGEN_CONTEXT_NEXT_ID: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
}

#[derive(Clone, Debug)]
struct VcgenContextFrame {
    id: u64,
    context: VcgenContext,
}

pub(crate) struct VcgenContextGuard {
    frame_id: u64,
    _thread_affine: std::marker::PhantomData<std::rc::Rc<()>>,
}

impl Drop for VcgenContextGuard {
    fn drop(&mut self) {
        // Remove only the frame this guard owns. Normal lexical/unwind drops
        // are LIFO; ownership lookup also prevents an explicit out-of-order
        // drop from erasing a newer nested invocation.
        let _ = VCGEN_CONTEXT_STACK.try_with(|stack| {
            let mut stack = stack.borrow_mut();
            if let Some(index) = stack.iter().rposition(|frame| frame.id == self.frame_id) {
                stack.remove(index);
            }
        });
    }
}

/// Run one generation operation under `context`, restoring the previous frame
/// even when the operation panics. Kept crate-private so proof policy can enter
/// only through APIs that take an explicit [`VcgenContext`].
fn enter_vcgen_context(context: &VcgenContext) -> VcgenContextGuard {
    let frame_id = VCGEN_CONTEXT_NEXT_ID.with(|next| {
        let frame_id = next.get();
        next.set(frame_id.checked_add(1).expect("vcgen context scope id overflow"));
        frame_id
    });
    VCGEN_CONTEXT_STACK.with(|stack| {
        stack.borrow_mut().push(VcgenContextFrame { id: frame_id, context: context.clone() });
    });
    VcgenContextGuard { frame_id, _thread_affine: std::marker::PhantomData }
}

pub(crate) fn with_vcgen_context<R>(context: &VcgenContext, f: impl FnOnce() -> R) -> R {
    let _guard = enter_vcgen_context(context);
    f()
}

/// Run a public generation entry under `context` only when it belongs to the
/// function being generated. A mismatched owner receives a fresh empty frame:
/// function-local policy and crate-derived callee facts both fail closed.
pub(crate) fn with_function_vcgen_context<R>(
    def_path: &str,
    context: &VcgenContext,
    f: impl FnOnce() -> R,
) -> R {
    if context.def_path == def_path {
        return with_vcgen_context(context, f);
    }
    let empty = VcgenContext::for_function(def_path);
    with_vcgen_context(&empty, f)
}

/// Unit tests for deep internal helpers cannot always enter through a public
/// generation API. Give them the same unwind-safe scope rather than reviving
/// overwrite-only test setters that can contaminate a reused harness thread.
#[cfg(test)]
pub(crate) fn enter_test_callee_summaries(summaries: CalleeSummaryContext) -> VcgenContextGuard {
    enter_vcgen_context(
        &VcgenContext::for_function("<vcgen-test-summary-scope>").with_callee_summaries(summaries),
    )
}

fn with_current_vcgen_context<R>(def_path: &str, f: impl FnOnce(&VcgenContext) -> R) -> Option<R> {
    VCGEN_CONTEXT_STACK.with(|stack| {
        let stack = stack.borrow();
        let context = &stack.last()?.context;
        (context.def_path == def_path).then(|| f(context))
    })
}

fn with_current_callee_summaries<R>(f: impl FnOnce(&CalleeSummaryContext) -> R) -> Option<R> {
    VCGEN_CONTEXT_STACK.with(|stack| {
        let stack = stack.borrow();
        stack.last().map(|frame| f(&frame.context.callee_summaries))
    })
}

