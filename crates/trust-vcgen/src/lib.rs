#[cfg(test)]
mod f5_e2e_repro {
    use trust_types::{
        BasicBlock, BlockId, LocalDecl, Operand, Place, Rvalue, SourceSpan, Statement, Terminator,
        Ty, VcKind, VerifiableBody, VerifiableFunction,
    };

    use crate::modular::{FunctionSummary, SummaryDatabase};

    fn assign(place: Place, rvalue: Rvalue) -> Statement {
        Statement::Assign { place, rvalue, span: SourceSpan::default() }
    }

    #[test]
    fn f5_e2e_shape_dominance_fires() {
        let text = "(a) <= (1.0e150) && (a) >= (-(1.0e150)) && (b) <= (1.0e150) && (b) >= (-(1.0e150))";
        let pre = trust_types::parse_spec_expr(text).expect("parses");
        eprintln!("PARSED: {pre:?}");
        let func = VerifiableFunction {
            name: "caller".to_string(),
            def_path: "test::caller".to_string(),
            span: SourceSpan::default(),
            body: VerifiableBody {
                locals: vec![
                    LocalDecl { index: 0, ty: Ty::f64_ty(), name: Some("_0".into()) },
                    LocalDecl { index: 1, ty: Ty::f64_ty(), name: Some("a".into()) },
                    LocalDecl { index: 2, ty: Ty::f64_ty(), name: Some("b".into()) },
                    LocalDecl { index: 3, ty: Ty::f64_ty(), name: None },
                    LocalDecl { index: 4, ty: Ty::f64_ty(), name: None },
                    LocalDecl { index: 5, ty: Ty::f64_ty(), name: None },
                ],
                blocks: vec![
                    BasicBlock {
                        id: BlockId(0),
                        stmts: vec![
                            assign(Place::local(3), Rvalue::Use(Operand::Copy(Place::local(1)))),
                            assign(Place::local(4), Rvalue::Use(Operand::Copy(Place::local(2)))),
                        ],
                        terminator: Terminator::Call {
                            unwind: trust_types::UnwindEdge::Unreachable,
                            is_unsafe_sig: false,
                            is_foreign: false,
                            func: "test::callee".to_string(),
                            args: vec![
                                Operand::Move(Place::local(3)),
                                Operand::Move(Place::local(4)),
                            ],
                            dest: Place::local(5),
                            target: Some(BlockId(1)),
                            span: SourceSpan::default(),
                            atomic: None,
                        },
                    },
                    BasicBlock {
                        id: BlockId(1),
                        stmts: vec![assign(
                            Place::local(0),
                            Rvalue::Use(Operand::Copy(Place::local(5))),
                        )],
                        terminator: Terminator::Return,
                    },
                ],
                arg_count: 2,
                return_ty: Ty::f64_ty(),
            },
            contracts: vec![],
            preconditions: vec![pre.clone()],
            postconditions: vec![],
            spec: Default::default(),
        };
        let mut db = SummaryDatabase::new();
        let summary = FunctionSummary::new("test::callee")
            .with_param_names(vec!["a".to_string(), "b".to_string()])
            .with_precondition(pre);
        db.insert(summary);
        let vcs = crate::generate::generate_callsite_precondition_vcs(&func, &db);
        let precond: Vec<_> = vcs
            .iter()
            .filter(|vc| matches!(vc.kind, VcKind::Precondition { .. }))
            .collect();
        assert!(
            precond.is_empty(),
            "F5 dominance must skip the exactly-matching precondition; got {:#?}",
            precond.iter().map(|vc| &vc.formula).collect::<Vec<_>>()
        );
    }
}
