//! trust_vcgen: Verification condition generation for Trust
//!
//! Takes a VerifiableFunction (extracted from MIR) and produces
//! VerificationConditions that can be dispatched to solvers.
//!
//! For M2, focuses on L0 safety VCs:
//! - Arithmetic overflow (add, sub, mul on integer types)
//! - Division by zero
//! - Remainder by zero
//! - Index out-of-bounds (array/slice access)
//! - Assert terminator conditions (rustc's own safety checks)
//! - Cast overflow (narrowing, signed-to-unsigned, unsigned-to-signed)
//! - Negation overflow (-x when x == INT_MIN)
//!
//! Author: Andrew Yates <andrewyates.name@gmail.com>
//! Copyright 2026 Andrew Yates | License: Apache 2.0

// trust-vcgen is pure data-structure VC generation over trust-types'
// VerifiableFunction; it contains no `contract_requires { ... }` macro
// invocations and no `#[trust::..]` attributes are *applied* in this crate
// (the only references are in doc comments describing compiler-set hints,
// which are parsed elsewhere). The previous `#![feature(contracts_internals)]`
// + `#![feature(register_tool)]` + `#![register_tool(trust)]` were therefore
// dead nightly gates that blocked stable consumption (e.g. by the `clean`
// workspace) for no functional reason. Removed at the root so `generate_vcs`
// and the whole crate build on the stable release channel.
//
// The `rustc::*` allows below only fire under the compiler's internal lints
// (i.e. when built with `RUSTC_BOOTSTRAP`/inside rustc); they are inert on a
// normal stable build, so they stay as harmless tool-lint allows.
#![allow(rustc::default_hash_types, rustc::potential_query_instability)]
