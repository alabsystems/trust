/// Validate the positional Trust MIR invariants consumed by proof-capable VC
/// generation entry points.
///
/// Rustc extraction emits dense locals and blocks, and every `Place.local` /
/// `BlockId` in the public schema is a vector index.  A hand-built or stale
/// serialized body may instead make the retained `LocalDecl.index` or
/// `BasicBlock.id` disagree with that positional authority.  Admitting such a
/// body would let different proof lanes read different locals or blocks.  This
/// boundary therefore validates the complete structural reference graph before
/// any VC is generated.
///
/// This is structural admission, not provenance or authenticity. Public and
/// deserialized MIR fields such as `exhaustive_enum_unreachable`, `is_foreign`,
/// and `is_unsafe_sig` remain caller-constructible. Passing this check cannot
/// give those fields proof authority; only the live compiler extraction and its
/// transport-bound consumer may rely on their compiler-vetted meaning.
pub fn validate_function(func: &VerifiableFunction) -> Result<(), VcgenError> {
    let body = &func.body;
    if body.blocks.is_empty() {
        return Err(VcgenError::MissingBody(func.name.clone()));
    }
    if body.locals.is_empty() {
        return Err(VcgenError::MalformedMir {
            function: func.name.clone(),
            detail: "body has no return-place local at index 0".to_string(),
        });
    }
    if body.arg_count >= body.locals.len() {
        return Err(VcgenError::MalformedMir {
            function: func.name.clone(),
            detail: format!(
                "arg_count {} requires locals 0..={}, but the body has {} local(s)",
                body.arg_count,
                body.arg_count,
                body.locals.len()
            ),
        });
    }
    if body.locals[0].ty != body.return_ty {
        return Err(VcgenError::MalformedMir {
            function: func.name.clone(),
            detail: format!(
                "return-place local has type {:?}, but body.return_ty is {:?}",
                body.locals[0].ty, body.return_ty
            ),
        });
    }
    for (position, local) in body.locals.iter().enumerate() {
        if local.index != position {
            return Err(VcgenError::MalformedMir {
                function: func.name.clone(),
                detail: format!(
                    "local declaration at position {position} carries index {}",
                    local.index
                ),
            });
        }
    }
    for (position, block) in body.blocks.iter().enumerate() {
        if block.id != BlockId(position) {
            return Err(VcgenError::MalformedMir {
                function: func.name.clone(),
                detail: format!("basic block at position {position} carries id bb{}", block.id.0),
            });
        }
        for statement in &block.stmts {
            validate_statement_references(func, statement)?;
        }
        validate_terminator_references(func, &block.terminator)?;
    }
    Ok(())
}

fn validate_local_reference(func: &VerifiableFunction, local: usize) -> Result<(), VcgenError> {
    if local < func.body.locals.len() {
        Ok(())
    } else {
        Err(VcgenError::InvalidLocal { index: local, num_locals: func.body.locals.len() })
    }
}

fn validate_block_reference(func: &VerifiableFunction, block: BlockId) -> Result<(), VcgenError> {
    if block.0 < func.body.blocks.len() {
        Ok(())
    } else {
        Err(VcgenError::InvalidBlock {
            block: format!("bb{}", block.0),
            function: func.name.clone(),
        })
    }
}

fn validate_place_references(func: &VerifiableFunction, place: &Place) -> Result<(), VcgenError> {
    validate_local_reference(func, place.local)?;
    for projection in &place.projections {
        match projection {
            Projection::Index(local) => validate_local_reference(func, *local)?,
            Projection::Field(_)
            | Projection::Deref
            | Projection::Downcast(_)
            | Projection::OpaqueCast(_)
            | Projection::UnwrapUnsafeBinder(_)
            | Projection::ConstantIndex { .. }
            | Projection::Subslice { .. } => {}
            _ => {
                return Err(VcgenError::MalformedMir {
                    function: func.name.clone(),
                    detail: "place contains an unknown projection variant".to_string(),
                });
            }
        }
    }
    Ok(())
}

fn validate_operand_references(
    func: &VerifiableFunction,
    operand: &Operand,
) -> Result<(), VcgenError> {
    match operand {
        Operand::Copy(place) | Operand::Move(place) => validate_place_references(func, place),
        Operand::Constant(_) | Operand::Symbolic(_) | Operand::Unsupported { .. } => Ok(()),
        _ => Err(VcgenError::MalformedMir {
            function: func.name.clone(),
            detail: "body contains an unknown operand variant".to_string(),
        }),
    }
}

fn validate_rvalue_references(
    func: &VerifiableFunction,
    rvalue: &Rvalue,
) -> Result<(), VcgenError> {
    match rvalue {
        Rvalue::Use(operand)
        | Rvalue::UnaryOp(_, operand)
        | Rvalue::Cast(operand, _)
        | Rvalue::Repeat(operand, _) => validate_operand_references(func, operand),
        Rvalue::BinaryOp(_, lhs, rhs) | Rvalue::CheckedBinaryOp(_, lhs, rhs) => {
            validate_operand_references(func, lhs)?;
            validate_operand_references(func, rhs)
        }
        Rvalue::Ref { place, .. }
        | Rvalue::Discriminant(place)
        | Rvalue::Len(place)
        | Rvalue::AddressOf(_, place)
        | Rvalue::CopyForDeref(place) => validate_place_references(func, place),
        Rvalue::Aggregate(_, operands) | Rvalue::Unsupported { operands, .. } => {
            for operand in operands {
                validate_operand_references(func, operand)?;
            }
            Ok(())
        }
        // Trust: W2 inc-0 — `PtrOffset` is a KNOWN modeled carrier (the extracted
        // `BinOp::Offset`), not an unknown/malformed variant. Validate its two
        // operand references exactly like a `BinaryOp` so the body is admitted and
        // reaches the VC lane, where its fail-closed in-bounds obligation is
        // emitted (see `collect_rvalue_unsupported`). Rejecting it as malformed
        // here would defeat the distinguishable modeling — collapsing every offset
        // body to an indistinguishable MalformedTrustIr before the obligation runs.
        Rvalue::PtrOffset { ptr, count } => {
            validate_operand_references(func, ptr)?;
            validate_operand_references(func, count)
        }
        _ => Err(VcgenError::MalformedMir {
            function: func.name.clone(),
            detail: "body contains an unknown rvalue variant".to_string(),
        }),
    }
}

fn validate_statement_references(
    func: &VerifiableFunction,
    statement: &Statement,
) -> Result<(), VcgenError> {
    match statement {
        Statement::Assign { place, rvalue, .. } => {
            validate_place_references(func, place)?;
            validate_rvalue_references(func, rvalue)
        }
        Statement::StorageLive(local) | Statement::StorageDead(local) => {
            validate_local_reference(func, *local)
        }
        Statement::SetDiscriminant { place, .. }
        | Statement::Deinit { place }
        | Statement::Retag { place }
        | Statement::PlaceMention(place) => validate_place_references(func, place),
        Statement::Intrinsic { args, .. } | Statement::Unsupported { operands: args, .. } => {
            for operand in args {
                validate_operand_references(func, operand)?;
            }
            Ok(())
        }
        Statement::Coverage | Statement::ConstEvalCounter | Statement::Nop => Ok(()),
        _ => Err(VcgenError::MalformedMir {
            function: func.name.clone(),
            detail: "body contains an unknown statement variant".to_string(),
        }),
    }
}

fn validate_terminator_references(
    func: &VerifiableFunction,
    terminator: &Terminator,
) -> Result<(), VcgenError> {
    match terminator {
        Terminator::Goto(target) => validate_block_reference(func, *target),
        Terminator::SwitchInt { discr, targets, otherwise, .. } => {
            validate_operand_references(func, discr)?;
            let mut case_values = std::collections::BTreeSet::new();
            for (case_value, target) in targets {
                if !case_values.insert(*case_value) {
                    return Err(VcgenError::MalformedMir {
                        function: func.name.clone(),
                        detail: format!("SwitchInt contains duplicate case value {case_value}"),
                    });
                }
                validate_block_reference(func, *target)?;
            }
            validate_block_reference(func, *otherwise)
        }
        Terminator::Call { args, dest, target, atomic, .. } => {
            for arg in args {
                validate_operand_references(func, arg)?;
            }
            validate_place_references(func, dest)?;
            if let Some(target) = target {
                validate_block_reference(func, *target)?;
            }
            if let Some(atomic) = atomic {
                validate_place_references(func, &atomic.place)?;
                if let Some(dest) = &atomic.dest {
                    validate_place_references(func, dest)?;
                }
            }
            Ok(())
        }
        Terminator::Assert { cond, target, .. } => {
            validate_operand_references(func, cond)?;
            validate_block_reference(func, *target)
        }
        Terminator::Drop { place, target, .. } => {
            validate_place_references(func, place)?;
            validate_block_reference(func, *target)
        }
        Terminator::Opaque { targets, .. } => {
            for target in targets {
                validate_block_reference(func, *target)?;
            }
            Ok(())
        }
        Terminator::Return | Terminator::Unreachable | Terminator::Resume => Ok(()),
        _ => Err(VcgenError::MalformedMir {
            function: func.name.clone(),
            detail: "body contains an unknown terminator variant".to_string(),
        }),
    }
}

