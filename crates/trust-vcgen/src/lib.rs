/// Resolve the type of an operand from the function's local declarations.
///
/// Promoted to `pub` for use by trust-transval translation validation.
pub fn operand_ty(func: &VerifiableFunction, op: &Operand) -> Option<Ty> {
    match op {
        Operand::Copy(place) | Operand::Move(place) => place_ty(func, place),
        Operand::Constant(cv) => Some(match cv {
            ConstValue::Bool(_) => Ty::Bool,
            // SOUNDNESS (P0, hunt-revealed): `ConstValue::Int` carries no width, so it
            // was ALWAYS typed i64 — but an i128 constant SUBEXPRESSION (`i128::MAX-1`,
            // `i128::MIN+1`, `(i128::MAX/2)*2`) holds a value OUTSIDE i64's range, and
            // the i64-width in-range PREMISE then emitted for it (`i64::MIN <= v <=
            // i64::MAX`) is CONSTANT-FALSE — vacuously discharging any downstream
            // overflow VC (default-mode false proof: `let x=i128::MAX-1; x+b` proved
            // yet overflows). The value tells the width: a signed literal that does NOT
            // fit i64 cannot be narrower than i128 (Rust has no i65..i127), so widen to
            // 128. A value that fits i64 keeps width 64 — its in-range premise stays
            // TRUE and the OPERATION's type (not the const's) drives its overflow VC —
            // so this only corrects the previously-vacuous wide-constant case.
            ConstValue::Int(v) => {
                let width =
                    if (i64::MIN as i128..=i64::MAX as i128).contains(v) { 64 } else { 128 };
                Ty::Int { width, signed: true }
            }
            // ConstValue::Uint now carries bit width from MIR extraction.
            ConstValue::Uint(_, w) => Ty::Int { width: *w, signed: false },
            ConstValue::Float(_) => Ty::Float { width: 64 },
            ConstValue::FloatBits { width, .. } => Ty::Float { width: *width },
            ConstValue::Unit | ConstValue::CallableItem { .. } => Ty::Unit,
            // A typed opaque integer constant carries its declared integer type so
            // the arithmetic/bounds VCs it feeds get the correct sort. Its VALUE is
            // a fresh unconstrained symbol, so nothing is falsely proved.
            ConstValue::OpaqueScalar { width, signed } => {
                Ty::Int { width: *width, signed: *signed }
            }
            // Trust: piece #7a — a const-generic PARAM value carries its declared
            // integer type, identical to `OpaqueScalar`; identity is in the name.
            // `width == 1 && !signed` is the in-band encoding of a BOOL
            // const-generic (`const B: bool`, e.g. aterm-lz4's `USE_DICT`):
            // Rust has no 1-bit integer type, so the pattern is unambiguous.
            // It types as `Ty::Bool` so guards over it get the Bool sort that
            // its every use site expects — the correlation across `if B { … }`
            // branches (one shared symbol) is what keeps dict-gated paths from
            // decorrelating into spurious counterexamples.
            ConstValue::ConstParam { width: 1, signed: false, .. } => Ty::Bool,
            ConstValue::ConstParam { width, signed, .. } => {
                Ty::Int { width: *width, signed: *signed }
            }
            // Sound fallback for unknown ConstValue variants.
            // ConstValue is #[non_exhaustive], so new variants may appear.
            // Returning None (unknown type) is conservative — the caller will
            // use a default type, and VCs will be over-approximate.
            _ => return None,
        }),
        Operand::Symbolic(formula) => formula_ty(formula),
        // Sound fallback for unknown Operand variants.
        // Operand is #[non_exhaustive], so new variants may appear.
        // Return None rather than panicking — this causes callers to skip
        // VC generation for the unknown operand, which is sound (no missed bugs,
        // just potentially missed VCs).
        Operand::Unsupported { .. } => None,
        _ => None,
    }
}

/// Resolve an operand's type as a `Cow<Ty>` — the borrowed counterpart of `operand_ty`.
///
/// For a `Copy`/`Move` of a place this funnels through `place_ty_cow`, so a BARE FULL-VALUE
/// read of a fat-`Ty::Adt` local (`Operand::Move(whole_expr_local)`, the proof-combinator
/// family's `Expr`/`Eq`/`Name` arguments) resolves WITHOUT cloning the multi-MB declared
/// root — the dominant `TrustVcGenWorkBudgetExceeded` driver after the `place_ty` borrowed
/// walk. The `Constant`/`Symbolic` arms synthesize small owned types (a scalar `Ty`), so
/// they are returned `Cow::Owned`; nothing fat is ever cloned here.
///
/// Use this for any `operand_ty` caller that only INSPECTS the type (a `matches!`,
/// `is_integer`/`int_width`/`is_signed`, `sort_for_ty`/`ty_byte_size`, or an equality
/// check). A caller that needs an OWNED `Ty` (to store / feed a `VcKind`) keeps calling
/// `operand_ty` (or `.into_owned()`s this result), which meters the materialized clone
/// exactly as baseline.
///
/// SOUNDNESS: byte-identical RESULT to `operand_ty` — same resolution, the only difference
/// is that the fat root is BORROWED rather than cloned (`Ty` is immutable during VC-gen).
/// Inert/identical outside a VC-gen scope. DROP-ONLY: it never weakens or deletes an
/// obligation; under-charging the meter for a clone that never happens can only let MORE
/// functions complete (Unknown → Proved/runtime-checked), never manufacture a false-prove.
pub(crate) fn operand_ty_cow<'a>(
    func: &'a VerifiableFunction,
    op: &Operand,
) -> Option<std::borrow::Cow<'a, Ty>> {
    use std::borrow::Cow;
    match op {
        Operand::Copy(place) | Operand::Move(place) => place_ty_cow(func, place),
        // The non-place arms synthesize small scalar types — borrowing buys nothing, so
        // reuse `operand_ty`'s exact construction and own the (cheap) result. This keeps
        // the `ConstValue::Int` i64/i128 width-widening soundness fix (and every other
        // arm) in ONE place.
        _ => operand_ty(func, op).map(Cow::Owned),
    }
}

fn formula_ty(formula: &Formula) -> Option<Ty> {
    let sort = formula_sort(formula)?;
    match sort {
        Sort::Bool => Some(Ty::Bool),
        Sort::Int => Some(Ty::Int { width: 64, signed: true }),
        Sort::BitVec(width) => Some(Ty::Int { width, signed: false }),
        Sort::Array(_, _) => None,
        _ => None,
    }
}

pub(crate) fn formula_sort(formula: &Formula) -> Option<Sort> {
    match formula {
        Formula::Bool(_) => Some(Sort::Bool),
        Formula::Int(_) | Formula::UInt(_) => Some(Sort::Int),
        Formula::BitVec { width, .. } => Some(Sort::BitVec(*width)),
        Formula::Var(_, sort) | Formula::SymVar(_, sort) => Some(sort.clone()),
        Formula::Not(_)
        | Formula::And(_)
        | Formula::Or(_)
        | Formula::Implies(_, _)
        | Formula::Eq(_, _)
        | Formula::Lt(_, _)
        | Formula::Le(_, _)
        | Formula::Gt(_, _)
        | Formula::Ge(_, _)
        | Formula::BvULt(_, _, _)
        | Formula::BvULe(_, _, _)
        | Formula::BvSLt(_, _, _)
        | Formula::BvSLe(_, _, _)
        | Formula::Forall(_, _)
        | Formula::Exists(_, _) => Some(Sort::Bool),
        Formula::Add(_, _)
        | Formula::Sub(_, _)
        | Formula::Mul(_, _)
        | Formula::Div(_, _)
        | Formula::Rem(_, _)
        | Formula::Neg(_)
        | Formula::BvToInt(_, _, _) => Some(Sort::Int),
        Formula::BvAdd(_, _, width)
        | Formula::BvSub(_, _, width)
        | Formula::BvMul(_, _, width)
        | Formula::BvUDiv(_, _, width)
        | Formula::BvSDiv(_, _, width)
        | Formula::BvURem(_, _, width)
        | Formula::BvSRem(_, _, width)
        | Formula::BvAnd(_, _, width)
        | Formula::BvOr(_, _, width)
        | Formula::BvXor(_, _, width)
        | Formula::BvNot(_, width)
        | Formula::BvShl(_, _, width)
        | Formula::BvLShr(_, _, width)
        | Formula::BvAShr(_, _, width)
        | Formula::IntToBv(_, width) => Some(Sort::BitVec(*width)),
        Formula::BvExtract { high, low, .. } => Some(Sort::BitVec(high.saturating_sub(*low) + 1)),
        Formula::BvConcat(lhs, rhs) => {
            Some(Sort::BitVec(formula_bit_width(lhs)?.saturating_add(formula_bit_width(rhs)?)))
        }
        Formula::BvZeroExt(inner, extra) | Formula::BvSignExt(inner, extra) => {
            Some(Sort::BitVec(formula_bit_width(inner)?.saturating_add(*extra)))
        }
        Formula::Ite(_, then_formula, else_formula) => {
            let then_sort = formula_sort(then_formula)?;
            (then_sort == formula_sort(else_formula)?).then_some(then_sort)
        }
        Formula::Select(array, _) => match formula_sort(array)? {
            Sort::Array(_, elem) => Some(*elem),
            _ => None,
        },
        Formula::Store(array, _, _) => formula_sort(array),
        _ => None,
    }
}

fn formula_bit_width(formula: &Formula) -> Option<u32> {
    match formula_sort(formula)? {
        Sort::BitVec(width) => Some(width),
        _ => None,
    }
}

// ── verifier-perf: mid-generation VC-WORK budget (a sound, additive bound) ──
//
// A function can have modest *per-place* types yet still explode the VC-generator,
// because the generation walk MATERIALIZES (clones) the declared `Ty` tree once per
// `place_ty`/`place_sort`/`operand_ty` query, of which there are O(places ×
// statements). When the declared type is a deeply-nested recursive ADT — the kernel's
// `Expr`/`ExprKind`/`Name`/`Environment` lower to fat `Ty::Adt` trees (flattened
// enums) — those repeated deep clones drive VC-gen to multi-GB RSS and never complete.
// `clean-kernel`'s `build_ind_app` (`for fv in param_fvars { app = Expr::app(app, fv) }`)
// is the witness: modest declared signature, thousands of fat-`Adt` clones, minutes of
// stall with the verifier making zero progress.
//
// FIX (a TRUE mid-generation work-bound): meter the ACTUAL generation work — the
// structural `Ty`-node count materialized by every type clone the generation walk
// performs. `place_ty` is the funnel through which the walk materializes an owned
// declared/projected `Ty`; `place_sort_from_declared_type` → `sort_for_ty` is the
// second O(datatype-size) hot path (it builds a `Sort` WITHOUT cloning the `Ty`, so it
// bypasses `place_ty`). Accumulate the node count per function in a thread-local; once
// it crosses the budget, set a sticky `tripped` flag and, from then on, have these hot
// paths hand back cheap fail-closed values (a `Ty::Unsupported` leaf / `Sort::Int`) so
// the in-flight walk finishes in bounded time rather than stalling. The per-function
// VC-gen entry points reset the meter on entry and, on exit, if it tripped, DISCARD
// every (partial, possibly leaf-degraded) obligation the walk produced and emit a single
// fail-closed `UnsupportedMir` for the whole function — degrading it, and only it, to
// Unknown.
//
// SOUNDNESS (paramount): this can only ADD Unknown, never manufacture a PROVE.
//  * The `tripped` flag is sticky for the function. Any obligation generated after the
//    trip — degraded leaf or not — is DISCARDED by the entry point, so the leaf returns
//    never reach a reported verdict.
//  * A non-tripping function clones identically to baseline (the meter only counts; it
//    never alters a type), so its verdicts are byte-identical.
//  * A tripping function is replaced wholesale by `unsupported_mir_vc`, which
//    preclassifies to Unknown and is NEVER Proved, and never a guaranteed-violation.
// Each function's VC-gen is independent (its own reset on entry); the meter is inert
// outside a scope, so a stray `place_ty` call behaves as pre-bound baseline.

/// Default mid-generation work budget, counted as structural `Ty` nodes MATERIALIZED
/// across the two O(datatype-size) generation hot paths during ONE function's VC-gen:
/// the `place_ty` `Ty`-tree clones AND the `place_sort_from_declared_type` →
/// `sort_for_ty` builds (each called O(places × statements) times). Sized FAR above any
/// ordinary function (a typical function touches a few small types a few hundred times —
/// well under ~500K nodes) but FAR below the many millions a `build_ind_app`-shaped
/// aggregate-loop explosion reaches before it stalls at multi-GB RSS. So only the
/// genuinely pathological generation-explosion functions trip it, and they trip EARLY
/// (bounding peak memory). The production value is deterministic because crossing this
/// bound changes the fail-closed obligation inventory.
const MAX_GENERATION_WORK_BUDGET: usize = 2_000_000;

mod gen_work {
    //! Thread-local mid-generation work meter (see the block comment above
    //! `place_ty`). A re-entrancy DEPTH guard makes the meter scope the OUTERMOST
    //! VC-gen entry for a function: nested calls (e.g.
    //! `…_and_summaries` → `…_with_discharge` → `generate_vcs`) share one meter, so
    //! the work the outer call already accumulated (callsite preconditions,
    //! abstract-interp pre-pass) is not clobbered by an inner reset. The meter resets
    //! only on the 0→1 entry and the budget/flag persist for the whole function's
    //! generation.
    use std::cell::{Cell, RefCell};

    thread_local! {
        /// Cumulative structural `Ty`-node work materialized this function.
        static WORK: Cell<usize> = const { Cell::new(0) };
        /// Sticky: set once `WORK` crosses the budget for this function.
        static TRIPPED: Cell<bool> = const { Cell::new(false) };
        /// Per-function cached deterministic budget.
        /// `usize::MAX` disables the bound.
        static BUDGET: Cell<usize> = const { Cell::new(super::MAX_GENERATION_WORK_BUDGET) };
        /// Re-entrancy depth: reset fires only on the 0→1 transition.
        static DEPTH: Cell<usize> = const { Cell::new(0) };
        /// Locals whose declared-type materialization has ALREADY been charged this
        /// scope, keyed by `(locals-slice ptr, local index)`. The meter measures PEAK
        /// materialization, not cumulative re-query CHURN: every projected place type is a
        /// SUBTREE of its base local's declared type (`<= that local's node count`, itself
        /// `<= 8_000` — the extractor's `MAX_TYPE_LOWERING_PRODUCED_NODES` cap) and every
        /// clone is TRANSIENT (built into a `Sort`, then dropped), so at most O(1) fat clone
        /// is live at a time. Charging a local's declared-type nodes ONCE (an upper bound
        /// covering all its projections) bounds peak by `Sigma_{distinct locals} nodes(ty)`;
        /// re-charging the same local per query mistook cumulative churn for peak and tripped
        /// spuriously (aterm-spec `eval`: a few `Expr`-typed locals re-queried hundreds of
        /// times across lanes). The `ptr` discriminator keeps the key correct under a
        /// cross-function nested `enter()` reusing a bare index.
        static CHARGED: RefCell<trust_types::fx::FxHashSet<(usize, usize)>> =
            RefCell::new(trust_types::fx::FxHashSet::default());
    }

    #[cfg(test)]
    thread_local! {
        static TEST_BUDGET: Cell<Option<usize>> = const { Cell::new(None) };
    }

    /// The production work budget is fixed because crossing it changes the
    /// fail-closed obligation inventory. Tests use an explicit thread-local
    /// override rather than ambient process state.
    fn read_budget() -> usize {
        #[cfg(test)]
        if let Some(budget) = TEST_BUDGET.with(Cell::get) {
            return if budget == 0 { usize::MAX } else { budget };
        }
        super::MAX_GENERATION_WORK_BUDGET
    }

    #[cfg(test)]
    pub(super) fn set_test_budget(budget: Option<usize>) {
        TEST_BUDGET.with(|slot| slot.set(budget));
    }

    /// Enter a VC-gen scope. On the OUTERMOST entry (depth 0→1) the meter is reset and
    /// the budget re-read. Returns a guard that decrements depth on drop.
    #[must_use]
    pub(super) fn enter() -> Guard {
        let depth = DEPTH.with(|d| {
            let n = d.get();
            d.set(n + 1);
            n
        });
        if depth == 0 {
            WORK.with(|w| w.set(0));
            TRIPPED.with(|t| t.set(false));
            BUDGET.with(|b| b.set(read_budget()));
            CHARGED.with(|c| c.borrow_mut().clear());
            // A fresh outermost scope is a fresh function: drop any memoized
            // place types/Sorts from the previous one (see `place_memo`).
            super::place_memo::reset();
        }
        Guard
    }

    /// RAII scope guard: decrements the re-entrancy depth on drop and, when the
    /// OUTERMOST scope exits (depth→0), clears the meter so a tripped state can never
    /// leak into a later, unscoped `place_ty` call on the same thread.
    pub(super) struct Guard;
    impl Drop for Guard {
        fn drop(&mut self) {
            let depth = DEPTH.with(|d| {
                let n = d.get().saturating_sub(1);
                d.set(n);
                n
            });
            if depth == 0 {
                WORK.with(|w| w.set(0));
                TRIPPED.with(|t| t.set(false));
                CHARGED.with(|c| c.borrow_mut().clear());
                // The function's generation is over: free the memoized place
                // types/Sorts so nothing can leak into a later scope (or into an
                // unscoped call, where the memo is inert anyway).
                super::place_memo::reset();
            }
        }
    }

    /// Charge a LOCAL's declared-type materialization ONCE per scope (peak-work metering).
    /// `locals_ptr` is `func.body.locals.as_ptr() as usize` (the per-function discriminator);
    /// `nodes_for_cap` computes the node count given the remaining headroom `cap` (called ONLY
    /// on the first metered touch of this local). Returns whether the meter is now tripped —
    /// on `true` the caller degrades to a leaf. A re-touch of an already-charged local, an
    /// inert scope, a tripped meter, or a disabled budget all charge 0. See the `CHARGED` doc
    /// for the peak-vs-cumulative soundness argument (drop-only; never a false PROVE).
    pub(super) fn charge_local_once(
        locals_ptr: usize,
        local: usize,
        nodes_for_cap: impl FnOnce(usize) -> usize,
    ) -> bool {
        if !scope_active() {
            return false;
        }
        if TRIPPED.with(Cell::get) {
            return true;
        }
        if BUDGET.with(Cell::get) == usize::MAX {
            return false;
        }
        let newly = CHARGED.with(|c| c.borrow_mut().insert((locals_ptr, local)));
        if !newly {
            return false;
        }
        let cap = remaining().saturating_add(1);
        record(nodes_for_cap(cap))
    }

    /// Whether a VC-gen scope is currently active on this thread. Outside any scope the
    /// meter is inert, so a stray `place_ty` call behaves as pre-bound baseline.
    pub(super) fn scope_active() -> bool {
        DEPTH.with(Cell::get) > 0
    }

    /// Record `nodes` of materialized type-clone work; trip if the cumulative total
    /// crosses the budget. Returns whether the meter is now tripped. Inert (returns
    /// false, records nothing) when no scope is active.
    pub(super) fn record(nodes: usize) -> bool {
        if !scope_active() {
            return false;
        }
        if TRIPPED.with(Cell::get) {
            return true;
        }
        let budget = BUDGET.with(Cell::get);
        if budget == usize::MAX {
            return false;
        }
        let total = WORK.with(|w| {
            let n = w.get().saturating_add(nodes);
            w.set(n);
            n
        });
        if total > budget {
            TRIPPED.with(|t| t.set(true));
            if std::env::var("TRUST_VCGEN_TRACE_BUDGET").is_ok() {
                use std::io::Write as _;
                let _ = writeln!(
                    std::io::stderr(),
                    "[GEN_WORK_BUDGET] tripped: cumulative type-clone work {total} > budget {budget} (function degraded to Unsupported)"
                );
                let _ = std::io::stderr().flush();
            }
            true
        } else {
            false
        }
    }

    /// Whether this function's VC-gen tripped the work budget. Inert (false) when no
    /// scope is active.
    pub(super) fn is_tripped() -> bool {
        scope_active() && TRIPPED.with(Cell::get)
    }

    /// Remaining work headroom before the budget trips (saturating). Used to cap
    /// per-call node counting at O(headroom) so a single huge type costs no more than
    /// what is needed to decide the trip. `usize::MAX` when the bound is disabled.
    pub(super) fn remaining() -> usize {
        let budget = BUDGET.with(Cell::get);
        if budget == usize::MAX {
            return usize::MAX;
        }
        budget.saturating_sub(WORK.with(Cell::get))
    }

    /// Cumulative work recorded this function (diagnostic / threshold-calibration).
    pub(super) fn used() -> usize {
        WORK.with(Cell::get)
    }
}

// ── verifier-perf: per-function place-type/Sort memo for the metered hot paths ──
//
// `place_ty` and `place_sort_from_declared_type` are DETERMINISTIC in `(func, place)`:
// they read only the function's declared local types (immutable for the whole VC-gen
// pass, see `place_ty_cow`) and the place's projection path. Yet the generation walk
// queries the SAME places O(places × statements) times per lane, and each owned query
// re-materializes (deep-clones / re-builds) the same resolved `Ty`/`Sort` tree. For a
// long straight-line function over moderate flattened ADTs (`Vec<LinearConstraint>` /
// `Result<…>` with `BTreeMap<String, _>`/`String` internals — ~50-300-node `Ty::Adt`
// trees), that re-clone PRODUCT alone crosses `MAX_GENERATION_WORK_BUDGET` and
// fail-closes a function whose types are individually harmless (ny-cert's
// `crown::Relu1Problem::certify` is the witness).
//
// FIX: memoize the computed `Ty`/`Sort` per function, keyed by `(local, encoded
// projection path)`. The meter charge is the peak per-local `charge_local_once` (the
// base local's declared type covers every projected subtree, paid once per scope); a
// HIT charges `HIT_COST` (~a map lookup), so the meter reflects real
// first-materialization work instead of an O(queries) re-clone artifact.
//
// KEY STABILITY: only projection variants whose payload is a STABLE MIR identifier are
// encoded (`Field`/`Downcast` indices, the `Index` LOCAL — the resolved TYPE of an
// index step does not depend on the runtime index value — and `ConstantIndex`/
// `Subslice` offsets, `Deref`). `OpaqueCast`/`UnwrapUnsafeBinder` embed an inline
// replacement `Ty`, and `Projection` is `#[non_exhaustive]`; paths containing them —
// or any future variant — take the UNCACHED path (`key_for` returns `None`), so an
// unencodable projection can never alias a cached entry.
//
// SOUNDNESS: pure memoization of a deterministic function — a HIT replays the
// byte-identical `Ty`/`Sort` the first query computed, so every downstream VC is
// unchanged. The memo is inert outside a `gen_work` scope (out-of-scope calls behave
// byte-identically to baseline), is cleared on every outermost scope entry AND exit,
// and entries are bound to a function identity (address + locals buffer + name) that a
// query for any OTHER function fails, so a stale entry cannot survive into another
// function's generation. Degraded (post-trip) leaves are NEVER stored: on a trip the
// callers return before the store, so the cache only ever holds real resolved values.
//
// METER FIDELITY FOR THE PATHOLOGICAL SHAPES: a resolved tree over
// `MAX_MEMOIZED_TY_NODES` is never cached, and a kernel-scale fat local
// (`Expr`/`ExprKind`/`Name`, ~10^5+ nodes) trips `charge_local_once` on its FIRST
// touch (its declared-type node count alone crosses the budget), degrading the
// function exactly as before. A HIT's real (uncharged) work is bounded by one
// ≤`MAX_MEMOIZED_TY_NODES` clone, and the hard wall-clock watchdog remains the
// fail-closed backstop on total time. Retained memory is bounded too: every entry is
// ≤`MAX_MEMOIZED_TY_NODES` nodes, entries are keyed by the function's finitely many
// `(local, projection-path)` places, and the memo is cleared on every outermost
// scope boundary.
mod place_memo {
    use std::cell::RefCell;
    use std::collections::HashMap;

    use super::{Place, Projection, Sort, Ty, VerifiableFunction};

    /// Work-meter charge for a memo HIT: the real cost of a hit is a hash lookup plus a
    /// bounded (≤ `MAX_MEMOIZED_TY_NODES`) clone, not a full resolve + materialize.
    pub(super) const HIT_COST: usize = 1;

    /// Largest resolved tree (structural `Ty` nodes, as counted by
    /// `gen_work_datatype_nodes`) the memo will hold. Sized comfortably above the
    /// moderate flattened-ADT trees the memo exists for (~50-300 nodes) and far below
    /// the kernel-scale recursive-`Expr` trees the work meter exists for, so those
    /// stay uncached and keep tripping the budget on their first
    /// `charge_local_once` touch. Also bounds a HIT's real (uncharged) clone work.
    /// `pub(super)` so the store callers can count the resolved tree against
    /// `cap = MAX_MEMOIZED_TY_NODES + 1`: a cap-truncated count exceeds the bound and
    /// is refused by `store_ty`/`store_sort`, so a STORED `nodes` is always the TRUE
    /// tree size.
    pub(super) const MAX_MEMOIZED_TY_NODES: usize = 4_096;

    /// `(local, encoded projection path)` — see `key_for`.
    pub(super) type Key = (usize, Vec<u64>);

    struct State {
        /// Identity of the function the entries were computed for: the function's
        /// address, its locals buffer's address + length, and its name (owned Strings /
        /// integers only — no stale pointer is ever dereferenced). A query for a
        /// non-matching function misses (lookup) or rebinds-and-clears (store);
        /// combined with the clear-on-scope-boundary hooks, reusing an entry across
        /// functions would need an in-scope allocator address reuse AND a name
        /// collision — and the VC-gen scope only queries functions it holds borrowed
        /// for the whole pass.
        func_ptr: usize,
        locals_ptr: usize,
        locals_len: usize,
        func_name: String,
        tys: HashMap<Key, Ty>,
        sorts: HashMap<Key, Sort>,
    }

    impl State {
        fn is_for(&self, func: &VerifiableFunction) -> bool {
            let (func_ptr, locals_ptr, locals_len) = identity(func);
            self.func_ptr == func_ptr
                && self.locals_ptr == locals_ptr
                && self.locals_len == locals_len
                && self.func_name == func.name
        }
    }

    thread_local! {
        static MEMO: RefCell<Option<State>> = const { RefCell::new(None) };
    }

    fn identity(func: &VerifiableFunction) -> (usize, usize, usize) {
        (
            std::ptr::from_ref(func) as usize,
            func.body.locals.as_ptr() as usize,
            func.body.locals.len(),
        )
    }

    /// Clear the memo. Called by `gen_work` on every outermost scope entry AND exit so
    /// entries can never leak across functions (or linger while no VC-gen runs).
    pub(super) fn reset() {
        MEMO.with(|m| *m.borrow_mut() = None);
    }

    /// The memo key for `place`, or `None` when the place must take the UNCACHED path:
    /// outside a `gen_work` scope (the memo is inert there, matching the meter), or
    /// when the projection path contains a variant that embeds an inline `Ty`
    /// (`OpaqueCast`/`UnwrapUnsafeBinder`) or is unknown (`Projection` is
    /// `#[non_exhaustive]`). Each encoded variant has a distinct tag and a fixed
    /// payload arity, so the encoding is injective (a prefix code) — distinct
    /// projection paths can never collide on one key.
    pub(super) fn key_for(place: &Place) -> Option<Key> {
        if !super::gen_work::scope_active() {
            return None;
        }
        let mut path = Vec::with_capacity(place.projections.len() * 2);
        for proj in &place.projections {
            match proj {
                Projection::Deref => path.push(0),
                Projection::Field(i) => path.extend([1, *i as u64]),
                Projection::Index(local) => path.extend([2, *local as u64]),
                Projection::Downcast(v) => path.extend([3, *v as u64]),
                Projection::ConstantIndex { offset, min_length, from_end } => {
                    path.extend([4, *offset as u64, *min_length as u64, u64::from(*from_end)]);
                }
                Projection::Subslice { from, to, from_end } => {
                    path.extend([5, *from as u64, *to as u64, u64::from(*from_end)]);
                }
                // `OpaqueCast`/`UnwrapUnsafeBinder` embed an inline replacement `Ty`;
                // any future variant is unknown here. Fail to the UNCACHED path.
                _ => return None,
            }
        }
        Some((place.local, path))
    }

    pub(super) fn lookup_ty(func: &VerifiableFunction, key: &Key) -> Option<Ty> {
        MEMO.with(|m| {
            let memo = m.borrow();
            let state = memo.as_ref()?;
            if !state.is_for(func) {
                return None;
            }
            state.tys.get(key).cloned()
        })
    }

    pub(super) fn lookup_sort(func: &VerifiableFunction, key: &Key) -> Option<Sort> {
        MEMO.with(|m| {
            let memo = m.borrow();
            let state = memo.as_ref()?;
            if !state.is_for(func) {
                return None;
            }
            state.sorts.get(key).cloned()
        })
    }

    /// Store a resolved place type. `nodes` is the resolved tree's node count as
    /// counted by `gen_work_datatype_nodes` with `cap = MAX_MEMOIZED_TY_NODES + 1`
    /// (see the const doc): a cap-truncated count exceeds the bound and is refused
    /// below — so a STORED `nodes` is always the TRUE tree size, and the
    /// `MAX_MEMOIZED_TY_NODES` comparison is exact.
    pub(super) fn store_ty(func: &VerifiableFunction, key: Key, ty: &Ty, nodes: usize) {
        if nodes > MAX_MEMOIZED_TY_NODES || !super::gen_work::scope_active() {
            return;
        }
        MEMO.with(|m| {
            let mut memo = m.borrow_mut();
            bind(&mut memo, func).tys.insert(key, ty.clone());
        });
    }

    /// Store a resolved declared-type `Sort`. `nodes` is the resolved `Ty`'s node
    /// count (counted against `cap = MAX_MEMOIZED_TY_NODES + 1`); see `store_ty` for
    /// why it is always exact.
    pub(super) fn store_sort(func: &VerifiableFunction, key: Key, sort: &Sort, nodes: usize) {
        if nodes > MAX_MEMOIZED_TY_NODES || !super::gen_work::scope_active() {
            return;
        }
        MEMO.with(|m| {
            let mut memo = m.borrow_mut();
            bind(&mut memo, func).sorts.insert(key, sort.clone());
        });
    }

    /// The memo state bound to `func`, clearing and rebinding first if it was bound to
    /// a different function (or to nothing).
    fn bind<'a>(memo: &'a mut Option<State>, func: &VerifiableFunction) -> &'a mut State {
        let rebind = !memo.as_ref().is_some_and(|state| state.is_for(func));
        if rebind {
            let (func_ptr, locals_ptr, locals_len) = identity(func);
            *memo = Some(State {
                func_ptr,
                locals_ptr,
                locals_len,
                func_name: func.name.clone(),
                tys: HashMap::new(),
                sorts: HashMap::new(),
            });
        }
        memo.as_mut().expect("state was just bound")
    }
}

