/// Count the TOTAL structural `Ty` nodes reachable from `ty` — every constructor AND its
/// nested children — short-circuiting once `cap` is reached so a huge tree costs O(cap),
/// not O(size). This is the TRUE per-materialization clone cost the generation walk pays
/// at each owned `place_ty`/`place_sort` query: `Ty::clone()` (and `sort_for_ty`)
/// deep-copies the WHOLE tree.
///
/// IMPORTANT: the kernel's recursive `Expr`/`ExprKind`/`Name`/`Environment` lower to
/// deeply-nested **`Ty::Adt`** trees (flattened enums: `{Adt expr::Expr { fields:[(kind,
/// Adt ExprKind {…}), …]}}`), so the `Ty::Adt` arm is the dominant cost. Both the
/// struct/union `fields` view AND each enum `variants[].fields` list are deep-copied by
/// `Ty::clone`, so both are counted here to faithfully reflect the materialization cost.
fn gen_work_datatype_nodes(ty: &Ty, cap: usize) -> usize {
    fn go(ty: &Ty, cap: usize, acc: &mut usize) {
        if *acc >= cap {
            return;
        }
        *acc += 1;
        match ty {
            Ty::Ref { inner, .. } => go(inner, cap, acc),
            Ty::RawPtr { pointee, .. } => go(pointee, cap, acc),
            Ty::Slice { elem } | Ty::Array { elem, .. } | Ty::SymArray { elem, .. } => {
                go(elem, cap, acc)
            }
            Ty::Tuple(tys) => tys.iter().for_each(|t| go(t, cap, acc)),
            Ty::Adt { fields, variants, .. } => {
                for (_, t) in fields {
                    go(t, cap, acc);
                }
                for v in variants {
                    for (_, t) in &v.fields {
                        go(t, cap, acc);
                    }
                }
            }
            // Lever A: charge a modeled datatype's variant-field nodes so the VC-gen
            // work meter still bounds a `Ty::Datatype` materialization (a by-name
            // ref is empty and costs just the `+1` leaf above).
            Ty::Datatype { variants, .. } => {
                for (_, fs) in variants {
                    for (_, t) in fs {
                        go(t, cap, acc);
                    }
                }
            }
            Ty::Closure { upvars, .. } | Ty::Coroutine { upvars, .. } => {
                upvars.iter().for_each(|t| go(t, cap, acc));
            }
            // Scalar leaves (Int/Bool/Float/…) count as the single `*acc += 1` above with
            // no descent — they are cheap but non-zero, so a function with thousands of
            // scalar place-queries still accrues bounded work.
            _ => {}
        }
    }
    let mut acc = 0;
    go(ty, cap, &mut acc);
    acc
}

/// The cheap fail-closed leaf returned by owned type materialization once the work
/// meter has tripped, so the rest of the (about-to-be-discarded) walk costs O(1) per
/// query instead of cloning the fat ADT tree. Identical in kind/detail shape to the
/// existing recursive-ADT marker
/// (`collect_type_unsupported`'s `kind == "TyKind::Adt" && detail.starts_with("recursive")`
/// arm), so even if a downstream consumer inspects it, it fails closed exactly as a
/// genuinely recursive ADT would.
fn gen_work_degraded_leaf() -> Ty {
    Ty::Unsupported {
        kind: "TyKind::Adt".to_string(),
        detail: "recursive ADT (degraded: function exceeded VC-generation work budget)".to_string(),
    }
}

// ── verifier-perf: fat-`Ty::Adt` budget for the NON-VC-gen bundle path ──────
//
// The mid-generation work-bound above bounds trust-vcgen's VC-GENERATION walk. But the
// full-verification path also constructs a native trust-ir bundle
// (`trust_verify::build_full_verification_input` → `function_to_verifier_api_bundle` /
// `trust_ir_bridge::lower`) that recursively walks the UN-degraded declared `Ty::Adt`
// tree with many O(datatype-size) walks. For the kernel's `Expr`/`ExprKind`/`Name`
// cluster (a 464 MB serialized recursor type) those walks drive RSS to multi-GB and
// never complete — the `build_ind_app` stall — and the per-function wall-clock budget is
// enforced only at SMT dispatch, AFTER bundle construction, so it does not bound this.
//
// FIX: degrade an over-budget function's fat recursive `Ty::Adt` declared types to the
// existing recursive-ADT fail-closed marker `Ty::Unsupported { kind: "TyKind::Adt",
// detail: "recursive …" }` ONCE, up front, so the bundle builders see the cheap type.
// This introduces NO new type modeling: it degrades a fat `Ty::Adt` (which already
// exists on this branch) to the SAME `Ty::Unsupported` shape trust-mir-extract already
// produces for genuinely recursive ADTs — the load-bearing `detail.starts_with(
// "recursive")` shape `collect_type_unsupported` already skips on the declaration walk.
//
// SOUNDNESS (paramount): DROP-ONLY. Borrowed (no clone) for the in-budget common case —
// byte-identical to baseline. For an over-budget function the recursive types become the
// fail-closed recursive-ADT marker, so the bundle reverts to its sound, fail-closed
// verdict for THAT function: it can only LOSE a would-be proof (turn it Unknown), never
// manufacture a false PROVE and never a guaranteed-violation.

/// Per-function fat-ADT node budget for the bundle path. A function whose declared
/// local/return types exceed this many structural `Ty` nodes has its recursive `Ty::Adt`
/// types degraded to the fail-closed marker before bundle construction. Sized so an
/// ordinary function (small types) is never touched, while the pathological fat-recursor
/// cluster trips. The production value is deterministic because degradation changes the
/// fail-closed obligation inventory.
const MAX_BUNDLE_ADT_BUDGET: usize = 2_000_000;

#[cfg(test)]
thread_local! {
    static TEST_BUNDLE_ADT_BUDGET: std::cell::Cell<Option<usize>> = const {
        std::cell::Cell::new(None)
    };
}

/// The deterministic bundle-path fat-ADT node budget.
fn bundle_adt_budget() -> usize {
    #[cfg(test)]
    if let Some(budget) = TEST_BUNDLE_ADT_BUDGET.with(std::cell::Cell::get) {
        return if budget == 0 { usize::MAX } else { budget };
    }
    MAX_BUNDLE_ADT_BUDGET
}

#[cfg(test)]
pub(crate) fn set_bundle_adt_test_budget(budget: Option<usize>) {
    TEST_BUNDLE_ADT_BUDGET.with(|slot| slot.set(budget));
}

/// Total structural-`Ty`-node cost of `func`'s declared local + return types,
/// short-circuited at `cap` so an enormous function costs O(cap), not O(size).
fn func_adt_cost(func: &VerifiableFunction, cap: usize) -> usize {
    let mut total = 0usize;
    for decl in &func.body.locals {
        total += gen_work_datatype_nodes(&decl.ty, cap.saturating_sub(total));
        if total >= cap {
            return total;
        }
    }
    total += gen_work_datatype_nodes(&func.body.return_ty, cap.saturating_sub(total));
    total
}

/// Recursively replace every fat recursive `Ty::Adt` in `ty` with the fail-closed
/// recursive-ADT marker `Ty::Unsupported { kind: "TyKind::Adt", detail: "recursive …" }`.
/// The `"recursive"` detail prefix is load-bearing: it is the exact shape
/// `collect_type_unsupported` skips on the *declaration* walk (a recursive ADT value
/// carries no obligation) while still failing closed on any *use* — i.e. byte-identical
/// to what trust-mir-extract produces for genuinely recursive ADTs. All non-ADT
/// structure is preserved.
fn degrade_fat_adts(ty: &mut Ty) {
    match ty {
        Ty::Adt { .. } => {
            *ty = Ty::Unsupported {
                kind: "TyKind::Adt".to_string(),
                detail: "recursive ADT (degraded: over per-function bundle ADT budget)".to_string(),
            };
        }
        Ty::Ref { inner, .. } => degrade_fat_adts(inner),
        Ty::RawPtr { pointee, .. } => degrade_fat_adts(pointee),
        Ty::Slice { elem } | Ty::Array { elem, .. } | Ty::SymArray { elem, .. } => {
            degrade_fat_adts(elem)
        }
        Ty::Tuple(tys) => tys.iter_mut().for_each(degrade_fat_adts),
        Ty::Closure { upvars, .. } | Ty::Coroutine { upvars, .. } => {
            upvars.iter_mut().for_each(degrade_fat_adts);
        }
        _ => {}
    }
}

/// verifier-perf: enforce the per-function fat-`Ty::Adt` bundle budget. Returns the
/// function unchanged (BORROWED) when its declared-type node cost is within budget — the
/// overwhelmingly common case, so no allocation. When the cost exceeds the budget,
/// returns an OWNED clone whose every recursive `Ty::Adt` (in declared local/return
/// types) is degraded to the fail-closed recursive-ADT `Unsupported` marker, so the
/// bundle builders process that single function's cheap, fail-closed type in bounded
/// time/memory.
///
/// Call this once at the entry of the bundle-construction path, before any
/// O(datatype-size) walk, so the degrade is seen uniformly by every builder.
///
/// SOUNDNESS: DROP-ONLY (see the block comment above). Borrowed in-budget = baseline;
/// over-budget = fail-closed Unknown for that one function. Never a false PROVE.
#[must_use]
pub fn enforce_datatype_budget(
    func: &VerifiableFunction,
) -> std::borrow::Cow<'_, VerifiableFunction> {
    let cap = bundle_adt_budget();
    if cap == usize::MAX {
        return std::borrow::Cow::Borrowed(func);
    }
    // +1 so a cost that exactly hits the cap is still distinguished from "over";
    // short-circuited so an enormous function costs O(cap), not O(size).
    let cost = func_adt_cost(func, cap.saturating_add(1));
    if cost <= cap {
        return std::borrow::Cow::Borrowed(func);
    }
    if std::env::var("TRUST_VCGEN_TRACE_BUDGET").is_ok() {
        eprintln!(
            "[BUNDLE_ADT_BUDGET] degraded {} adt_node_cost>={cost} cap={cap} (reverted to fail-closed recursive-ADT Unsupported)",
            func.name,
        );
    }
    let mut owned = func.clone();
    for decl in &mut owned.body.locals {
        degrade_fat_adts(&mut decl.ty);
    }
    degrade_fat_adts(&mut owned.body.return_ty);
    std::borrow::Cow::Owned(owned)
}

/// Borrow a local's declared type WITHOUT cloning (and without metering — the meter
/// charges materialization, and a borrow materializes nothing). The borrow is valid for
/// the function's whole VC-gen pass (`func.body.locals[].ty` is owned and immutable
/// during generation), so any caller that only inspects/projects the type should use
/// this instead of materializing it through `place_ty` to avoid deep-cloning the fat
/// recursive-ADT root.
pub(crate) fn local_ty_ref(func: &VerifiableFunction, local: usize) -> Option<&Ty> {
    func.body.locals.iter().find(|decl| decl.index == local).map(|decl| &decl.ty)
}

pub(crate) fn sort_for_ty(ty: &Ty) -> Sort {
    match ty {
        Ty::Bool => Sort::Bool,
        // Source-level integer VCs use mathematical Ints unless a preserved
        // symbolic payload supplies a stricter machine sort.
        Ty::Int { .. } => Sort::Int,
        _ => Sort::from_ty(ty),
    }
}

pub(crate) fn operand_sort(func: &VerifiableFunction, op: &Operand) -> Option<Sort> {
    match op {
        Operand::Copy(place) | Operand::Move(place) => place_sort(func, place),
        Operand::Constant(cv) => Some(match cv {
            ConstValue::Bool(_) => Sort::Bool,
            ConstValue::Int(_) | ConstValue::Uint(_, _) => Sort::Int,
            ConstValue::Float(_) => Sort::BitVec(64),
            ConstValue::FloatBits { width, .. } => Sort::BitVec(*width),
            ConstValue::Unit | ConstValue::CallableItem { .. } => Sort::Int,
            // A typed opaque integer constant has integer sort (matching the
            // Int/Uint arms above, which also map to the Int theory). Its value is a
            // fresh unconstrained symbol.
            ConstValue::OpaqueScalar { .. } => Sort::Int,
            // Trust: piece #7a — a const-generic PARAM value has integer sort,
            // identical to `OpaqueScalar`; its identity lives in the symbol name.
            // Exception: a BOOL const-generic (in-band `width==1 && !signed`,
            // see `operand_ty`) is Bool-sorted end-to-end.
            ConstValue::ConstParam { width: 1, signed: false, .. } => Sort::Bool,
            ConstValue::ConstParam { .. } => Sort::Int,
            _ => return None,
        }),
        Operand::Symbolic(formula) => formula_sort(formula),
        Operand::Unsupported { .. } => None,
        _ => None,
    }
}

pub(crate) fn place_sort(func: &VerifiableFunction, place: &Place) -> Option<Sort> {
    // Trust: the BARE array local of an array-theory-eligible array has the SMT
    // Array sort (Int -> elem). Element *reads* keep their scalar sort (they are
    // `Select` results), so this only fires for the whole-array term itself.
    if place.projections.is_empty()
        && let Some(model) = array_theory_local(func, place.local)
    {
        return Some(Sort::Array(Box::new(Sort::Int), Box::new(model.elem_sort)));
    }
    symbolic_assignment_sort_for_place(func, place)
        .or_else(|| place_sort_from_declared_type(func, place))
        .or_else(|| place_ty(func, place).map(|ty| sort_for_ty(&ty)))
}

fn place_sort_from_declared_type(func: &VerifiableFunction, place: &Place) -> Option<Sort> {
    let base_ty = local_ty_ref(func, place.local)?;
    // Charge the BASE local's declared-type materialization ONCE per scope (every projected
    // subtree below is `<=` it). Degrade to the cheap `Sort::Int` on trip.
    if gen_work::charge_local_once(func.body.locals.as_ptr() as usize, place.local, |cap| {
        gen_work_datatype_nodes(base_ty, cap)
    }) {
        return Some(Sort::Int);
    }
    // verifier-perf (place-Sort memo, see `place_memo` and the meter comment below):
    // the declared-type Sort is deterministic in `(func, place)` for the whole VC-gen
    // pass, so a repeat query replays the memoized Sort for a `HIT_COST` charge instead
    // of re-walking the projections and re-building the fat `Sort` tree. The meter
    // charge is the peak `charge_local_once` above (which covers every projected
    // subtree), so the memo is pure CPU reuse here; nothing is looked up or stored
    // once tripped.
    let memo_key = if gen_work::is_tripped() { None } else { place_memo::key_for(place) };
    if let Some(key) = &memo_key
        && let Some(cached) = place_memo::lookup_sort(func, key)
    {
        if gen_work::record(place_memo::HIT_COST) {
            return Some(Sort::Int);
        }
        return Some(cached);
    }

    let mut ty = base_ty;
    let mut pending_variant: Option<usize> = None;

    for proj in &place.projections {
        match proj {
            Projection::Downcast(v) => {
                pending_variant = Some(*v);
            }
            Projection::Field(idx) => {
                if let (Some(v), Ty::Adt { fields, .. }) = (pending_variant, ty) {
                    pending_variant = None;
                    let prefix = format!("__v{v}_");
                    ty = fields
                        .iter()
                        .filter(|(name, _)| name.starts_with(&prefix))
                        .nth(*idx)
                        .map(|(_, field_ty)| field_ty)?;
                } else if let Ty::Datatype { variants, .. } = ty {
                    // Lever A: a `Field` after a `Downcast(v)` selects variant v's
                    // i-th field; a bare `Field` on a single-variant (struct-like)
                    // datatype selects variant 0's i-th field. A multi-variant
                    // datatype with no preceding downcast is ambiguous — fail closed
                    // (None), exactly as the `Ty::Adt` path does. Resolving the
                    // datatype field gives it a concrete `Sort::from_ty`-modeled
                    // sort, so `place_sort` no longer returns None and the place
                    // stops false-stamping `TrustSymbolicAggregateFieldSortMissing`.
                    let v = match pending_variant.take() {
                        Some(v) => v,
                        None if variants.len() == 1 => 0,
                        None => return None,
                    };
                    ty = variants.get(v).and_then(|(_, fs)| fs.get(*idx)).map(|(_, t)| t)?;
                } else {
                    pending_variant = None;
                    ty = project_ty_ref(ty, proj)?;
                }
            }
            _ => {
                pending_variant = None;
                ty = project_ty_ref(ty, proj)?;
            }
        }
    }

    // verifier-perf mid-generation work-bound: this is the OTHER O(datatype-size) hot
    // path the generation walk hammers — `sort_for_ty` builds a fresh `Sort` mirroring
    // the modeled type, and `place_sort` is called O(places × statements) times (it does
    // NOT clone the `Ty`, so it bypasses `place_ty`'s meter). Meter the resolved type's
    // node cost here too; once the per-function budget trips, return the cheap
    // fail-closed `Sort::Int` instead of building the fat `Sort`. The whole function is
    // discarded on trip, so this never reaches a verdict.
    //
    // SOUNDNESS: DROP-ONLY — a tripped function is degraded wholesale to Unknown, never
    // Proved; inert outside a VC-gen scope.
    if gen_work::is_tripped() {
        return Some(Sort::Int);
    }
    let sort = sort_for_ty(ty);
    if let Some(key) = memo_key {
        // The store bound needs the TRUE tree size. Count it against the memo cap (the
        // meter charge here is the peak `charge_local_once` at the top, not a per-call
        // record): a cap-truncated count exceeds `MAX_MEMOIZED_TY_NODES`, so
        // `store_sort` refuses it and an oversized tree is never cached.
        let nodes =
            gen_work_datatype_nodes(ty, place_memo::MAX_MEMOIZED_TY_NODES.saturating_add(1));
        place_memo::store_sort(func, key, &sort, nodes);
    }
    Some(sort)
}

fn project_ty_ref<'a>(ty: &'a Ty, proj: &'a Projection) -> Option<&'a Ty> {
    match proj {
        Projection::Downcast(_) => Some(ty),
        Projection::OpaqueCast(ty) | Projection::UnwrapUnsafeBinder(ty) => Some(ty),
        Projection::Field(idx) => match ty {
            Ty::Tuple(fields) => fields.get(*idx),
            Ty::Adt { fields, .. } => fields.get(*idx).map(|(_, field_ty)| field_ty),
            Ty::Closure { upvars, .. } => upvars.get(*idx),
            // Lever A: a bare `Field` on a single-variant (struct-like) datatype
            // selects variant 0's i-th field. A multi-variant datatype reached
            // without a `Downcast` is ambiguous here (the downcast-aware resolution
            // lives in `place_sort_from_declared_type`/`place_ty`); fail closed.
            Ty::Datatype { variants, .. } if variants.len() == 1 => {
                variants[0].1.get(*idx).map(|(_, field_ty)| field_ty)
            }
            _ => None,
        },
        Projection::Deref => match ty {
            Ty::Ref { inner, .. } => Some(inner),
            Ty::RawPtr { pointee, .. } => Some(pointee),
            _ => None,
        },
        Projection::Index(_) | Projection::ConstantIndex { .. } => match ty {
            // Trust: piece #7a — indexing a const-generic array steps to its
            // element type, exactly like a concrete `[T; N]`.
            Ty::Array { elem, .. } | Ty::Slice { elem } | Ty::SymArray { elem, .. } => Some(elem),
            _ => None,
        },
        // Subslice changes array length/slice extent. `place_ty` still handles
        // that owned synthetic type; fall back there instead of guessing here.
        Projection::Subslice { .. } => None,
        _ => None,
    }
}

/// verifier-perf: borrowed-first projection step for `place_ty`'s walk.
///
/// Identical RESULT to `project_ty(ty.clone(), proj)` (same obligations downstream),
/// but BORROWS the field/deref/index subtree instead of deep-cloning the whole `Ty`.
/// Only the two arms that genuinely SYNTHESIZE a new type allocate:
///   * `Subslice` rebuilds an `Array`/`Slice` with a new length, and
///   * `OpaqueCast`/`UnwrapUnsafeBinder` carry an inline replacement `Ty`,
/// so those return `Cow::Owned`; everything else returns `Cow::Borrowed`. This is the
/// load-bearing efficiency change: the kernel's fat recursive-`Ty::Adt` declared types
/// (`Expr`/`ExprKind`/`Name`) are walked by REFERENCE, and only the (small) resolved
/// field/element is ever cloned — not the multi-MB root tree, once per query.
///
/// SOUNDNESS: pure efficiency. The borrowed subtree is structurally identical to what
/// `project_ty` would have cloned (`Ty` is immutable during VC-gen), so the resolved
/// type — and therefore every VC the resolved type feeds — is byte-identical.
fn project_ty_cow<'a>(ty: &'a Ty, proj: &Projection) -> Option<std::borrow::Cow<'a, Ty>> {
    use std::borrow::Cow;
    match proj {
        Projection::Downcast(_) => Some(Cow::Borrowed(ty)),
        // These carry an inline replacement `Ty` in the projection itself; it is not a
        // subtree of `ty`, so it must be owned (matching `project_ty`'s `ty.clone()`).
        Projection::OpaqueCast(t) | Projection::UnwrapUnsafeBinder(t) => {
            Some(Cow::Owned(t.clone()))
        }
        Projection::Field(idx) => match ty {
            Ty::Tuple(fields) => fields.get(*idx).map(Cow::Borrowed),
            Ty::Adt { fields, .. } => fields.get(*idx).map(|(_, field_ty)| Cow::Borrowed(field_ty)),
            Ty::Closure { upvars, .. } => upvars.get(*idx).map(Cow::Borrowed),
            Ty::Datatype { variants, .. } if variants.len() == 1 => {
                variants[0].1.get(*idx).map(|(_, field_ty)| Cow::Borrowed(field_ty))
            }
            _ => None,
        },
        Projection::Deref => match ty {
            Ty::Ref { inner, .. } => Some(Cow::Borrowed(inner)),
            Ty::RawPtr { pointee, .. } => Some(Cow::Borrowed(pointee)),
            _ => None,
        },
        Projection::Index(_) | Projection::ConstantIndex { .. } => match ty {
            // Trust: piece #7a — indexing a const-generic array steps to its
            // element type, exactly like a concrete `[T; N]`.
            Ty::Array { elem, .. } | Ty::Slice { elem } | Ty::SymArray { elem, .. } => {
                Some(Cow::Borrowed(elem))
            }
            _ => None,
        },
        // Subslice SYNTHESIZES a new `Array`/`Slice` (new length / re-borrowed elem) —
        // the one arm that must allocate. The element subtree is still borrowed-then-
        // cloned exactly once, never the parent.
        Projection::Subslice { from, to, from_end } => match ty {
            Ty::Array { elem, len } => {
                let result_len = if *from_end {
                    len.checked_sub(*from as u64)?.checked_sub(*to as u64)?
                } else {
                    if to < from || *to as u64 > *len {
                        return None;
                    }
                    (to - from) as u64
                };
                Some(Cow::Owned(Ty::Array { elem: elem.clone(), len: result_len }))
            }
            Ty::Slice { elem } => Some(Cow::Owned(Ty::Slice { elem: elem.clone() })),
            _ => None,
        },
        _ => None,
    }
}

fn symbolic_assignment_sort_for_place(func: &VerifiableFunction, query: &Place) -> Option<Sort> {
    let mut found = None;

    for block in &func.body.blocks {
        for stmt in &block.stmts {
            let Statement::Assign { place, rvalue, .. } = stmt else {
                continue;
            };
            let Some(sort) = symbolic_assignment_sort_for_query(place, rvalue, query) else {
                continue;
            };
            if found.as_ref().is_some_and(|existing| existing != &sort) {
                return None;
            }
            found = Some(sort);
        }
    }

    found
}

fn symbolic_assignment_sort_for_query(
    place: &Place,
    rvalue: &Rvalue,
    query: &Place,
) -> Option<Sort> {
    if place == query {
        match rvalue {
            Rvalue::Use(Operand::Symbolic(formula)) => return formula_sort(formula),
            Rvalue::Cast(Operand::Symbolic(_), to_ty) => return Some(sort_for_ty(to_ty)),
            _ => {}
        }
    }

    let Rvalue::Aggregate(kind, operands) = rvalue else {
        return None;
    };
    operands.iter().enumerate().find_map(|(index, operand)| {
        let field_place = aggregate_field_place(place, kind, index, operands.len())?;
        if &field_place != query {
            return None;
        }
        match operand {
            Operand::Symbolic(formula) => formula_sort(formula),
            _ => None,
        }
    })
}

pub(crate) fn aggregate_field_place(
    place: &Place,
    kind: &AggregateKind,
    index: usize,
    field_count: usize,
) -> Option<Place> {
    let projection = match kind {
        AggregateKind::Tuple
        | AggregateKind::Adt { active_field: None, .. }
        | AggregateKind::Closure { .. } => Projection::Field(index),
        AggregateKind::Array => {
            Projection::ConstantIndex { offset: index, min_length: field_count, from_end: false }
        }
        _ => return None,
    };

    let mut field_place = place.clone();
    field_place.projections.push(projection);
    Some(field_place)
}

// Trust: enum-variant payload place for an ADT aggregate, projected through a
// `Downcast(variant)` so it matches how a `match`-arm payload READ is named. A
// MIR enum-payload read is `((o as Some).0)` → projection `[Downcast(1),
// Field(0)]` → `o@1.0`, whereas `aggregate_field_place` names the same write
// `o.0` (no downcast); the two never unify, leaving the variant payload write
// unconstrained (the solver was then free to pick an overflowing value). Emitting
// *both* names fixes that without needing to tell a struct (read `o.0`) from an
// enum (read `o@v.0`) — a distinction `AggregateKind::Adt` cannot express.
// Returns `None` for non-ADT and union (`active_field: Some`) aggregates, whose
// field reads do not go through a downcast.
pub(crate) fn aggregate_variant_field_place(
    place: &Place,
    kind: &AggregateKind,
    index: usize,
) -> Option<Place> {
    let AggregateKind::Adt { variant, active_field: None, .. } = kind else {
        return None;
    };
    let mut field_place = place.clone();
    field_place.projections.push(Projection::Downcast(*variant));
    field_place.projections.push(Projection::Field(index));
    Some(field_place)
}

pub(crate) fn is_thin_pointer_identity_cast(from_ty: &Ty, to_ty: &Ty) -> bool {
    is_thin_pointer_ty(from_ty) && is_thin_pointer_ty(to_ty)
}

pub(crate) fn is_callable_reification_cast(from_ty: &Ty, to_ty: &Ty) -> bool {
    match (from_ty, to_ty) {
        (Ty::Unit, Ty::FnPtr { .. }) => true,
        (Ty::FnDef { sig: from_sig, .. }, Ty::FnPtr { sig: to_sig }) => from_sig == to_sig,
        _ => false,
    }
}

pub(crate) fn is_fn_pointer_identity_cast(from_ty: &Ty, to_ty: &Ty) -> bool {
    matches!(
        (from_ty, to_ty),
        (Ty::FnPtr { sig: from_sig }, Ty::FnPtr { sig: to_sig }) if from_sig == to_sig
    )
}

/// `&[T; N] -> &[T]` unsize coercion: a reference to an array becomes a reference
/// to a slice of the same element type (`&str` is `&[u8]`-shaped here, so it is
/// covered too). The bridge lowers this precisely (the slice carries the array's
/// length); for VC generation it is a metadata-only coercion that introduces no
/// new arithmetic/bounds obligation, so it is a supported cast.
pub(crate) fn is_array_to_slice_ref_cast(from_ty: &Ty, to_ty: &Ty) -> bool {
    let pointee = |t: &Ty| match t {
        Ty::Ref { inner, .. } => Some((**inner).clone()),
        _ => None,
    };
    let (Some(from_p), Some(to_p)) = (pointee(from_ty), pointee(to_ty)) else {
        return false;
    };
    // Trust: piece #7a — a concrete `[T; N]` or const-generic `[T; _]` array unsizes
    // to a slice `[T]` the same metadata-only way; recognizing it suppresses a spurious
    // "unsupported cast" obligation. Compare the element type MODULO `disc_index_safe`
    // (a lowering REPRESENTATION artifact — the array-context and slice-context
    // spellings of the SAME element enum can differ only in that flag, so a plain `==`
    // false-rejected the coercion and left the cast an `unsupported_mir` coverage gap,
    // as `array_to_slice_pointer_cast` in trust-ir-bridge did before commit 79a7f91100).
    // Sound: introduces no new arithmetic/bounds fact (the slice length stays opaque);
    // a genuine element-type change still yields `false`.
    match (from_p, to_p) {
        (Ty::Array { elem: a, .. }, Ty::Slice { elem: b })
        | (Ty::SymArray { elem: a, .. }, Ty::Slice { elem: b }) => {
            a.eq_ignoring_disc_index_safe(&b)
        }
        _ => false,
    }
}

/// True when a cast TARGET is a reference (or raw pointer) to a slice (`&[T]` /
/// `*const [T]`; `&str` lowers to a `&[u8]`-shaped slice). `convert.rs` only emits
/// an `Rvalue::Cast` with such a target for a metadata-only array→slice unsize
/// coercion (trait objects go to `OpaqueConst`), which carries NO panic/overflow
/// obligation. The typed case is `is_array_to_slice_ref_cast`, but that fails when
/// the source lost its `&[T;N]` type — e.g. a promoted array constant (`let t:
/// &[T] = &[a,b,c]`) that lowered to `OpaqueConst` (Unit), or an array whose
/// element is itself a fat pointer. Accepting the cast by TARGET stays sound: the
/// slice length stays opaque (`push_borrow_slice_len` only asserts a length when
/// the source length is determinable), so no false fact is emitted.
pub(crate) fn cast_target_is_slice_ref(to_ty: &Ty) -> bool {
    let pointee = match to_ty {
        Ty::Ref { inner, .. } => inner,
        Ty::RawPtr { pointee, .. } => pointee,
        _ => return false,
    };
    matches!(**pointee, Ty::Slice { .. })
}

pub(crate) fn is_modeled_identity_cast(from_ty: &Ty, to_ty: &Ty) -> bool {
    if let (Ty::Int { width: fw, signed: fs }, Ty::Int { width: tw, signed: ts }) = (from_ty, to_ty)
    {
        // soundness (round-8): an int->int `as` cast is value-preserving
        // (and thus soundly modeled as identity `dest == source`) ONLY when it
        // cannot change the mathematical value for ANY input:
        //   - same width AND signedness (a pure no-op), or
        //   - a widening (tw > fw) that is NOT signed->unsigned (unsigned source
        //     zero-extends and fits; signed->signed sign-extends; signed->unsigned
        //     would wrap negatives, so it is excluded).
        // Narrowing (truncation mod 2^tw), same-width signedness reinterpret, and
        // signed->unsigned widening all change the value, so modeling them as
        // identity was a false-PROVE of properties over the casted value (e.g.
        // `(x as u8) as u32 == x`). Returning false routes them to the fail-closed
        // path (no value-fact in the v2 lowering; Err/unsupported in chc). Correct
        // modular/reinterpret modeling is a future completeness item.
        return (*fw == *tw && *fs == *ts) || (*tw > *fw && !(*fs && !*ts));
    }
    is_thin_pointer_identity_cast(from_ty, to_ty) || is_fn_pointer_identity_cast(from_ty, to_ty)
}

/// A numeric `as` cast that crosses the float boundary (`int -> float`,
/// `float -> int`, `float -> float`). Rust models these as infallible (no panic:
/// `float -> int` saturates since 1.45), so they carry NO safety obligation —
/// the only thing we cannot model precisely is the resulting *value* (IEEE-754
/// semantics over our BitVec float sort). Treat the destination as a fresh
/// unconstrained value rather than refusing the whole function: sound
/// over-approximation — value-dependent obligations stay `unknown`, never
/// falsely proved, but the function's other obligations are no longer poisoned.
pub(crate) fn is_float_numeric_cast(from_ty: &Ty, to_ty: &Ty) -> bool {
    matches!(from_ty, Ty::Float { .. }) || matches!(to_ty, Ty::Float { .. })
}

pub(crate) fn unsupported_cast_reason(from_ty: &Ty, to_ty: &Ty) -> String {
    if from_ty.is_fn_ptr() || to_ty.is_fn_ptr() {
        if let (Some(from_sig), Some(to_sig)) =
            (callable_signature(from_ty), callable_signature(to_ty))
            && from_sig != to_sig
        {
            return format!(
                "function pointer cast changes callable signature from {from_sig:?} to {to_sig:?}; signature-changing callable casts are not modeled"
            );
        }
        return "function pointer casts require callable address/provenance semantics; only opaque zero-capture reification and fn pointer identity casts are modeled"
            .to_string();
    }

    if from_ty.is_pointer_like() || to_ty.is_pointer_like() {
        if from_ty.is_pointer_like() && to_ty.is_pointer_like() {
            return "pointer cast changes or depends on fat-pointer metadata/provenance; only thin pointer-to-pointer identity casts are modeled"
                .to_string();
        }
        return "pointer/integer casts expose or recover provenance and require explicit pointer provenance semantics"
            .to_string();
    }

    "only bool-to-integer, integer-to-integer, and thin pointer-to-pointer identity cast semantics are modeled"
        .to_string()
}

fn callable_signature(ty: &Ty) -> Option<&trust_types::FnSig> {
    match ty {
        Ty::FnDef { sig, .. } | Ty::FnPtr { sig } => Some(sig),
        _ => None,
    }
}

pub(crate) fn callable_reification_token(dest_name: &str, sort: Sort) -> Formula {
    Formula::Var(format!("__trust_callable_reify_{dest_name}"), sort)
}

pub(crate) fn is_thin_pointer_ty(ty: &Ty) -> bool {
    match ty {
        Ty::Ref { inner, .. } | Ty::RawPtr { pointee: inner, .. } => is_thin_pointer_pointee(inner),
        // A single-pointer NEWTYPE struct (`Box`/`Unique`/`NonNull`) IS a thin
        // pointer: after stripping zero-sized pad fields (`PhantomData`/`Unit`) it
        // has exactly one non-pad field that recursively resolves to a thin
        // pointer. This lets the `vec!`/`Box` machinery's `*mut u8 -> Box` /
        // `NonNull -> *const` transmutes (lowered as `Rvalue::Cast`) be modeled as
        // value-preserving thin-pointer identity casts in the v2 SMT path, matching
        // the native trust-mc wrap/unwrap. Fail-closed for any non-newtype / fat
        // pointer (the address bits are preserved; pointee validity is separate).
        Ty::Adt { .. } => is_single_pointer_newtype_adt(ty, POINTER_NEWTYPE_FUEL),
        _ => false,
    }
}

const POINTER_NEWTYPE_FUEL: u32 = 8;

/// A zero-sized pad field (`PhantomData` lowers to an empty-field `Adt`; `Unit`)
/// — skipped when testing whether a struct is a single-pointer NEWTYPE.
fn is_zero_sized_newtype_pad(ty: &Ty, fuel: u32) -> bool {
    if fuel == 0 {
        return false;
    }
    match ty {
        Ty::Unit => true,
        Ty::Adt { fields, .. } => {
            fields.iter().all(|(_, f)| is_zero_sized_newtype_pad(f, fuel - 1))
        }
        _ => false,
    }
}

/// True iff `ty` is a single-pointer newtype struct: exactly one non-pad field
/// that (recursively) resolves to a thin pointer. Fail-closed for a multi-field
/// struct, an enum, or a fat-pointer leaf, so no value transmute is modeled as a
/// pointer identity cast.
fn is_single_pointer_newtype_adt(ty: &Ty, fuel: u32) -> bool {
    if fuel == 0 {
        return false;
    }
    let Ty::Adt { fields, .. } = ty else {
        return false;
    };
    let mut non_pad = fields.iter().map(|(_, f)| f).filter(|f| !is_zero_sized_newtype_pad(f, fuel));
    let Some(inner) = non_pad.next() else {
        return false;
    };
    if non_pad.next().is_some() {
        return false;
    }
    is_thin_pointer_ty(inner) || is_single_pointer_newtype_adt(inner, fuel - 1)
}

fn is_thin_pointer_pointee(ty: &Ty) -> bool {
    !matches!(
        ty,
        Ty::Slice { .. }
            | Ty::Str
            | Ty::Dynamic { .. }
            | Ty::Unsupported { .. }
    )
}

pub(crate) fn project_ty(ty: Ty, proj: &Projection) -> Option<Ty> {
    match proj {
        Projection::Downcast(_) => Some(ty),
        Projection::OpaqueCast(ty) | Projection::UnwrapUnsafeBinder(ty) => Some(ty.clone()),
        Projection::Field(idx) => match ty {
            Ty::Tuple(fields) => fields.get(*idx).cloned(),
            Ty::Adt { fields, .. } => fields.get(*idx).map(|(_, field_ty)| field_ty.clone()),
            Ty::Closure { upvars, .. } => upvars.get(*idx).cloned(),
            // Lever A: a bare `Field` on a single-variant (struct-like) datatype
            // selects variant 0's i-th field (multi-variant needs a `Downcast`,
            // handled by `place_ty`); fail closed otherwise.
            Ty::Datatype { variants, .. } if variants.len() == 1 => {
                variants[0].1.get(*idx).map(|(_, field_ty)| field_ty.clone())
            }
            _ => None,
        },
        Projection::Deref => match ty {
            Ty::Ref { inner, .. } => Some(*inner),
            Ty::RawPtr { pointee, .. } => Some(*pointee),
            _ => None,
        },
        Projection::Index(_) | Projection::ConstantIndex { .. } => match ty {
            // Trust: piece #7a — indexing a const-generic array steps to its
            // element type, exactly like a concrete `[T; N]`.
            Ty::Array { elem, .. } | Ty::Slice { elem } | Ty::SymArray { elem, .. } => Some(*elem),
            _ => None,
        },
        Projection::Subslice { from, to, from_end } => match ty {
            Ty::Array { elem, len } => {
                let result_len = if *from_end {
                    len.checked_sub(*from as u64)?.checked_sub(*to as u64)?
                } else {
                    if to < from || *to as u64 > len {
                        return None;
                    }
                    (to - from) as u64
                };
                Some(Ty::Array { elem, len: result_len })
            }
            Ty::Slice { elem } => Some(Ty::Slice { elem }),
            // Trust: piece #7a — a subslice of a const-generic array has an
            // unknown resulting length; fail closed rather than guess (this is
            // 7c/7d territory, not 7a). Sound: returns no synthetic type, so the
            // downstream length lookup fails and the range check fails-closed.
            _ => None,
        },
        _ => None,
    }
}

pub(crate) fn place_ty(func: &VerifiableFunction, place: &Place) -> Option<Ty> {
    // OWNED resolution: walk by reference (`place_ty_cow`), then materialize. The work
    // meter charges the RESOLVED type's node cost here (what `into_owned` clones), exactly
    // as before — so an OWNED query trips byte-identically to baseline. A borrowing caller
    // that only inspects the type should call `place_ty_cow` instead and pay no clone (and
    // no metering of a clone it never performs); see that function.
    //
    // verifier-perf (place-type memo, see `place_memo`): the resolved type is
    // deterministic in `(func, place)` for the whole VC-gen pass, so the FIRST owned
    // query per distinct place performs the full materialization — metered by the peak
    // `charge_local_once` below — and every repeat replays the memoized result for a
    // `HIT_COST` charge instead of re-performing the O(places × statements) re-clone
    // product that fail-closed moderate-typed functions.
    //
    // SOUNDNESS: pure efficiency. The resolved type is structurally identical to the old
    // owned walk (`Ty` is immutable during VC-gen; a memo HIT replays the identical
    // first-query result), so every downstream VC is byte-identical, and the meter still
    // bounds a pathological OWNED materialization (a budget-crossing local trips
    // `charge_local_once` on first touch; an over-`MAX_MEMOIZED_TY_NODES` tree is never
    // cached, with the wall-clock watchdog backstopping its uncached repeat queries).
    // On a trip the whole function is discarded (DROP-ONLY: Unknown, never Proved),
    // and nothing is stored.
    let memo_key = if gen_work::is_tripped() { None } else { place_memo::key_for(place) };
    if let Some(key) = &memo_key
        && let Some(cached) = place_memo::lookup_ty(func, key)
    {
        if gen_work::record(place_memo::HIT_COST) {
            return Some(gen_work_degraded_leaf());
        }
        return Some(cached);
    }
    let ty = place_ty_cow(func, place)?;
    // Charge the BASE local's declared-type materialization ONCE per scope (shared `CHARGED`
    // memo with `place_sort_from_declared_type`, so a local pays at most once total).
    // The resolved `ty` is a subtree of `decl_ty(local)` except for `place_ty_cow`'s synthetic
    // OpaqueCast/Subslice steps, which are themselves 8k-capped — a bounded under-count, and the
    // meter is drop-only, so never a false PROVE.
    if gen_work::charge_local_once(func.body.locals.as_ptr() as usize, place.local, |cap| {
        local_ty_ref(func, place.local).map_or(0, |t| gen_work_datatype_nodes(t, cap))
    }) {
        return Some(gen_work_degraded_leaf());
    }
    let ty = ty.into_owned();
    if let Some(key) = memo_key {
        // The store bound needs the TRUE tree size. Count it against the memo cap (the
        // meter charge here is the peak `charge_local_once` above, not a per-call
        // record): a cap-truncated count exceeds `MAX_MEMOIZED_TY_NODES`, so `store_ty`
        // refuses it and an oversized tree is never cached.
        let nodes =
            gen_work_datatype_nodes(&ty, place_memo::MAX_MEMOIZED_TY_NODES.saturating_add(1));
        place_memo::store_ty(func, key, &ty, nodes);
    }
    Some(ty)
}

/// Resolve a place's type as a `Cow<Ty>` — the borrowed core of `place_ty`. The declared
/// type is walked by REFERENCE and only the synthetic `Subslice`/`OpaqueCast`/variant-field
/// steps allocate (`step_place_ty_cow`), so the kernel's fat recursive-`Ty::Adt` declared
/// types (`Expr`/`ExprKind`/`Name`) are resolved WITHOUT ever cloning the multi-MB root.
///
/// This is the load-bearing memory-efficiency entry: a caller that only INSPECTS the
/// resolved type (`matches!`, `is_integer`, `int_width`, `sort_for_ty`, equality, …) must
/// use this instead of `place_ty` — it then never materializes the fat root and is never
/// charged the (never-performed) clone, so the function does not trip the VC-gen work
/// budget on a bare full-value read. A caller that needs an OWNED `Ty` (to store / mutate /
/// feed a `VcKind`) calls `place_ty` (or `.into_owned()` on this result), which meters the
/// materialized clone exactly as baseline.
///
/// SOUNDNESS: byte-identical RESULT to `place_ty` (`Ty` is immutable during VC-gen, so the
/// borrowed walk resolves the structurally-identical subtree the owned walk cloned). On a
/// tripped function it returns the same cheap fail-closed leaf `place_ty` would, so the
/// wholesale fail-closed degrade is preserved. DROP-ONLY, never a false-prove.
pub(crate) fn place_ty_cow<'a>(
    func: &'a VerifiableFunction,
    place: &Place,
) -> Option<std::borrow::Cow<'a, Ty>> {
    use std::borrow::Cow;
    // Once tripped, the function is about to be discarded — hand back the cheap fail-closed
    // leaf so the rest of the (doomed) walk costs O(1) per query, identical to `place_ty`.
    if gen_work::is_tripped() {
        return Some(Cow::Owned(gen_work_degraded_leaf()));
    }
    let mut ty: Cow<'a, Ty> = Cow::Borrowed(local_ty_ref(func, place.local)?);
    // a MIR `Field` after a `Downcast(v)` is *variant-relative* (the
    // i-th field of variant v). `lower_enum_adt` flattens an enum to fields
    // `[__tag, __v{v}_{f}, ...]`, so resolving such a `Field` with a flat lookup
    // returns the wrong slot — `Field(0)` lands on `__tag` (an Int) instead of
    // variant v's first payload. For a nested enum that makes the inner payload's
    // type resolve to the tag's Int, and a discriminant read on it false-fails as
    // InvalidDiscriminant. Track the pending downcast variant and select the
    // i-th `__v{v}_*` field instead.
    let mut pending_variant: Option<usize> = None;
    for proj in &place.projections {
        match proj {
            Projection::Downcast(v) => {
                // A downcast does not change the modeled type; it only records
                // which variant a following `Field` projection is relative to.
                pending_variant = Some(*v);
            }
            Projection::Field(idx) => {
                if let (Some(v), Ty::Adt { fields, .. }) = (pending_variant, ty.as_ref()) {
                    pending_variant = None;
                    let prefix = format!("__v{v}_");
                    let next = fields
                        .iter()
                        .filter(|(name, _)| name.starts_with(&prefix))
                        .nth(*idx)
                        .map(|(_, t)| t.clone())?;
                    ty = Cow::Owned(next);
                } else if let Ty::Datatype { variants, .. } = ty.as_ref() {
                    // Lever A: variant-relative datatype field. `Field` after a
                    // `Downcast(v)` selects variant v's i-th field; a bare `Field`
                    // on a single-variant datatype selects variant 0's; multi-variant
                    // without a downcast is ambiguous → fail closed.
                    let v = match pending_variant.take() {
                        Some(v) => v,
                        None if variants.len() == 1 => 0,
                        None => return None,
                    };
                    let next =
                        variants.get(v).and_then(|(_, fs)| fs.get(*idx)).map(|(_, t)| t.clone())?;
                    ty = Cow::Owned(next);
                } else {
                    pending_variant = None;
                    ty = step_place_ty_cow(ty, proj)?;
                }
            }
            _ => {
                pending_variant = None;
                ty = step_place_ty_cow(ty, proj)?;
            }
        }
    }
    Some(ty)
}

/// One projection step of `place_ty`'s borrowed walk. Threads a `Cow<'a, Ty>` so a
/// borrowed accumulator stays borrowed across borrowed steps (the fat-ADT win), and an
/// owned accumulator (after a synthetic `Subslice`/`OpaqueCast` step) clones the next
/// projection result to keep ownership. Byte-identical RESULT to `project_ty` on the
/// equivalent owned `Ty`.
pub(crate) fn step_place_ty_cow<'a>(
    ty: std::borrow::Cow<'a, Ty>,
    proj: &Projection,
) -> Option<std::borrow::Cow<'a, Ty>> {
    use std::borrow::Cow;
    match ty {
        // Still borrowing the function's declared type — project by reference; only the
        // synthetic arms allocate (see `project_ty_cow`), and the borrow keeps lifetime
        // `'a` (the function's), so subsequent borrowed steps stay clone-free.
        Cow::Borrowed(t) => project_ty_cow(t, proj),
        // Already owning a synthetic intermediate — its borrow cannot escape this frame,
        // so resolve against it and clone the (small) result to re-own.
        Cow::Owned(t) => project_ty_cow(&t, proj).map(|c| Cow::Owned(c.into_owned())),
    }
}

pub(crate) fn raw_ptr_aggregate_support_error(
    func: &VerifiableFunction,
    pointee_ty: &Ty,
    mutable: bool,
    operands: &[Operand],
) -> Option<String> {
    if operands.len() != 2 {
        return Some(format!(
            "raw pointer aggregate must have data pointer and metadata operands; got {} operands",
            operands.len()
        ));
    }

    if let Some(reason) = single_lane_raw_ptr_pointee_error(pointee_ty) {
        return Some(format!(
            "raw pointer aggregate for pointee {pointee_ty:?} requires fat-pointer metadata semantics: {reason}"
        ));
    }

    match operand_ty(func, &operands[0]) {
        Some(Ty::RawPtr { mutable: data_mutable, pointee }) => {
            if data_mutable != mutable {
                return Some(format!(
                    "raw pointer aggregate data pointer mutability {data_mutable} does not match aggregate mutability {mutable}"
                ));
            }
            if let Some(reason) = single_lane_raw_ptr_pointee_error(&pointee) {
                return Some(format!(
                    "raw pointer aggregate data operand must be a thin raw pointer; got {pointee:?}: {reason}"
                ));
            }
        }
        Some(other) => {
            return Some(format!(
                "raw pointer aggregate first operand must be a raw pointer; got {other:?}"
            ));
        }
        None => {
            return Some(
                "raw pointer aggregate first operand type is unknown; cannot prove it is a thin raw pointer"
                    .to_string(),
            );
        }
    }

    match operand_ty_cow(func, &operands[1]).as_deref() {
        Some(Ty::Unit) => None,
        Some(other) => {
            Some(format!("thin raw pointer aggregate metadata must be unit; got {other:?}"))
        }
        None => {
            Some("thin raw pointer aggregate metadata type is unknown; expected unit".to_string())
        }
    }
}

fn single_lane_raw_ptr_pointee_error(pointee_ty: &Ty) -> Option<String> {
    match pointee_ty {
        Ty::Slice { .. } => Some("slice pointers carry a length metadata lane".to_string()),
        Ty::Dynamic { .. } => {
            Some("trait-object pointers carry a vtable metadata lane".to_string())
        }
        Ty::Unsupported { kind, detail } => {
            Some(format!("pointee type {kind} is unsupported: {detail}"))
        }
        _ => None,
    }
}

pub(crate) fn place_has_raw_deref(func: &VerifiableFunction, place: &Place) -> bool {
    // verifier-perf: walk the declared type by REFERENCE (no fat-root clone) — this is a
    // pure structural inspection (does any deref hit a raw pointer?), never a move.
    use std::borrow::Cow;
    let Some(mut ty) = local_ty_ref(func, place.local).map(Cow::Borrowed) else {
        return false;
    };

    for proj in &place.projections {
        match proj {
            Projection::Deref => {
                if matches!(ty.as_ref(), Ty::RawPtr { .. }) {
                    return true;
                }
                // Borrow the pointee when the accumulator is still borrowed; clone only
                // if we are already on a synthetic owned intermediate. Non-ref => stop.
                ty = match ty {
                    Cow::Borrowed(Ty::Ref { inner, .. }) => Cow::Borrowed(inner),
                    Cow::Owned(Ty::Ref { inner, .. }) => Cow::Owned(*inner),
                    _ => return false,
                };
            }
            _ => {
                let Some(next_ty) = step_place_ty_cow(ty, proj) else {
                    return false;
                };
                ty = next_ty;
            }
        }
    }

    false
}

pub(crate) fn operand_has_raw_deref(func: &VerifiableFunction, operand: &Operand) -> bool {
    match operand {
        Operand::Copy(place) | Operand::Move(place) => place_has_raw_deref(func, place),
        _ => false,
    }
}

pub(crate) fn slice_len_formula(func: &VerifiableFunction, operand: &Operand) -> Option<Formula> {
    let place = match operand {
        Operand::Copy(place) | Operand::Move(place) => place,
        _ => return None,
    };

    // Trust: an `as_bytes()` result has EXACTLY the byte length of its receiver
    // (byte-length-preserving; `str` is modeled as `[u8]`), so resolve its length to
    // the receiver's OWN length var. This unifies an `!s.is_empty()` guard (length on
    // `s`) with an `s.as_bytes()[i]` index bound (length on the fresh `as_bytes`
    // result) — so guarded string indexing PROVES instead of over-refuting. SOUND +
    // fail-closed: the length transfers only when the receiver itself has a slice
    // length (see `guards::as_bytes_length_receiver`), and an UNguarded index still
    // refutes (the receiver's len var is unconstrained without the guard).
    if place.projections.is_empty() {
        if let Some(recv) = guards::as_bytes_length_receiver(func, place.local) {
            // The receiver is a slice/str (`slice_len_formula`) OR a SHARED owned
            // container (`&String`/`&Vec` — `String::as_bytes()` etc.); in both the
            // byte length equals the receiver's own length var, so an
            // `!s.is_empty()` guard discharges an `s.as_bytes()[i]` bound. The
            // owned-container fallback is SHARED-ref-gated (see
            // `guards::owned_container_len_var`) — a `&mut` receiver declines, so the
            // resize hazard stays refuted.
            return slice_len_formula(func, recv)
                .or_else(|| guards::owned_container_len_var(func, recv));
        }
    }

    match place_ty_cow(func, place)?.as_ref() {
        // A reference to a FIXED-SIZE array (`&[T; N]` / `&mut [T; N]`) has a
        // STATICALLY-KNOWN length `N` — the length is part of the type and is
        // immutable, exactly as for a bare `[T; N]`. So `&bytes[a..b]` /
        // `(&mut bytes)[a..b]` (the idiomatic `bytes[a..b].copy_from_slice(..)`
        // shape on a `let mut bytes = [0u8; N];`) resolves its bound to the constant
        // `N` and the `b <= N` range check PROVES, instead of hitting the
        // unmodeled-len fail-close (`Formula::Bool(true)`) the RangeIndex body emits
        // when no length is found — which a forced-violation escalation then wrongly
        // reports as a GUARANTEED out-of-bounds on provably in-bounds code.
        // SOUNDNESS: `N` is the EXACT array length (never an over-approximation), so
        // this can only PROVE a genuinely in-bounds index, never hide a real OOB (an
        // out-of-range constant `b > N` still folds the violation to true). GENERAL —
        // arrays, no datatype modeling. Placed before the `&[T]` (Slice) arm; the two
        // are disjoint (Array vs Slice inner), so ordering is precision-only.
        Ty::Ref { inner, .. } if matches!(inner.as_ref(), Ty::Array { .. }) => {
            match inner.as_ref() {
                Ty::Array { len, .. } => Some(Formula::Int(i128::from(*len))),
                _ => None,
            }
        }
        // Trust: piece #7a — a reference to a const-generic array (`&[T; N]`)
        // resolves its length to the SAME per-param symbol the bare array uses,
        // so a guard `i < N` on a `&[T; N]` range/index still discharges. Sound:
        // the const-param length is immutable, exactly like the concrete-`N` arm.
        Ty::Ref { inner, .. } if matches!(inner.as_ref(), Ty::SymArray { .. }) => {
            match inner.as_ref() {
                Ty::SymArray { len_sym, .. } => Some(sym_array_len_formula(len_sym)),
                _ => None,
            }
        }
        // A raw pointer to a fixed-size array (`*const [T; N]` / `*mut [T; N]`) is a
        // THIN pointer whose pointee length is the static `N` — same constant-length
        // resolution as `&[T; N]` above. Sound for the same reason.
        Ty::RawPtr { pointee, .. } if matches!(pointee.as_ref(), Ty::Array { .. }) => {
            match pointee.as_ref() {
                Ty::Array { len, .. } => Some(Formula::Int(i128::from(*len))),
                _ => None,
            }
        }
        // Trust: piece #7a — raw pointer to a const-generic array; same per-param
        // symbol as the `&[T; N]` arm.
        Ty::RawPtr { pointee, .. } if matches!(pointee.as_ref(), Ty::SymArray { .. }) => {
            match pointee.as_ref() {
                Ty::SymArray { len_sym, .. } => Some(sym_array_len_formula(len_sym)),
                _ => None,
            }
        }
        Ty::Ref { inner, .. } if matches!(inner.as_ref(), Ty::Slice { .. }) => Some(
            Formula::var_owned(format!("{}__slice_len", place_to_var_name(func, place)), Sort::Int),
        ),
        // A raw pointer to a slice (e.g. the `FakeForPtrMetadata` pointer that
        // `<[T]>::len()` reads on a `&mut [T]`) is a fat pointer whose metadata is
        // the slice length; its `__slice_len` var is tied to the referent slice's
        // length by the `AddressOf` block definition (guards.rs).
        Ty::RawPtr { pointee, .. } if matches!(pointee.as_ref(), Ty::Slice { .. }) => Some(
            Formula::var_owned(format!("{}__slice_len", place_to_var_name(func, place)), Sort::Int),
        ),
        Ty::Slice { .. } => Some(Formula::var_owned(
            format!("{}__slice_len", place_to_var_name(func, place)),
            Sort::Int,
        )),
        Ty::Array { len, .. } => Some(Formula::Int(i128::from(*len))),
        // Trust: piece #7a — a bare const-generic array `[T; N]` resolves its
        // length to the per-param symbol `__trust_constparam_{index}_{name}`,
        // the SAME symbol the const-generic value `N` lowers to. The bounds VC
        // `i >= N ∨ i < 0` is then SAT (REFUTED) with no guard, and UNSAT
        // (PROVED) under a guard `i < N`. SOUNDNESS: keyed on the param identity,
        // never on `(width, signed)`, so an index on `[T; M]` cannot be
        // discharged by a guard on a DIFFERENT param `N` (M != N -> distinct
        // symbols). See INV-1 in the piece #7a blueprint.
        Ty::SymArray { len_sym, .. } => Some(sym_array_len_formula(len_sym)),
        _ => None,
    }
}

/// Trust: piece #7a — the ONE canonical length formula for a const-generic
/// array, a fresh unconstrained `Sort::Int` var named on the param identity. It
/// deliberately does NOT end with `__slice_len`, so `conjoin_slice_len_bounds`
/// (suffix-gated) will not attach a spurious `0 <= N <= isize::MAX` fact (INV-4).
/// The name matches, byte-for-byte, the symbol the const-generic VALUE `N`
/// produces via `operand_to_formula`'s `ConstValue::ConstParam` arm and the
/// native `chc.rs` arm, so a guard `i < N` and the length share one SMT term.
pub(crate) fn sym_array_len_formula(len_sym: &trust_types::ConstLen) -> Formula {
    Formula::var_owned(trust_types::const_param_symbol(len_sym.index, &len_sym.name), Sort::Int)
}

/// Convert a u128 discriminant/switch value into a Formula without truncation.
///
/// Values that fit in i128 become `Formula::Int` for compatibility with the
/// mathematical-integer encoding used elsewhere. Values above `i128::MAX`
/// use `Formula::UInt` to avoid silent high-bit truncation.
pub(crate) fn u128_to_formula(value: u128) -> Formula {
    match i128::try_from(value) {
        Ok(n) => Formula::Int(n),
        Err(_) => Formula::UInt(value),
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ExplicitDiscriminantField {
    pub place: Place,
    pub ty: Ty,
    pub name: String,
}

pub(crate) fn explicit_discriminant_field_for_place(
    func: &VerifiableFunction,
    place: &Place,
) -> Result<ExplicitDiscriminantField, String> {
    // verifier-perf: borrowed resolve — a `SetDiscriminant` on a fat-ADT place (e.g. an
    // `Expr`/`Name`-typed local) would otherwise deep-clone the multi-MB declared root
    // just to locate one tag field. Walk by reference; only the small resolved tag field
    // (`field_ty`/`field_name`) is cloned, at the end.
    let place_ty = place_ty_cow(func, place).ok_or_else(|| {
        format!(
            "place `{}` has unknown type; cannot locate an explicit discriminant/tag field",
            place_to_var_name(func, place)
        )
    })?;

    let Ty::Adt { name: adt_name, fields, .. } = place_ty.as_ref() else {
        return Err(format!(
            "place `{}` has type {place_ty:?}; SetDiscriminant is modeled only for tagged ADTs with an explicit discriminant/tag field",
            place_to_var_name(func, place)
        ));
    };

    let Some((field_index, (field_name, field_ty))) =
        fields.iter().enumerate().find(|(_, (field_name, _))| {
            matches!(field_name.as_str(), "discriminant" | "__discriminant" | "tag" | "__tag")
        })
    else {
        let field_list =
            fields.iter().map(|(field_name, _)| field_name.as_str()).collect::<Vec<_>>().join(", ");
        return Err(format!(
            "ADT `{adt_name}` has no explicit discriminant/tag field in the TrustIr layout; fields=[{field_list}]"
        ));
    };

    if !matches!(field_ty, Ty::Bool | Ty::Int { .. }) {
        return Err(format!(
            "ADT `{adt_name}` discriminant/tag field `{field_name}` has type {field_ty:?}; expected bool or integer"
        ));
    }

    let mut discr_place = place.clone();
    discr_place.projections.push(Projection::Field(field_index));
    Ok(ExplicitDiscriminantField {
        place: discr_place,
        ty: field_ty.clone(),
        name: field_name.clone(),
    })
}

pub(crate) fn explicit_discriminant_value_formula(
    ty: &Ty,
    variant_index: usize,
) -> Result<(Sort, Formula), String> {
    match ty {
        Ty::Bool => match variant_index {
            0 => Ok((Sort::Bool, Formula::Bool(false))),
            1 => Ok((Sort::Bool, Formula::Bool(true))),
            _ => Err(format!(
                "variant index {variant_index} does not fit bool discriminant/tag field"
            )),
        },
        Ty::Int { width, signed } => {
            let width = *width;
            let signed = *signed;
            if width == 0 || width > 128 {
                return Err(format!(
                    "integer discriminant/tag width {width} is outside the supported 1..=128 range"
                ));
            }

            let value = variant_index as u128;
            let max = if signed {
                if width == 128 { i128::MAX as u128 } else { (1u128 << (width - 1)) - 1 }
            } else if width == 128 {
                u128::MAX
            } else {
                (1u128 << width) - 1
            };

            if value > max {
                return Err(format!(
                    "variant index {variant_index} does not fit {}{} discriminant/tag field",
                    if signed { "i" } else { "u" },
                    width
                ));
            }

            Ok((Sort::Int, u128_to_formula(value)))
        }
        other => {
            Err(format!("discriminant/tag field type {other:?} is not modeled as bool or integer"))
        }
    }
}

pub(crate) fn float_bits_magnitude_is_zero(bits: u128, width: u32) -> bool {
    if !(2..=128).contains(&width) {
        return false;
    }
    let magnitude_mask = (1u128 << (width - 1)) - 1;
    bits & magnitude_mask == 0
}

fn sanitize_symbol_fragment(input: &str) -> String {
    let mut out = String::new();
    for ch in input.chars() {
        if out.len() >= 64 {
            break;
        }
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    out.trim_matches('_').to_string()
}

/// Convert an operand to an SMT formula variable.
/// Uses Sort::Int for integer types (mathematical integers) to enable
/// range-based overflow checking.
///
/// Promoted to `pub` for use by trust-transval translation validation.
pub fn operand_to_formula(func: &VerifiableFunction, op: &Operand) -> Formula {
    // Trust: existing call sites stay byte-identical — they get the scalar path
    // (array-theory context = None). Only the v2 VC-builder path, which owns the
    // version prepass, calls the `_with_array_ctx` variant with `Some`.
    operand_to_formula_with_array_ctx(func, op, None)
}

/// Trust: array-theory-aware `operand_to_formula`. When `array_ctx` is `Some`
/// AND `op` reads an element of an array-theory-eligible local, returns a
/// `Select` term keyed on the live array version; otherwise falls through to the
/// scalar path, byte-identical to the old behavior.
pub(crate) fn operand_to_formula_with_array_ctx(
    func: &VerifiableFunction,
    op: &Operand,
    array_ctx: Option<&ArrayReadCtx<'_>>,
) -> Formula {
    if let Some(ctx) = array_ctx
        && let Some(select) = array_element_select(func, op, ctx)
    {
        return select;
    }
    match op {
        Operand::Copy(place) | Operand::Move(place) => {
            let name = place_to_var_name(func, place);
            let sort = operand_sort(func, op).unwrap_or(Sort::Int);
            // Use interned SymVar to reduce per-variable heap allocations.
            Formula::var(&name, sort)
        }
        Operand::Constant(cv) => match cv {
            ConstValue::Bool(b) => Formula::Bool(*b),
            ConstValue::Int(n) => Formula::Int(*n),
            ConstValue::Uint(n, _) => match i128::try_from(*n) {
                Ok(n) => Formula::Int(n),
                Err(_) => Formula::UInt(*n),
            },
            // Model float constants as their IEEE-754 bit pattern so guard
            // propagation can relate comparisons like `y == 0.0` to later
            // safety VCs on the same operand.
            ConstValue::Float(f) => Formula::BitVec { value: i128::from(f.to_bits()), width: 64 },
            ConstValue::FloatBits { bits, width } => match i128::try_from(*bits) {
                Ok(value) => Formula::BitVec { value, width: *width },
                Err(_) => Formula::var_owned(
                    format!("__trust_float_bits_{width}_{bits:x}"),
                    Sort::BitVec(*width),
                ),
            },
            ConstValue::Unit => Formula::Int(0),
            ConstValue::CallableItem { def_path, kind, def_path_hash } => Formula::var_owned(
                ConstValue::callable_smt_var_name(def_path, *kind, *def_path_hash),
                Sort::Int,
            ),
            // a `&str` literal as an opaque integer term, named
            // injectively from its bytes so distinct strings never share a term
            // (a shared term would let the solver "prove" a false disequality).
            ConstValue::Str { bytes } => {
                Formula::var_owned(ConstValue::str_smt_var_name(bytes), Sort::Int)
            }
            // A typed opaque integer constant (const-generic `N`, associated const,
            // `size_of::<T>()` in a generic body): an unconstrained integer-sorted
            // symbol. Sound: it asserts no value, so any obligation depending on its
            // value stays satisfiable-as-negation (Unknown/Failed), never falsely
            // proved. The two value-decision folds that COULD false-prove over it —
            // `v2_const_eq_truth` (branch pruning) and `v2_divisor_is_zero_formula`
            // (div/rem-by-zero) — match on the `ConstValue` STRUCTURALLY before
            // formula conversion and are fixed to treat `OpaqueScalar` as
            // unknown-valued, so they never consult this symbol. The native-bundle
            // path lowers each occurrence to an INDEPENDENT fresh symbol in
            // `emit_const`; this general formula renderer keeps the existing
            // by-name interning, identical to the pre-existing `__unknown_const`
            // behavior, and is only an over-approximation — never a false prove.
            ConstValue::OpaqueScalar { width, signed } => Formula::var_owned(
                format!("__trust_opaque_scalar_{}{}", if *signed { "i" } else { "u" }, width),
                Sort::Int,
            ),
            // Trust: piece #7a — a const-generic PARAM value `N` read as an
            // operand (e.g. the `N` in a guard `if i < N`). It lowers to the ONE
            // canonical per-param symbol `__trust_constparam_{index}_{name}` — the
            // SAME string `Ty::SymArray`'s length uses — so the guard fact and the
            // bounds VC share one SMT term. SOUNDNESS: keyed on the param IDENTITY,
            // NEVER on `(width, signed)`, so two distinct usize params `M`, `N`
            // never collide (the M==N false-proof). The symbol is unconstrained
            // (asserts no value); the `v2_const_eq_truth` / `v2_divisor_is_zero`
            // folds get parallel `ConstParam` arms so a const-param value stays
            // unknown-valued in both (never "definitely unequal" / "provably
            // nonzero"), preserving div/branch soundness.
            // A BOOL const-generic (in-band `width==1 && !signed`) lowers to the
            // same ONE canonical per-param symbol, Bool-sorted: every `if B`
            // guard across the function shares it, so the true- and false-branch
            // path conditions stay mutually exclusive (the decorrelation that
            // previously minted spurious `overflow` counterexamples on
            // dict-gated arithmetic is structurally impossible). Unconstrained:
            // the proof must hold for BOTH instantiations, which is exactly the
            // semantics of verifying the polymorphic body once.
            ConstValue::ConstParam { index, name, width: 1, signed: false } => {
                Formula::var_owned(trust_types::const_param_symbol(*index, name), Sort::Bool)
            }
            ConstValue::ConstParam { index, name, .. } => {
                Formula::var_owned(trust_types::const_param_symbol(*index, name), Sort::Int)
            }
            // Sound fallback for unknown ConstValue variants.
            // Produce an unconstrained symbolic variable rather than panicking.
            // This is sound: an unconstrained variable can take any value, so
            // no real bug is missed.
            // Use interned SymVar.
            _ => Formula::var("__unknown_const", Sort::Int),
        },
        Operand::Symbolic(formula) => formula.clone(),
        Operand::Unsupported { kind, detail } => Formula::var_owned(
            format!(
                "__trust_unsupported_operand_{}_{}",
                sanitize_symbol_fragment(kind),
                sanitize_symbol_fragment(detail)
            ),
            Sort::Int,
        ),
        // Sound fallback for unknown Operand variants.
        // Produce an unconstrained symbolic variable rather than panicking.
        // Use interned SymVar.
        _ => Formula::var("__unknown_operand", Sort::Int),
    }
}

/// Build a human-readable variable name from a Place.
// Render an array-literal element read `a[_i]` (where `_i` is a
// provable constant `c`) as the same `[c;min=N]` name that
// `aggregate_field_place` gives the literal's element *write*. Without this the
// read is a fresh, unconstrained variable disconnected from the constructed
// value (`a = [1,2,3,4]` then `a[0] + a[1]` false-fails an overflow VC because
// the solver may pick max values for the reads). Returns `None` — keeping the
// conservative `[_i]` name — unless the indexed thing is the bare array local
// AND that local is construction-immutable. Both guards are load-bearing for
// soundness: equating a read to the constructed value is only valid when no
// element store, mutable borrow, or re-construction can change it between
// construction and the read. When unmet we fall back to the old unconstrained
// name, which fails closed (Failed/Unknown), never false-proves.
fn constant_array_index_segment(
    func: &VerifiableFunction,
    place: &Place,
    pos: usize,
    index_local: usize,
) -> Option<String> {
    let c = index_local_const(func, index_local)?;
    // Shape A — `base[idx]`: Index is the first projection, so the indexed value is
    // the base local itself and its immutability is decidable from the base alone.
    // Nested forms (`s.f[idx]`) fall back.
    if pos == 0 {
        // verifier-perf: borrow the declared type — only the `len` (a Copy u64) is read.
        let Ty::Array { len, .. } = local_ty_ref(func, place.local)? else {
            return None;
        };
        // Trust: an eligible array-theory local routes EVERY element read
        // (including a const index) through `Select`, never the `[c;min=len]`
        // literal-naming path — returning None here keeps the two channels
        // disjoint.
        if array_theory_local(func, place.local).is_some() {
            return None;
        }
        if !array_local_index_naming_stable(func, place.local) {
            return None;
        }
        return Some(format!("[{c};min={len}]"));
    }
    // — Shape B — the indexed array sits at `place.projections[..pos]`,
    // reached from a *shared-reference* root that is never reseated, through a
    // leading Deref and then only Field / constant-Index steps. A shared reference's
    // pointee cannot be mutated or `&mut`-aliased through it, and Field/const-Index
    // navigation introduces no new mutable access, so `(*r)…[c]` observes the same
    // element at every read; the constant index `c` makes two reads converge despite
    // their distinct MIR index temps. Examples this covers: `(*r)[c]` (pos 1),
    // `(*r).f[c]` (struct field then index), `(*r)[c1][c2]` (nested array).
    //
    // Conservative gates, all load-bearing for soundness:
    //  * `&mut` root, or a written/reseated root, falls back — the pointee may be
    //    written between reads.
    //  * Any *further* Deref in the prefix falls back — it dereferences an inner
    //    reference (possibly `&mut`) whose pointee is not guaranteed immutable.
    //  * A non-constant index in the prefix falls back — its MIR temp need not
    //    converge between reads, so the path itself would not be stable.
    let prefix = &place.projections[..pos];
    let immutable_shared_path = matches!(prefix.first(), Some(Projection::Deref))
        // verifier-perf: borrow the declared type — only a variant check, no move.
        && matches!(local_ty_ref(func, place.local)?, Ty::Ref { mutable: false, .. })
        && local_is_never_written(func, place.local)
        && prefix[1..].iter().all(|p| match p {
            Projection::Field(_) | Projection::ConstantIndex { .. } => true,
            Projection::Index(l) => index_local_const(func, *l).is_some(),
            _ => false,
        });
    if !immutable_shared_path {
        return None;
    }
    // Type of the array being indexed = the place truncated to the prefix.
    let mut indexed = place.clone();
    indexed.projections.truncate(pos);
    match place_ty_cow(func, &indexed)?.as_ref() {
        Ty::Array { len, .. } => Some(format!("[{c};min={len}]")),
        Ty::Slice { .. } => Some(format!("[{c};slice]")),
        _ => None,
    }
}

// true iff the storage rooted at `local` is never the base of any
// assignment — neither reseated (`local = …`) nor written through a projection
// (`*local = …`, `local.f = …`, `local[i] = …`). For a function argument this means
// the value, and everything reachable from it, is fixed for the whole body, so a
// deref/index expressed relative to `local` denotes the same place at every read.
pub(crate) fn local_is_never_written(func: &VerifiableFunction, local: usize) -> bool {
    !func.body.blocks.iter().any(|block| {
        block
            .stmts
            .iter()
            .any(|stmt| matches!(stmt, Statement::Assign { place, .. } if place.local == local))
    })
}

// Resolve a local to a single constant `usize` index, or `None`.
// Sound only if *every* assignment to the local is the *same* non-negative
// integer constant (and there is at least one): then the local holds that value
// wherever it is read. Any non-constant assignment, or two differing constants
// (e.g. a loop induction variable, or a switch-merged index), yields `None`.
// Round-13: the scan also poisons on the WRITE CHANNELS a stmt-only def scan
// cannot see — a call destination, and a `&mut`/`&raw mut` borrow of the local
// (`*r = 9;` assigns through the borrow, not this local) — which now matters
// because this resolver feeds float-lane DISCHARGES (aggregate const-index
// tracing, place-name rendering) where a stale constant claims the wrong
// element.
pub(crate) fn index_local_const(func: &VerifiableFunction, local: usize) -> Option<usize> {
    let mut found: Option<u128> = None;
    for block in &func.body.blocks {
        for stmt in &block.stmts {
            let Statement::Assign { place, rvalue, .. } = stmt else {
                continue;
            };
            if let Rvalue::Ref { mutable: true, place: borrowed }
            | Rvalue::AddressOf(true, borrowed) = rvalue
                && borrowed.local == local
            {
                return None;
            }
            if place.local != local || !place.projections.is_empty() {
                continue;
            }
            let v = match rvalue {
                Rvalue::Use(Operand::Constant(ConstValue::Uint(v, _))) => *v,
                Rvalue::Use(Operand::Constant(ConstValue::Int(v))) if *v >= 0 => *v as u128,
                // Assigned something that is not a known non-negative constant.
                _ => return None,
            };
            match found {
                Some(prev) if prev != v => return None,
                _ => found = Some(v),
            }
        }
        if let Terminator::Call { dest, .. } = &block.terminator
            && dest.local == local
        {
            return None;
        }
    }
    found.and_then(|v| usize::try_from(v).ok())
}

// A local has "stable index naming" if every const-index read of
// it converges, under SSA last-write-wins, with the array literal and with any
// in-place const-index store — so equating a read of element `c` to the value
// most recently written to `c` is sound. The requirements:
//   * exactly one whole-local store (the construction);
//   * every *element/subslice* store uses a compile-time-constant `Index` — its
//     place name `[c;min=len]` then matches the literal's and the const-read's, so
//     a later store correctly overrides the stale literal (`seen_dests` within a
//     block at guards.rs, `extend_killing_redefs` across blocks);
//   * no `&mut`/raw-mut borrow of the local.
//
// widens the old "construction-immutable" gate (which bailed on *any*
// element store) to admit *constant*-index stores: `a = [10,1]; a[0] = 0; …` now
// keeps stable naming, and the store's `[0;min=len]` fact overrides the literal's,
// so `a[0]+a[1]` proves and `a[0]-a[1]` correctly FAILS (0-1 underflow). The bail
// cases below are all load-bearing for soundness — each prevents a *stale literal*
// surviving a write it cannot match, which would otherwise vacuously discharge a
// real overflow (a false-PROVE):
//   * a VARIABLE-index store could touch any element, so it must not be modeled as
//     overriding one element's fact while the others' literals survive;
//   * a ConstantIndex/Subslice store has a name (`from_end`, span) that need not
//     equal the literal's `[c;min=len]`, so its write could be lost;
//   * a `&mut`/raw-mut borrow can mutate elements through an alias we don't track.
// In every bail case we return `false`, falling back to opaque per-index naming:
// the whole array reads as free (a sound false-FAIL), never a false-PROVE.
fn array_local_index_naming_stable(func: &VerifiableFunction, local: usize) -> bool {
    let mut whole_assigns = 0usize;
    for block in &func.body.blocks {
        for stmt in &block.stmts {
            let Statement::Assign { place, rvalue, .. } = stmt else {
                continue;
            };
            if place.local == local {
                if place.projections.is_empty() {
                    whole_assigns += 1;
                } else {
                    // An in-place element/subslice store: stable only for a
                    // compile-time-constant `Index`. Everything else bails (see above).
                    for p in &place.projections {
                        match p {
                            Projection::Index(idx) if index_local_const(func, *idx).is_some() => {}
                            Projection::Index(_)
                            | Projection::ConstantIndex { .. }
                            | Projection::Subslice { .. } => return false,
                            _ => {}
                        }
                    }
                }
            }
            // A mutable borrow or raw-mut address-of could mutate elements later.
            match rvalue {
                Rvalue::Ref { mutable: true, place: borrowed }
                | Rvalue::AddressOf(true, borrowed)
                    if borrowed.local == local =>
                {
                    return false;
                }
                _ => {}
            }
        }
    }
    whole_assigns == 1
}

// =====================================================================
// Trust: McCarthy array-theory channel for STRAIGHT-LINE variable-index
// array code.
//
// SOUNDNESS by construction: this channel engages ONLY for array locals in
// functions whose CFG has NO JOIN BLOCK (every basic block has <= 1
// predecessor). With no joins there are no control-flow merges, so no stale
// array fact can ever leak across a join, and the branch_merge /
// arm_definition_map passes never fire for these functions. Any array in a
// function with a branch/loop merge stays in the sound opaque-poison
// fallback (false-FAIL) — that path is untouched.
//
// `array_theory_local` returning `Some` implies `array_local_index_naming_stable`
// is `false` (the latter bails on the variable-index store), so the two channels
// are disjoint.
// =====================================================================

/// A scalar-element array local that is eligible for the McCarthy array-theory
/// channel. `len` is the declared array length (informational); `elem_sort` is
/// the SMT sort of one element (always a scalar: Int / Bool / BitVec).
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ArrayModel {
    pub len: Option<u64>,
    pub elem_sort: Sort,
}

/// True iff the CFG of `func` has no join block — every basic block is listed as
/// a successor by at most one terminator. This also excludes loops (a loop
/// header has >= 2 predecessors: the entry edge and the back edge).
pub(crate) fn func_has_no_join(func: &VerifiableFunction) -> bool {
    let n = func.body.blocks.len();
    let mut pred_count = vec![0u32; n];
    for block in &func.body.blocks {
        for target in terminator_target_blocks(&block.terminator) {
            if target.0 < n {
                pred_count[target.0] += 1;
            }
        }
    }
    pred_count.iter().all(|&c| c < 2)
}

/// All successor block ids of a terminator (every branch target it may take).
fn terminator_target_blocks(terminator: &Terminator) -> Vec<BlockId> {
    match terminator {
        Terminator::Goto(target) => vec![*target],
        Terminator::SwitchInt { targets, otherwise, .. } => {
            let mut blocks: Vec<BlockId> = targets.iter().map(|(_, t)| *t).collect();
            blocks.push(*otherwise);
            blocks
        }
        Terminator::Call { target: Some(target), .. } => vec![*target],
        Terminator::Assert { target, .. } | Terminator::Drop { target, .. } => vec![*target],
        Terminator::Opaque { targets, .. } => targets.clone(),
        Terminator::Return
        | Terminator::Call { target: None, .. }
        | Terminator::Unreachable
        | Terminator::Resume => vec![],
        // `Terminator` is non_exhaustive; an unknown terminator has no modeled
        // successors here (conservative — counts no predecessors for it).
        _ => vec![],
    }
}

/// True iff the storage rooted at `local` may be mutated through an alias the
/// array-theory channel does not model. Conservative: when unsure, returns true
/// (the channel then bails to the sound opaque fallback). Specifically true if:
///   * a `&mut`/`&raw mut` borrow whose canonical base local is `local`;
///   * any `Terminator::Call` passing an operand referencing `local`
///     (`Move(local)`, or a `Ref`/`AddressOf` whose canonical base is `local`);
///   * a call destination projected into `local`.
fn array_local_escapes(func: &VerifiableFunction, local: usize) -> bool {
    let base_is_local = |place: &Place| canonicalize_place(func, place.clone(), 16).local == local;
    for block in &func.body.blocks {
        for stmt in &block.stmts {
            if let Statement::Assign { rvalue, .. } = stmt {
                match rvalue {
                    Rvalue::Ref { mutable: true, place } | Rvalue::AddressOf(true, place)
                        if base_is_local(place) =>
                    {
                        return true;
                    }
                    _ => {}
                }
            }
        }
        if let Terminator::Call { args, dest, .. } = &block.terminator {
            // A call destination into `local` reassigns/mutates it: a projected
            // dest (`a[i] = f()`) mutates an element in place, and a WHOLE-local
            // dest (`a = fresh()`) reseats the entire array to an unmodeled value
            // -- both invalidate the McCarthy version chain seeded before the
            // call. (Construction via a literal `[..]`/`[x; n]` is a
            // Statement::Assign, not a Call, so it is unaffected.)
            if dest.local == local {
                return true;
            }
            for arg in args {
                match arg {
                    Operand::Move(place) if place.local == local => return true,
                    Operand::Symbolic(_) | Operand::Unsupported { .. } => {
                        // Cannot inspect — fail closed.
                        return true;
                    }
                    _ => {}
                }
            }
        }
    }
    // A reference operand to `local` passed to a call may mutate it via the
    // callee. Scan rvalues that *create* such references and are then handed to a
    // call. Conservatively, any `&mut`/raw-mut already returned true above; a
    // shared `&local` passed to a call cannot mutate `local`, so it is safe.
    false
}

/// True iff `stmt` is an *element store* `a[Index(idx)] = w` into `local` whose
/// index is a NON-constant `Index` projection (so it engages array theory). The
/// leading projection must be `Index`.
pub(crate) fn is_array_theory_element_store(
    func: &VerifiableFunction,
    local: usize,
    stmt: &Statement,
) -> bool {
    let Statement::Assign { place, .. } = stmt else {
        return false;
    };
    if place.local != local {
        return false;
    }
    // Trust: once an array is eligible (which REQUIRES a variable-index store),
    // EVERY `Index` element store to it must flow through the array channel and
    // bump the version — including a const-FOLDING `a[Index(j)]` where `j`
    // resolves to a constant. Such a store is NOT a "variable-index store" for
    // eligibility, but the scalar `[c;min=len]` path is bypassed for eligible
    // arrays, so dropping it here would make it vanish entirely and a later
    // same-slot read would see a STALE value (false-PROVE). `index_local_const`
    // is therefore deliberately NOT consulted: the index term is the index
    // local's value either way (a const-folding index reads via its `_j == c`
    // scalar fact), and the read and store sides agree because both count a
    // store via this one predicate.
    let _ = func;
    matches!(place.projections.first(), Some(Projection::Index(_)))
}

/// Decide whether `local` is an eligible array-theory local. Returns `Some`
/// (with the element sort) IFF all of:
///   * `local`'s type is `Ty::Array{elem, len}` and `elem` has a SCALAR sort
///     (Int / Bool / BitVec) — nested Array/Slice/Adt/Tuple/Ref elems bail;
///   * `func_has_no_join(func)` — the CFG has no control-flow merge;
///   * there is >= 1 element store to `local` with a NON-constant `Index`;
///   * NO `ConstantIndex`/`Subslice` store to `local`, and no escape.
/// Trust: a local is value-STABLE if it has at most one definition reaching its
/// uses -- a pure input parameter defined at entry and never reassigned, or a
/// single-assignment temporary -- AND it cannot be mutated through an alias. A
/// `Terminator::Call` dest and an `&mut`/escaping-call use also count via
/// `array_local_escapes`. Used for the McCarthy array index and for widening-mul
/// cast operands; both can become false-PROVE vectors if a reassigned runtime
/// value is still encoded at a stale SMT name or narrowed source width.
pub(crate) fn index_local_stable(func: &VerifiableFunction, local: usize) -> bool {
    let is_param = (1..=func.body.arg_count).contains(&local);
    let mut defs = usize::from(is_param);
    for block in &func.body.blocks {
        for stmt in &block.stmts {
            if let Statement::Assign { place, .. } = stmt
                && place.local == local
                && place.projections.is_empty()
            {
                defs += 1;
            }
        }
        // Trust: a `Terminator::Call` whose dest IS the index local reassigns it
        // (`i = f()`), invisible to a Statement::Assign-only scan. Count it as a
        // definition so a reassigned-via-call index is NOT stable.
        if let Terminator::Call { dest, .. } = &block.terminator
            && dest.local == local
        {
            defs += 1;
        }
    }
    if defs > 1 {
        return false;
    }
    // Trust: the index could also be mutated through an alias between the store
    // and the read (`let r = &mut i; mutate(r)`, or passed by Move/opaquely to a
    // callee). `array_local_escapes` detects exactly those events for a local; if
    // the index can escape-mutate, it is not stable.
    !array_local_escapes(func, local)
}

pub(crate) fn array_theory_local(func: &VerifiableFunction, local: usize) -> Option<ArrayModel> {
    // verifier-perf: borrow the declared type (no fat-root clone) — this only inspects
    // the element type/sort, never moves the `Ty`.
    let Ty::Array { elem, len } = local_ty_ref(func, local)? else {
        return None;
    };
    // The element must be a SCALAR with one of the modeled sorts (Int / Bool /
    // BitVec). `sort_for_ty` falls back to `Sort::Int` for NON-scalar types
    // (Array/Slice/Adt/Tuple/Ref/...), so a sort check alone would wrongly admit
    // them — gate on the element TYPE directly, then confirm the sort.
    if !matches!(**elem, Ty::Bool | Ty::Int { .. } | Ty::Float { .. } | Ty::Bv(_)) {
        return None;
    }
    let elem_sort = sort_for_ty(elem);
    if !matches!(elem_sort, Sort::Int | Sort::Bool | Sort::BitVec(_)) {
        return None;
    }
    if !func_has_no_join(func) {
        return None;
    }
    let mut has_variable_index_store = false;
    for block in &func.body.blocks {
        for stmt in &block.stmts {
            let Statement::Assign { place, .. } = stmt else {
                continue;
            };
            if place.local != local || place.projections.is_empty() {
                continue;
            }
            match place.projections.first() {
                Some(Projection::Index(idx)) => {
                    // Trust (index-staleness): the index local of EVERY element
                    // store (const-folding OR variable) must be STABLE -- never
                    // reassigned. Otherwise a store `Store(v, idx, w)` and a later
                    // read `Select(v, idx)` at the SAME SMT name would let ROW1
                    // fire spuriously after `idx` is reassigned between them
                    // (e.g. `a[i]=0; i=j; a[i]`), forcing the read to the stored
                    // value though the real indices differ -- a false-PROVE.
                    // Bail to the sound opaque fallback.
                    if !index_local_stable(func, *idx) {
                        return None;
                    }
                    if index_local_const(func, *idx).is_none() {
                        has_variable_index_store = true;
                    }
                }
                // A ConstantIndex / Subslice store has a name that need not match
                // the Select/Store model; bail to the sound opaque fallback.
                Some(Projection::ConstantIndex { .. } | Projection::Subslice { .. }) => {
                    return None;
                }
                _ => {}
            }
        }
    }
    if !has_variable_index_store {
        return None;
    }
    if array_local_escapes(func, local) {
        return None;
    }
    Some(ArrayModel { len: Some(*len), elem_sort })
}

/// The SMT term for version `version` of array `local` with element sort `elem`.
/// Distinct versions get distinct names so a `Store` chain links them.
pub(crate) fn array_term_var(local: usize, version: u32, elem: Sort) -> Formula {
    Formula::Var(
        format!("arr${local}$v{version}"),
        Sort::Array(Box::new(Sort::Int), Box::new(elem)),
    )
}

/// The SMT term for version `version` of array `local`, resolving the element
/// sort from `array_theory_local` (defaulting to Int when not eligible).
fn array_term_formula(func: &VerifiableFunction, local: usize, version: u32) -> Formula {
    let elem = array_theory_local(func, local).map(|m| m.elem_sort).unwrap_or(Sort::Int);
    array_term_var(local, version, elem)
}

/// The SMT index term for an element-access projection.
pub(crate) fn array_index_formula(func: &VerifiableFunction, idx_proj: &Projection) -> Formula {
    match idx_proj {
        Projection::Index(l) => Formula::var(
            &place_to_var_name(func, &Place { local: *l, projections: vec![] }),
            Sort::Int,
        ),
        Projection::ConstantIndex { offset, .. } => Formula::Int(*offset as i128),
        // Other projections never reach here (the caller gates on element access).
        _ => Formula::Int(0),
    }
}

/// Linear version context for the no-join (acyclic) CFG: the entry version of
/// each eligible array local at the start of each block. Because there are no
/// joins, every block inherits its unique predecessor's exit version, so no
/// havoc is ever needed.
#[derive(Debug, Clone, Default)]
pub(crate) struct ArrayVersionCtx {
    entry: FxHashMap<(BlockId, usize), u32>,
}

/// Count the element stores to `local` in `stmts[..end]` (in program order).
/// This is the SINGLE store-count oracle used by both the read side and the
/// store side, so versions never disagree.
pub(crate) fn count_element_stores(
    func: &VerifiableFunction,
    local: usize,
    stmts: &[Statement],
) -> u32 {
    stmts.iter().filter(|s| is_array_theory_element_store(func, local, s)).count() as u32
}

impl ArrayVersionCtx {
    /// The array version live at `stmts[stmt_idx]` of `block` (i.e. the version
    /// to READ): the block's entry version plus the element stores strictly
    /// before `stmt_idx`.
    pub(crate) fn live_version(
        &self,
        func: &VerifiableFunction,
        local: usize,
        block: BlockId,
        stmt_idx: usize,
    ) -> u32 {
        let entry = self.entry.get(&(block, local)).copied().unwrap_or(0);
        let block_ref = func.body.blocks.iter().find(|b| b.id == block);
        let bumped = block_ref
            .map(|b| count_element_stores(func, local, &b.stmts[..stmt_idx.min(b.stmts.len())]))
            .unwrap_or(0);
        entry + bumped
    }
}

/// Forward topological version prepass over the no-join (acyclic) CFG.
/// `entry[(entry_block, local)] = 0` for each eligible local; each block's exit
/// version = its entry version + element-store count, propagated to every
/// successor (which has this block as its unique predecessor, or — for a branch
/// — shares this same exit across all successors).
pub(crate) fn v2_array_version_prepass(func: &VerifiableFunction) -> ArrayVersionCtx {
    let mut ctx = ArrayVersionCtx::default();
    if func.body.blocks.is_empty() || !func_has_no_join(func) {
        return ctx;
    }
    // Eligible locals — computed once.
    let eligible: Vec<usize> = func
        .body
        .locals
        .iter()
        .map(|d| d.index)
        .filter(|&l| array_theory_local(func, l).is_some())
        .collect();
    if eligible.is_empty() {
        return ctx;
    }
    let entry_block = func.body.blocks[0].id;
    for &local in &eligible {
        ctx.entry.insert((entry_block, local), 0);
    }
    // Forward BFS/topo walk: each block, once its entry version is known, sets
    // its successors' entry version to its own exit version. The no-join CFG is
    // acyclic, so a simple worklist over a finite number of edges terminates.
    let mut worklist = vec![entry_block];
    let mut seen: std::collections::HashSet<BlockId> = std::collections::HashSet::new();
    while let Some(bid) = worklist.pop() {
        if !seen.insert(bid) {
            continue;
        }
        let Some(block) = func.body.blocks.iter().find(|b| b.id == bid) else {
            continue;
        };
        for &local in &eligible {
            let entry = ctx.entry.get(&(bid, local)).copied().unwrap_or(0);
            let exit = entry + count_element_stores(func, local, &block.stmts);
            for succ in terminator_target_blocks(&block.terminator) {
                // Unique predecessor (no-join) => safe to set; first writer wins
                // and there is only ever one writer.
                ctx.entry.entry((succ, local)).or_insert(exit);
                worklist.push(succ);
            }
        }
    }
    ctx
}

/// Read context for `operand_to_formula`: which array version to use for an
/// element read happening at `(block, stmt_idx)`.
pub(crate) struct ArrayReadCtx<'a> {
    versions: &'a ArrayVersionCtx,
    block: BlockId,
    stmt_idx: usize,
}

impl<'a> ArrayReadCtx<'a> {
    pub(crate) fn new(versions: &'a ArrayVersionCtx, block: BlockId, stmt_idx: usize) -> Self {
        ArrayReadCtx { versions, block, stmt_idx }
    }
}

/// If `op` is a Copy/Move of an *element access* (`a[i]` / `a[const]`) into an
/// array-theory-eligible local, return its `Select(arr$local$v{n}, idx)` term.
/// `n` is the version live at the read point per the single store-count oracle.
fn array_element_select(
    func: &VerifiableFunction,
    op: &Operand,
    ctx: &ArrayReadCtx<'_>,
) -> Option<Formula> {
    let place = match op {
        Operand::Copy(place) | Operand::Move(place) => place,
        _ => return None,
    };
    // The element access must be `local[idx]` directly (leading Index /
    // ConstantIndex into the bare array local) — the only shape the store side
    // models. Nested forms keep the scalar path.
    let idx_proj = place.projections.first()?;
    if !matches!(idx_proj, Projection::Index(_) | Projection::ConstantIndex { .. }) {
        return None;
    }
    // Only a single index projection (a scalar element read), no further nesting.
    if place.projections.len() != 1 {
        return None;
    }
    // Confirm eligibility (also disjoint from the scalar `[c;min=len]` channel).
    array_theory_local(func, place.local)?;
    let version = ctx.versions.live_version(func, place.local, ctx.block, ctx.stmt_idx);
    Some(Formula::Select(
        Box::new(array_term_formula(func, place.local, version)),
        Box::new(array_index_formula(func, idx_proj)),
    ))
}

// follow a reference local back to the place it points to, so a
// deref `*L` is named by its underlying storage instead of an opaque `L*`.
// Match guards on references re-borrow the binding
// (`_4 = &_3; _9 = *_4; if *_9 < K { ... *_3 + 1 ... }`), so the guard reads
// `*_9` while the arithmetic reads `*_3`; both alias the same payload yet get
// distinct SMT names, so the guard never constrains the overflow VC — a Goal-1
// false-fail. Only *unique, whole-local* definitions are followed, so the
// referent is unambiguous; `&mut` is safe because a write through the alias
// canonicalizes to the same place name, keeping reads and writes consistent.
pub(crate) fn unique_whole_local_def(func: &VerifiableFunction, local: usize) -> Option<&Rvalue> {
    let mut found: Option<&Rvalue> = None;
    for block in &func.body.blocks {
        for stmt in &block.stmts {
            let Statement::Assign { place, rvalue, .. } = stmt else { continue };
            if place.local != local {
                continue;
            }
            // A write THROUGH this reference (`*L = v` — projection starting with
            // Deref) changes the POINTEE, not what `L` points to, so it does not
            // make L's referent ambiguous: skip it. Trust #soundness (round-12):
            // previously such a store hit the bail below and returned None,
            // defeating the `*L -> referent` fold, so `place_to_var_name(*L)` was
            // the opaque `L*` and a store `*L = v` emitted a def about `L*` that
            // never havoced the referent `x` — a stale `x == 5` survived the
            // mutation and vacuously discharged a real overflow (a false-PROVE).
            // Folding restores the intended invariant: a write through the alias
            // names the same place as a direct read/write of the referent.
            if place.projections.first() == Some(&Projection::Deref) {
                continue;
            }
            // A field/index store into this local, or a second whole-local def,
            // makes its value ambiguous.
            if !place.projections.is_empty() || found.is_some() {
                return None;
            }
            found = Some(rvalue);
        }
    }
    found
}

// The place a reference *value* read from `source` ultimately points to.
fn referent_of_source(func: &VerifiableFunction, source: &Place, fuel: u32) -> Option<Place> {
    if fuel == 0 {
        return None;
    }
    match source.projections.as_slice() {
        // `L = Copy(M)` — L holds the same reference M does.
        [] => resolve_referent(func, source.local, fuel - 1),
        // `L = Copy(*M)` — M points to a slot holding the reference; follow it.
        [Projection::Deref] => match resolve_referent(func, source.local, fuel - 1) {
            Some(slot) if slot.projections.is_empty() => {
                resolve_referent(func, slot.local, fuel - 1)
            }
            Some(slot) => referent_of_source(func, &slot, fuel - 1),
            // M's referent is unknown because M is a never-written
            // parameter (e.g. `r: &&u32`). The reference value read from `*M` is then
            // fixed, and it points to `**M`; naming the deref relative to M lets two
            // reborrows of the same payload converge. A written/reseated M falls back
            // to the opaque `*M` name (no merge), preserving soundness.
            None if local_is_never_written(func, source.local) => Some(deref_of(source)),
            None => None,
        },
        // `L = Copy((*M).f…)` — a reference read out of a FIELD of M's pointee: the
        // closure-ENV upvar shape (`_6 = copy (*_1).0`, `_7 = copy (*_1).0`). Mirrors
        // the `[Deref]` arm: follow M's referent when it resolves; otherwise, for an
        // M that is never WHOLE-reseated (a closure env pointer — entry def only),
        // the reference lives in a fixed slot, so name its pointee definitionally as
        // `(*M).f*`. Two copies of the SAME upvar ref then converge on ONE name
        // (`_1*.0*`), which is what lets a guard read through one copy bound a use
        // read through another — the `&mut`-captured-upvar guard idiom
        // (`if acc < 1000 { acc += 1 }` inside a closure) previously FALSE-REFUTED
        // because each copy minted an opaque `_6*`/`_7*`.
        //
        // SOUND with the versioning fabric (the overlap-union mint): a write to the
        // slot (`(*M).f = other_ref`, name `_1*.0`), a write-back through the ref
        // (`(*(*M).f) = v`, name `_1*.0*`), and a Call/Drop havoc of M (base name
        // `_1`, M being a mut-pointer-carrying local) ALL name-overlap the pointee
        // read `_1*.0*`, so reads straddling any mutation channel mint DIFFERENT
        // version tokens and can never falsely unify. A whole-local reseat of M
        // itself has no name the fabric tracks relative to the old pointee, so it
        // fail-closes here (`whole_local_def_count != 0` declines to the opaque
        // per-copy name — no merge, the pre-existing conservative behavior).
        [Projection::Deref, rest @ ..]
            if !rest.is_empty() && rest.iter().all(|p| matches!(p, Projection::Field(_))) =>
        {
            match resolve_referent(func, source.local, fuel - 1) {
                Some(mut slot) => {
                    slot.projections.extend_from_slice(rest);
                    referent_of_source(func, &slot, fuel - 1)
                }
                None if crate::guards::whole_local_def_count(func, source.local) == 0 => {
                    Some(deref_of(source))
                }
                None => None,
            }
        }
        // `L = Copy(_agg.idx)` where `_agg = (op0, op1, …)` was built by an
        // `Aggregate`: `_agg.idx` IS the construction operand `op_idx` (a real value
        // equality), so L holds that operand's reference value. Fold through to it so a
        // tuple/struct-field copy of a reference names the SAME referent as the source —
        // e.g. `_23 = _6.0` with `_6 = (self, other)` makes `*_23` canonicalize to
        // `*self`, which lets `build_discriminant_cse_facts` tie `disc(*_23) ≡ disc(*self)`.
        // Only a CONSTRUCTED aggregate folds, so genuinely-distinct struct-field reads
        // never merge. For a never-written reference operand the referent is the
        // definitional `*op`, mirroring the `[Deref]` arm.
        [Projection::Field(idx)] => {
            let Some(Rvalue::Aggregate(_, operands)) = unique_whole_local_def(func, source.local)
            else {
                return None;
            };
            let (Operand::Copy(p) | Operand::Move(p)) = operands.get(*idx)? else {
                return None;
            };
            referent_of_source(func, p, fuel - 1).or_else(|| {
                (p.projections.is_empty() && local_is_never_written(func, p.local))
                    .then(|| deref_of(p))
            })
        }
        _ => None,
    }
}

// `place` extended by one Deref — the place the reference *stored at*
// `place` points to, expressed definitionally when no more concrete referent exists.
fn deref_of(place: &Place) -> Place {
    let mut derefed = place.clone();
    derefed.projections.push(Projection::Deref);
    derefed
}

fn resolve_referent(func: &VerifiableFunction, local: usize, fuel: u32) -> Option<Place> {
    if fuel == 0 {
        return None;
    }
    match unique_whole_local_def(func, local)? {
        Rvalue::Ref { place, .. } | Rvalue::AddressOf(_, place) => {
            Some(canonicalize_deref(func, place.clone(), fuel - 1))
        }
        Rvalue::Use(Operand::Copy(p) | Operand::Move(p)) => referent_of_source(func, p, fuel - 1),
        _ => None,
    }
}

/// True iff a store `*p = v` rooted at `local` (`p`) names an OPAQUE pointer —
/// i.e. `canonicalize_deref` cannot fold `*p` to a concrete referent place, so
/// `place_to_var_name(*p)` is the opaque `p*` that does NOT overlap the real
/// referent's name. This is EXACTLY when the store's mutation is invisible to the
/// name-based redef kill, so a fact about the referent survives stale.
///
/// Covers every non-foldable pointer provenance: a reseated / multiply-`&mut`-
/// borrowed pointer (no unique whole-local def), a pointer parameter, a
/// call-returned pointer, AND a CAST-laundered pointer (`&mut x as *mut T`,
/// `IntToPtr`, pointer arithmetic) whose unique def is an `Rvalue::Cast`/BinaryOp
/// that `resolve_referent` cannot fold (its `_ => None` arm). Mirrors the fuel
/// (16) `place_to_var_name` uses, so the predicate agrees with how the name is
/// actually minted: opaque-name ⟺ `resolve_referent` is `None`.
pub(crate) fn deref_pointer_is_opaque(func: &VerifiableFunction, local: usize) -> bool {
    resolve_referent(func, local, 16).is_none()
}

// Rewrite a place by resolving a leading deref-of-reference to its referent,
// recursively. A non-deref place, or a deref of a reference whose referent
// cannot be uniquely determined (e.g. a function parameter), is returned as-is.
fn canonicalize_deref(func: &VerifiableFunction, place: Place, fuel: u32) -> Place {
    if fuel == 0 {
        return place;
    }
    let Some((Projection::Deref, rest)) = place.projections.split_first() else {
        return place;
    };
    let Some(mut referent) = resolve_referent(func, place.local, fuel - 1) else {
        return place;
    };
    referent.projections.extend_from_slice(rest);
    canonicalize_deref(func, referent, fuel - 1)
}

// true iff the storage rooted at `local` is fixed for the whole body
// at most one whole-local store (a single construction, or zero for a parameter)
// and no other mutation path: no projected store, no `&mut`/`&raw mut`, no
// set-discriminant, no deinit, and no whole/projected call-destination write.
// Stronger than `local_is_never_written` (which ignores call dests and allows no
// construction) and complementary to `array_local_index_naming_stable`
// (which permits const-index element stores so long as their names converge).
// Under this predicate a place expressed relative to `local` denotes the same
// value at every read.
pub(crate) fn place_source_is_stable(func: &VerifiableFunction, local: usize) -> bool {
    let mut whole_assigns = 0usize;
    for block in &func.body.blocks {
        if let Terminator::Call { dest, .. } = &block.terminator {
            if dest.local == local {
                // Any call-dest store (whole or projected) reseats/mutates the value.
                if !dest.projections.is_empty() {
                    return false;
                }
                whole_assigns += 1;
            }
        }
        for stmt in &block.stmts {
            match stmt {
                Statement::Assign { place, rvalue, .. } => {
                    if place.local == local {
                        if place.projections.is_empty() {
                            whole_assigns += 1;
                        } else {
                            // A store through a projection mutates in place.
                            return false;
                        }
                    }
                    if let Rvalue::Ref { mutable: true, place: borrowed }
                    | Rvalue::AddressOf(true, borrowed) = rvalue
                    {
                        if borrowed.local == local {
                            return false;
                        }
                    }
                }
                Statement::SetDiscriminant { place, .. } | Statement::Deinit { place } => {
                    if place.local == local {
                        return false;
                    }
                }
                _ => {}
            }
        }
    }
    whole_assigns <= 1
}

// a struct/enum payload bound by a match arm reaches the arithmetic
// through a base-local value copy, not a reference: `_3 = Move(_1.downcast(0).field(0))`
// then `_3.field(0)` is the overflow operand, while the guard reads the same field
// via a reborrow (`_4 = &_1.downcast(0).field(0); *_4.field(0) < K`). The guard
// canonicalizes through the leading deref to `_1@0.0.0`, but the overflow operand
// stays `_3.0` — distinct SMT names, so the guard never constrains the overflow
// (a Goal-1 false-fail). When `_3` is a unique whole-local Copy/Move of a *stable*
// place `Q` (built only from static Field/Downcast projections), `_3.proj` denotes
// exactly `Q.proj`; return that rebased place so both reads converge. Soundness:
// both the alias local and `Q`'s root must be immutable (`place_source_is_stable`),
// so the rebase preserves the value at every read; otherwise return `None` and the
// opaque `_3` name is kept (fail-closed to a false-fail, never a false-prove).
fn base_value_alias(func: &VerifiableFunction, place: &Place) -> Option<Place> {
    // Only rebase a *projection into* the moved payload (`_3.field`), the struct-
    // field read that the guard sees as a deref-folded source field. A read of the
    // whole moved local (`_3`, empty projections) already converges with the guard
    // by its own name — folding it would only desync facts (e.g. scalar-payload
    // match guards #36/#50) keyed on that name, a precision regression.
    if place.projections.is_empty() {
        return None;
    }
    let Rvalue::Use(Operand::Copy(src) | Operand::Move(src)) =
        unique_whole_local_def(func, place.local)?
    else {
        return None;
    };
    if src.local == place.local {
        return None;
    }
    // The alias local must hold its single constructed value unchanged.
    if !place_source_is_stable(func, place.local) {
        return None;
    }
    // Restrict to enum-variant *payload* extraction (`_1 as Variant.0`) — the
    // match-arm bind that splits the guard name (reborrow → deref-folded source)
    // from the overflow name (moved base local). A `Downcast` in the source marks
    // exactly that pattern; plain local/tuple/struct-field copies (no downcast)
    // keep their own identity, so def-propagation and abstract-interp keying stay
    // undisturbed. Only static structural projections (Field/Downcast) may be
    // carried onto the source: they have no runtime-varying component, unlike
    // Index (varying index) or Deref (depends on a separately-tracked referent).
    if !src.projections.iter().any(|p| matches!(p, Projection::Downcast(_)))
        || !src
            .projections
            .iter()
            .all(|p| matches!(p, Projection::Field(_) | Projection::Downcast(_)))
    {
        return None;
    }
    // The source storage must be immutable wherever the alias is later read.
    if !place_source_is_stable(func, src.local) {
        return None;
    }
    let mut projections = src.projections.clone();
    projections.extend_from_slice(&place.projections);
    Some(Place { local: src.local, projections })
}

// canonicalize a place by first folding leading reference derefs
// (`canonicalize_deref`) and then rebasing through base-local value aliases
// (`base_value_alias`), alternating until a fixpoint. This makes a payload read
// via a reborrowed reference (guard side) and via a moved base local (arithmetic
// side) converge to one name. Each rebase moves to a strictly different base local
// with a unique def, so the loop terminates; `fuel` is a safety bound.
fn canonicalize_place(func: &VerifiableFunction, place: Place, fuel: u32) -> Place {
    let mut p = canonicalize_deref(func, place, fuel);
    for _ in 0..fuel {
        let Some(rebased) = base_value_alias(func, &p) else {
            break;
        };
        p = canonicalize_deref(func, rebased, fuel);
    }
    p
}

/// The characters a projection segment emitted by `place_to_var_name` may begin
/// with. `place_to_var_name` spells a place as `base ++ segments`, and this set is
/// the only thing that makes that concatenation decodable: a segment starts with
/// one of these, a base contains none of them, so the boundary is the first
/// occurrence in the string. Both halves of that invariant are ENFORCED, not
/// asserted — see the two uses in `place_to_var_name`. Adding a segment spelling
/// that starts with something else does not silently break the split: the emitter
/// prefixes `@` to any segment that would.
const PROJECTION_SEGMENT_LEAD: &[char] = &['.', '[', '*', '@'];

// Trust (leaf-assert-unhostage, 2026-07-11): `pub` (was `pub(crate)`) — the
// SINGLE SOURCE OF TRUTH for the VC formula variable vocabulary. trust-clean's
// guard-implied-assert augmentation (`prove.rs`, ordering-sentinel cmp facts)
// must spell the SAME names this emitter spells (`idx`, `self*.1`, `_6`, …) or
// its conjoined facts silently bind nothing; re-implementing the naming there
// would be a drift channel (canonicalization + the name-collision fallback
// live here). Exporting the one function keeps the two ends unforkable — the
// same rationale as `trust_types::total_call_summaries`.
pub fn place_to_var_name(func: &VerifiableFunction, place: &Place) -> String {
    // Public callers can construct Trust IR directly. Every canonicalization
    // helper resolves locals by explicit `LocalDecl.index` or scans Place IDs,
    // so sparse/reordered tables remain well-defined and must not lose useful
    // alias convergence. Duplicate declaration indices are genuinely
    // ambiguous, however; proof entry points reject them and this standalone
    // helper declines canonicalization while retaining a unique `_N` fallback.
    let mut seen_indices = trust_types::fx::FxHashSet::default();
    let local_indices_are_unique =
        func.body.locals.iter().all(|decl| seen_indices.insert(decl.index));
    let canonical = if local_indices_are_unique {
        canonicalize_place(func, place.clone(), 16)
    } else {
        place.clone()
    };
    let place = &canonical;
    let fallback = format!("_{}", place.local);
    // Trust #soundness (name-collision false proof): the base SMT name is the local's
    // SOURCE name, but a source name is NOT unique across distinct MIR locals — shadowing
    // (`let t = p`) or same-named bindings in sibling/parent scopes (incl. a parameter and
    // an inner local both named `t`) give two DISTINCT canonical locals the same name. A
    // FACT keyed to one local (the accumulator bound, a BV-mul dominating-guard operand
    // bound, a slice-length guard) would then be conjoined onto the OTHER local's VC and
    // vacuously discharge its real obligation — a confirmed FALSE PROOF
    // (`fn f(t:u16){ let t=0; for &x in &[255u8;4]{t+=x as u16;} ...; } t+60000` proved
    // while it overflows). Fix at the root: any source name shared by 2+ locals is
    // ambiguous, so fall back to the unique, SMT-safe per-local `_<local>` name for EVERY
    // local carrying it. Unique names (the overwhelming common case) are unchanged, so the
    // change is verdict-identical except where it CLOSES a fact leak. The accumulator's own
    // bound still discharges (its VC and its fact both resolve to the same `_<local>`); it
    // simply can no longer leak onto an unrelated same-named local.
    // Trust #soundness (fallback-collision false proof): the residual leak the
    // shared-source-name demotion above does NOT cover — a source name literally
    // spelled `_<k>` (a VALID Rust identifier) for one local collides with the
    // FALLBACK var `_<k>` an UNNAMED local at index k mints. Two distinct locals
    // would then share an SMT name and a fact keyed to one would vacuously
    // discharge the other's obligation (confirmed FALSE PROOF: a field/whole-
    // local guard on a closure-env local `_1` vs a param literally named `_1`).
    // Fix: a source name shaped like ANY local's fallback token is ambiguous —
    // demote it too. (Demoting `_<self>` is a no-op; it already equals fallback.)
    // The same rule applies to every shared synthetic Formula spelling: a
    // scalar source local `s__slice_len` must not alias the generated length of
    // slice `s`, nor may `__trust_constparam_0_N` alias const generic `N`.
    // `trust-types` owns the conservative namespace classifier so extraction,
    // contract admission, vcgen, and the native bridge cannot drift.
    // Trust #soundness (base/segment-boundary false proof, round 4): the residual
    // leak neither demotion above covers. Both of them make the BASE token unique
    // among bases; neither makes the CONCATENATION `base ++ segments` decodable. A
    // local literally named `q.0` mints the base `q.0` — character-for-character
    // what `Place { local: <the local named "q">, projections: [Field(0)] }` mints,
    // a different place over different storage. That name is unique among source
    // names and is not `_<digits>`-shaped, so it passes both prior filters.
    // Consumers that recover an obligation's subject by NAME-STRING equality then
    // accept a statement defining one of the two as the defining statement of the
    // other. `docs/audits/2026-07-30-forgery-audit-r4-verdict.md` §1 records that
    // mint against the `trust-clean` locators — `DivByZero` for a function
    // containing no division, and `NegationOverflow(W32)`; that half was not
    // re-executed here. What IS re-executed here is the collision itself:
    // `place_name_boundary_tests` drives `generate_vcs` over two asserts about two
    // different places and, without the demotion below, the whole function's
    // emitted vocabulary is the single name `q.0`.
    //
    // Fixed at the boundary, not at the shape. This function returns
    // `base ++ segments`, so make the split point recoverable from the string:
    //   (i) every segment begins with a `PROJECTION_SEGMENT_LEAD` character —
    //       enforced below where each segment is built, so it holds for the arms
    //       written today AND for any arm added later, rather than being a property
    //       someone must re-verify by reading the match; and
    //   (ii) a base contains no such character — a source name that does is
    //       ambiguous and demotes to the unique `_<local>` spelling, exactly as the
    //       two demotions above do for their shapes.
    // Therefore, for EVERY name this function returns, the base is the prefix up to
    // the first `PROJECTION_SEGMENT_LEAD` character; no base can absorb a leading
    // segment, and no `base ++ segments` can be read back as a bare base. That is a
    // decomposition argument over the whole encoding rather than an enumeration of
    // collision shapes — which is the respect in which it differs from the two
    // comments above, each of which closed one shape and left this one open.
    //
    // What this does NOT claim is injectivity on places. `place_to_var_name` stays
    // deliberately non-injective: `canonicalize_place` maps distinct places that denote the same
    // storage onto one name (that is its purpose), and two segment spellings
    // coincide by construction — a constant `Index` and the corresponding
    // `ConstantIndex` both print `[c;min=len]` (`constant_array_index_segment`
    // returns that format at :3383 and :3418, and the `ConstantIndex` arm below
    // builds it too), which names element `c` of the same base place either way.
    // The claim is only about the base/segment boundary.
    //
    // Cost, measured over crates/trust-clean/fixtures: 2326 functions, 16827
    // locals, 4923 of them source-named; 0 names contain `.`, `[`, `*` or `@` —
    // 0 contain any character outside `[A-Za-z0-9_]` at all — so this demotion
    // fires nowhere in that corpus. Re-running `generate_vcs` over all 2326 with
    // this conjunct removed hashes every VC list identically: 0 functions change,
    // 0 certificates withdrawn (trust-clean's suite is unchanged at 2460 passing).
    // Extraction has TWO local-name producers and neither applies a character
    // filter: `build_debug_name_map` copies rustc's `var_debug_info` name
    // (`trust-mir-extract/src/lib.rs:4014`) screening only for the synthetic
    // namespace (`:4028`), and `recover_direct_parameter_names` /
    // `merge_recovered_parameter_names` (`:3253-3337`, called at `:1426`) recovers
    // HIR parameter idents under the same screen (`:3320`) plus duplicate/occupancy
    // screens. So whether a rustc-produced `Symbol` can carry one of these
    // characters is NOT settled here — only that none does across the corpus
    // above. Nothing rests on that question, because the direction is fail-closed:
    // this demotion only ever SEPARATES names, never merges them. The demoted
    // spelling is `format!("_{}", place.local)` above, a function of the local index
    // alone, so no other local's whole-place can mint it (a source name spelled
    // `_<k>` is demoted by `name_is_fallback_shaped` to its OWN index), and no
    // projected place can, since every projected name carries a
    // `PROJECTION_SEGMENT_LEAD` character and `_<k>` carries none. The worst case is
    // therefore a lost fact convergence — a false-fail, never a grant.
    let name_is_fallback_shaped = |name: &str| -> bool {
        name.strip_prefix('_').and_then(|s| s.parse::<usize>().ok()).is_some()
    };
    let name_is_projection_shaped = |name: &str| -> bool { name.contains(PROJECTION_SEGMENT_LEAD) };
    let mut matching_decls = func.body.locals.iter().filter(|decl| decl.index == place.local);
    let matching_decl = matching_decls.next().filter(|_| matching_decls.next().is_none());
    let base = match matching_decl.and_then(|decl| decl.name.as_deref()) {
        Some(name)
            if func.body.locals.iter().filter(|d| d.name.as_deref() == Some(name)).count() <= 1
                && !name_is_fallback_shaped(name)
                && !name_is_projection_shaped(name)
                && trust_types::source_contract_synthetic_name_collision(name).is_none() =>
        {
            name
        }
        _ => &fallback,
    };

    if place.projections.is_empty() {
        base.to_string()
    } else {
        let projs: Vec<String> = place
            .projections
            .iter()
            .enumerate()
            .map(|(pos, p)| {
                let segment = match p {
                    Projection::Field(i) => format!(".{i}"),
                    Projection::Index(i) => constant_array_index_segment(func, place, pos, *i)
                        .unwrap_or_else(|| format!("[_{i}]")),
                    Projection::Deref => "*".to_string(),
                    Projection::Downcast(i) => format!("@{i}"),
                    Projection::OpaqueCast(_) => "@opaque_cast".to_string(),
                    Projection::UnwrapUnsafeBinder(_) => "@unwrap_unsafe_binder".to_string(),
                    Projection::ConstantIndex { offset, min_length, from_end } => {
                        if *from_end {
                            format!("[-{offset};min={min_length}]")
                        } else {
                            format!("[{offset};min={min_length}]")
                        }
                    }
                    Projection::Subslice { from, to, from_end } => {
                        if *from_end {
                            format!("[{from}..-{to}]")
                        } else {
                            format!("[{from}..{to}]")
                        }
                    }
                    // `Projection` is `#[non_exhaustive]`
                    // (`trust-types/src/model.rs:5720`), so this arm exists for
                    // variants that do not exist yet; the eight above are every
                    // variant declared today. Its `unknown` spelling has no lead
                    // character, which is exactly the hazard the wrapper below
                    // catches — a future variant would otherwise mint a segment
                    // that reads back as part of a base name.
                    _ => "unknown".to_string(),
                };
                // Half (i) of the base/segment-boundary invariant, enforced rather
                // than assumed: a segment that would not announce itself gets an
                // `@` so the decode point stays unambiguous. No-op today — every arm
                // above already starts with `.`, `[`, `*` or `@`, including all
                // three `Some` returns of `constant_array_index_segment`
                // (`[c;min=len]` at :3383 and :3418, `[c;slice]` at :3419).
                // `place_name_boundary_tests::every_projection_segment_leads` pins
                // ten spellings — one per `Projection` variant plus the `from_end`
                // twins of `ConstantIndex`/`Subslice` — and
                // `tests::arr_literal_const_index_read_name_matches_aggregate_write_name`
                // (:6706) pins `[c;min=N]`, and
                // `tests::deref_shared_slice_ref_const_index_converges` (tests.rs:7176)
                // pins `[c;slice]` as the golden string `s*[0;slice]` (:7204-7205).
                // Exactly ONE constructible spelling is pinned by no test: this wildcard
                // arm's `@unknown`. (An earlier draft said "two", missing the slice
                // golden because it grepped for the literal `c;slice` rather than for an
                // instantiated const — a coverage gap asserted, not measured.) Over
                // crates/trust-clean/fixtures the prefix fires 0 times: re-running
                // `generate_vcs` over all 2326 fixture functions with this branch
                // removed hashes every VC list identically.
                if segment.starts_with(PROJECTION_SEGMENT_LEAD) {
                    segment
                } else {
                    format!("@{segment}")
                }
            })
            .collect();
        format!("{base}{}", projs.join(""))
    }
}

