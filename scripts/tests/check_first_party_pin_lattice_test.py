        # trust-ir dependency now resolves to another repository, whose name a
        # URL-keyed scanner never matches. Inline and table forms both fail.
        fork = "https://github.com/someone/ir-fork.git"

        def inline(files: Files, revs: dict[str, str]) -> None:
            files["Cargo.toml"] += (f'\n[patch."{IR_URL}"]\n'
                                    f'trust-ir = {{ git = "{fork}", rev = "{revs["R"]}" }}\n')

        fixture = Fixture(self.tmp, clean=inline)
        line = len(clean_files("R", "G")["Cargo.toml"].splitlines()) + 3
        out = self.assertFails(
            fixture,
            f"LATTICE-L2 first-party/clean/Cargo.toml:{line} declares redirect:{fork}, "
            f"expected {fixture.revs['R']}")
        self.assertEqual(out.count("LATTICE-"), 1, out)

        def table(files: Files, revs: dict[str, str]) -> None:
            files["Cargo.toml"] += (f'\n[patch."{IR_URL}".trust-ir-build]\n'
                                    f'git = "{fork}"\nbranch = "main"\n')

        other = tempfile.TemporaryDirectory()
        try:
            fixture = Fixture(Path(other.name), cg=table)
            out = self.assertFails(fixture, f"declares redirect:{fork}, expected")
            self.assertIn("LATTICE-L1 first-party/trust-cg/Cargo.toml:", out)
        finally:
            other.cleanup()

