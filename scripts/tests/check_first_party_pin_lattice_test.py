def git_env() -> dict[str, str]:
    env = dict(os.environ)
    env.update({
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_AUTHOR_NAME": "Lattice Test",
        "GIT_AUTHOR_EMAIL": "lattice@example.invalid",
        "GIT_COMMITTER_NAME": "Lattice Test",
        "GIT_COMMITTER_EMAIL": "lattice@example.invalid",
    })
    env.pop("TRUST_IR_CLEAN_REPO", None)
    # The standing reading unless a case asks for a push.
    env.pop("TRUST_PUSHED_REFS", None)
    return env


def git(repo: Path, *args: str) -> str:
    done = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True,
                          env=git_env())
    if done.returncode != 0:
        raise AssertionError(f"git {' '.join(args)} failed: {done.stderr}")
    return done.stdout.strip()


def commit_files(repo: Path, files: Files, message: str) -> str:
    for path in list(repo.iterdir()):
        if path.name != ".git":
            shutil.rmtree(path) if path.is_dir() else path.unlink()
    for rel, content in files.items():
        target = repo / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "--allow-empty", "-m", message)
    return git(repo, "rev-parse", "HEAD")


def lock(*rows: tuple[str, str, str]) -> str:
    out = "# This file is automatically @generated by Cargo.\nversion = 4\n"
    for name, url, rev in rows:
        out += (f'\n[[package]]\nname = "{name}"\nversion = "0.14.0"\n'
                f'source = "git+{url}?rev={rev}#{rev}"\n')
    return out


