import contextlib
import importlib.util
import io
import sys
import tempfile
import tomllib
import unittest
from pathlib import Path


SCRIPT = Path(__file__).resolve().parents[1] / "trust_version_sync.py"
SPEC = importlib.util.spec_from_file_location("trust_version_sync", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
sync = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = sync
SPEC.loader.exec_module(sync)


ROOT_MANIFEST = """\
[workspace]
members = ["crates/trust-types"]

# the authority
[workspace.package]
version = "{authority}"
edition = "2024"

[workspace.dependencies]
serde = {{ version = "1" }}
"""



TYPES_MANIFEST = """\
[package]
name = "trust-types"
version.workspace = true
"""

LITERAL_MANIFEST = """\
[package]
name = "trust-literal"
version = "2.8.3"
"""

TARGO_TRUST_MANIFEST = """\
[patch.crates-io]
memchr = {{ path = "../crates/trust-memchr" }}

[package]
name = "targo-trust"
version = "{version}"
edition = "2021"

[dependencies]
serde = {{ version = "1" }}
"""

VERSION_SOURCE = """\
# header comment
schema_version = "trust.version-source.v2"
trust_product_version = "{version}"

[schemas]
version = "trust.version.v4"
"""

LOCK = """\
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "serde"
version = "{version}"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "trust-literal"
version = "2.8.3"

[[package]]
name = "trust-types"
version = "{version}"
dependencies = [
 "serde",
]

[[package]]
name = "uses-types"
version = "0.0.0"
dependencies = [
 "trust-types {version}",
]
"""


def make_tree(root: Path, authority: str, mirror: str) -> None:
    files = {
        "Cargo.toml": ROOT_MANIFEST.format(authority=authority),
        "src/version": f"{mirror}\n",
        "release/trust-version.toml": VERSION_SOURCE.format(version=mirror),
        "crates/trust-types/Cargo.toml": TYPES_MANIFEST,
        "crates/trust-literal/Cargo.toml": LITERAL_MANIFEST,
        "targo-trust/Cargo.toml": TARGO_TRUST_MANIFEST.format(version=mirror),
        "Cargo.lock": LOCK.format(version=mirror),
        # Historical evidence: never a mirror, never rewritten.
        "reports/old/Cargo.lock": LOCK.format(version=mirror),
    }
    for relative, text in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def run(argv: list[str]) -> tuple[int, str]:
    out = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
        code = sync.main(argv)
    return code, out.getvalue()


class TrustVersionSyncTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def test_check_names_every_disagreeing_mirror_and_the_fix(self) -> None:
        make_tree(self.root, "0.10.0", "0.1.0")
        code, out = run(["--check", "--root", str(self.root)])
        self.assertEqual(code, 1, out)
        for mirror in (
            "src/version",
            "release/trust-version.toml",
            "Cargo.toml",
            "targo-trust/Cargo.toml",
            "Cargo.lock",
        ):
            self.assertIn(mirror, out)
        self.assertNotIn("reports/", out)
        self.assertIn(sync.FIX, out)

    def test_write_moves_only_the_mirrored_values(self) -> None:
        make_tree(self.root, "0.10.0", "0.1.0")
        with tempfile.TemporaryDirectory() as expected_dir:
            expected = Path(expected_dir)
            make_tree(expected, "0.10.0", "0.10.0")
            code, out = run(["--write", "--no-cargo", "--root", str(self.root)])
            self.assertEqual(code, 0, out)
            for relative in (
                "src/version",
                "release/trust-version.toml",
                "Cargo.toml",
                "targo-trust/Cargo.toml",
            ):
                self.assertEqual(
                    (self.root / relative).read_text(),
                    (expected / relative).read_text(),
                    relative,
                )
            lock = tomllib.loads((self.root / "Cargo.lock").read_text())
            by_name = {p["name"]: p for p in lock["package"]}
            # Governed path package and its versioned edge move ...
            self.assertEqual(by_name["trust-types"]["version"], "0.10.0")
            self.assertEqual(by_name["uses-types"]["dependencies"], ["trust-types 0.10.0"])
            # ... a registry package at the same number and a literal-version
            # path package do not.
            self.assertEqual(by_name["serde"]["version"], "0.1.0")
            self.assertEqual(by_name["trust-literal"]["version"], "2.8.3")
            self.assertEqual(
                (self.root / "reports/old/Cargo.lock").read_text(), LOCK.format(version="0.1.0")
            )
            # Idempotent, and in sync afterwards.
            self.assertEqual(run(["--check", "--root", str(self.root)])[0], 0)
            code, out = run(["--write", "--no-cargo", "--root", str(self.root)])
            self.assertEqual(code, 0, out)
            self.assertIn("nothing to write", out)

    def test_a_nonzero_patch_authority_is_refused_and_nothing_is_written(self) -> None:
        make_tree(self.root, "0.10.1", "0.1.0")
        before = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        for argv in (["--check"], ["--write", "--no-cargo"]):
            code, out = run([*argv, "--root", str(self.root)])
            self.assertEqual(code, 1, out)
            self.assertIn("REFUSED", out)
            self.assertIn("VERSIONING.md", out)
        after = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        self.assertEqual(before, after)

    def test_suffixed_or_noncanonical_authorities_are_refused(self) -> None:
        for bad in ("0.10.0-dev.5+gabc", "0.10.0+gabc", "0.10", "00.10.0", "0.010.0"):
            with self.assertRaises(sync.SyncError, msg=bad):
                sync.validate_release_line(bad, "Cargo.toml")
        self.assertEqual(sync.validate_release_line("1.0.0", "Cargo.toml"), "1.0.0")

    def test_the_table_editor_touches_only_its_table(self) -> None:
        text = '[package]\nversion = "1"\n\n[workspace.package]\nversion = "0.1.0" # keep\n'
        updated = sync.set_toml_string(text, "workspace.package", "version", "0.10.0")
        self.assertEqual(
            updated, '[package]\nversion = "1"\n\n[workspace.package]\nversion = "0.10.0" # keep\n'
        )
        with self.assertRaises(sync.SyncError):
            sync.set_toml_string(text, "absent", "version", "0.10.0")


if __name__ == "__main__":
    unittest.main()
