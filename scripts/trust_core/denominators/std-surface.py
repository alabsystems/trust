def sha256_file(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def read_depinfo(path: Path) -> tuple[list[str], set[str]]:
    outputs, deps = [], set()
    for line in path.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        head, _, rest = line.partition(": ")
        if not rest and line.endswith(":"):
            head = line[:-1]
        if head.startswith("/"):
            outputs.append(head.rsplit("/", 1)[-1])
            deps.update(rest.split())
        else:
            deps.add(head)
    return outputs, {posixpath.normpath(d) for d in deps if not d.startswith("/")}


class HostBuild:
    """The stage1-std lib build of each crate: its dep-info (the files compiled), its cargo
    features and its build-script cfgs, each with its digest."""

    def __init__(self, root: Path, shown: str) -> None:
        self.root = root
        self.crates: dict[str, dict] = {}
        self.problem: str | None = None
        if not root.is_dir():
            self.problem = (f"{shown} does not exist: no stage1-std build of {HOST_TARGET} to read; a build of "
                            f"library/ at the recorded commit (or a byte-identical copy of its deps/, .fingerprint/ "
                            f"and build/std-*/output) unblocks it")
            return
        for crate in CRATES:
            chosen = []
            for d in sorted((root / "deps").glob(f"{crate}-*.d")):
                outputs, deps = read_depinfo(d)
                if any(o.endswith(".rlib") for o in outputs):
                    chosen.append((d, outputs, deps))
            if len(chosen) != 1:
                self.problem = (f"{shown}/deps: {len(chosen)} dep-info files of {crate} list an .rlib output "
                                f"(need exactly 1)")
                return
            d, outputs, deps = chosen[0]
            hsh = d.stem.split("-", 1)[1]
            fp = root / ".fingerprint" / d.stem / f"lib-{crate}.json"
            if not fp.is_file():
                self.problem = f"{shown}/.fingerprint/{d.stem}: missing lib-{crate}.json"
                return
            finger = json.loads(fp.read_text())
            features = json.loads(finger.get("features", "[]"))
            rustflags = finger.get("rustflags", [])
            cfg_flags = [f for f in rustflags if f.startswith("--cfg")]
            build_cfgs, outs = [], []
            if crate == "std":
                for o in sorted((root / "build").glob("std-*/output")):
                    outs.append(o)
                texts = {o.read_text() for o in outs}
                if len(texts) != 1:
                    self.problem = f"{shown}/build: {len(outs)} std build-script outputs, not one distinct text"
                    return
                build_cfgs = sorted({line.split("=", 1)[1] for line in texts.pop().splitlines()
                                     if re.match(r"cargo::?rustc-cfg=", line)})
            if cfg_flags:
                self.problem = f"{shown}: {crate}'s rustflags carry {cfg_flags}, which the evaluator does not model"
                return
            self.crates[crate] = {
                "depinfo": d, "depinfo_digest": sha256_file(d), "hash": hsh, "outputs": outputs,
                "files": {x for x in deps if x.endswith(".rs")}, "fingerprint": fp,
                "fingerprint_digest": sha256_file(fp),
                "features": features, "build_cfgs": build_cfgs,
                "build_outputs": [(str(o), sha256_file(o)) for o in outs],
            }


def pinned_host_build_absent(host: HostBuild, recorded: dict) -> str | None:
    """Why the host build `host` reads is not the one the table pins, or None when every recorded
    file is there with its recorded sha256."""
    if recorded.get("status") != "read":
        return None  # the table recorded no host build: nothing is pinned
    if host.problem:
        return host.problem
    for crate in CRATES:
        want, have = recorded.get(crate, {}), host.crates.get(crate)
        if have is None:
            return f"no {crate} build"
        if (have["depinfo_digest"] != want.get("depinfo_sha256")
                or have["fingerprint_digest"] != want.get("fingerprint_sha256")):
            return f"{crate}'s dep-info or fingerprint is not the recorded bytes"
        if sorted({d for _o, d in have["build_outputs"]}) != sorted(want.get("build_script_output_sha256", [])):
            return f"{crate}'s build-script output is not the recorded bytes"
    return None


def validate_host(meas: Measurement, host: HostBuild) -> tuple[dict, list[str]]:
    envs, problems = {}, []
    for crate in CRATES:
        info = host.crates[crate]
        env = host_env(crate, info["features"], info["build_cfgs"])
        envs[crate] = env
        w = meas.walkers[crate]
        predicted = {}
        for rel, nodes in w.files_reached.items():
            predicted.setdefault(rel, []).extend(env.chain(w.nodes[nd].decl_cfg) for nd in nodes)
        for rel, sites in w.included.items():
            predicted.setdefault(rel, []).extend(env.chain(chain) for _, chain in sites)
        predicted = {rel: True if True in vals else (False if all(v is False for v in vals) else None)
                     for rel, vals in predicted.items()}
        compiled = info["files"]
        for rel, v in sorted(predicted.items()):
            if v is True and rel not in compiled:
                problems.append(f"{crate}: {rel} evaluates compiled but is not in {info['depinfo'].name}")
            if v is False and rel in compiled:
                problems.append(f"{crate}: {rel} evaluates not compiled but {info['depinfo'].name} lists it")
            if v is None:
                problems.append(f"{crate}: {rel}: host value undetermined; dep-info says "
                                f"{'compiled' if rel in compiled else 'not compiled'}")
        for rel in sorted(compiled - set(predicted)):
            problems.append(f"{crate}: {info['depinfo'].name} lists {rel}, which the module tree does not reach")
    return envs, problems


