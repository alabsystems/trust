def self_test() -> int:
    """The predicates on synthetic sources whose every count is known: comments, raw strings,
    char literals, a fn-pointer type, an unsafe attribute, #[path], a non-mod-rs child, cfg_select
    arms, an orphan file, forwarded, let-bound and literal orderings, slice-shaped swaps, the intrinsic and
    wrapper tiers and two sync entry points."""
    tree = C.DirTree(Path("/nonexistent-std-surface-self-test"), SELF_TEST_FILES)
    meas = Measurement(Path("."), "", tree)
    meas.run()
    host = HostBuild(Path("/nonexistent-std-surface-self-test"), "self-test")
    report = build_report(meas, host, None, [])
    got = {r["name"]: r["value"] for r in report["rows"]}
    bad = {k: (v, got.get(k)) for k, v in SELF_TEST_EXPECT.items() if got.get(k) != v}
    labels = {nd.file: nd.cfg for nd in meas.walkers["core"].nodes}
    for rel, want in (("library/core/src/b.rs", ("unix",)), ("library/core/src/d.rs", ("unix",)),
                      ("library/core/src/e.rs", ("not(unix)",)), ("library/core/src/a/t.rs", ("test",))):
        if labels.get(rel) != want:
            bad[f"cfg label of {rel}"] = (want, labels.get(rel))
    for k, (want, have) in sorted(bad.items()):
        print(f"{KEY}: self-test: {k}: want {want}, got {have}", file=sys.stderr)
    print(f"{KEY}: self-test {'FAILED' if bad else 'passed'} ({len(SELF_TEST_EXPECT) + 4} checks)")
    return 1 if bad else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--repo", type=Path, default=C.REPO_ROOT)
    ap.add_argument("--rev", default="HEAD")
    ap.add_argument("--host-build", type=Path, help=f"default: <repo>/{DEFAULT_HOST_BUILD}")
    ap.add_argument("--record", type=Path, help=f"the table (default <repo>/{TABLE_REL})")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--current", action="store_true", help="with --check: a stale table fails")
    ap.add_argument("--sites", metavar="KIND")
    ap.add_argument("--self-test", action="store_true", help="run the predicates on synthetic sources")
    args = ap.parse_args(argv)
    if args.self_test:
        return self_test()
    table = args.record or args.repo / TABLE_REL
    rev = args.rev
    recorded = None
    if args.check:
        if not table.is_file():
            print(f"{KEY}: {TABLE_REL} is missing", file=sys.stderr)
            return 1
        recorded = C.tomllib.loads(table.read_text())["inputs"]["source"]
        rev = recorded["commit"]
    try:
        meas = Measurement(args.repo, rev)
        meas.run()
    except InputError as e:
        print(f"{KEY}: {e}", file=sys.stderr)
        return 2
    except ParseError as e:
        print(f"{KEY}: parse failure: {e}", file=sys.stderr)
        return 1
    host = HostBuild(args.host_build or args.repo / DEFAULT_HOST_BUILD,
                     "--host-build" if args.host_build else DEFAULT_HOST_BUILD)
    if args.check:
        absent = pinned_host_build_absent(host, C.tomllib.loads(table.read_text())["inputs"]["host_build"])
        if absent:
            print(f"{KEY}: UNAVAILABLE: the pinned stage1-std build is not on this host ({absent}); the table "
                  "cannot be re-measured here. Re-measure on a host whose build/ or artifact cache holds the "
                  "recorded files (scripts/trust_core/denominators.py --stash copies them, digest-checked), or pass "
                  "--host-build <a byte-identical copy>", file=sys.stderr)
            return 3
    envs, problems = (None, []) if host.problem else validate_host(meas, host)
    report = build_report(meas, host, envs, problems)
    if args.sites:
        seen = set()
        for s in sorted(meas.sites, key=lambda s: (s.crate, s.file, s.pos)):
            if s.kind == args.sites and (s.crate, s.file, s.pos) not in seen:
                seen.add((s.crate, s.file, s.pos))
                print(f"{s.crate}\t{s.op}\t{s.file}:{s.line}\t{s.detail}\t{s.macro}\t{' && '.join(s.cfg)}")
        if args.sites == "unreached":
            for crate, files in report["unreached"].items():
                for f in files:
                    print(f"{crate}\t{f}")
        return 0
    text = render_toml(meas, host, problems, report)
    if args.write:
        table.parent.mkdir(parents=True, exist_ok=True)
        table.write_text(text)
    for row in report["rows"]:
        shown = row["value"] if row["status"] == "measured" else f"BLOCKED ({row.get('blocked', '')})"
        print(f"{row['name']:<44} {shown}")
    if problems:
        print(f"{KEY}: host validation: {len(problems)} disagreement(s); host rows blocked", file=sys.stderr)
    if args.check:
        status = 0
        if table.read_text() != text:
            print(f"{KEY}: {TABLE_REL} is not reproduced by a measurement at {rev}", file=sys.stderr)
            status = 1
        else:
            print(f"{KEY}: {TABLE_REL} reproduced at {rev}")
        now = C.git(args.repo, "rev-parse", f"{args.rev}:library")
        if (now or "").strip() != recorded["trees"]["library"]:
            print(f"{KEY}: library/ at {args.rev} differs from the recorded tree: the table is stale",
                  file=sys.stderr)
            status = status or (1 if args.current else 0)
        return status
    return 0


if __name__ == "__main__":
    sys.exit(main())
