TOKEN = re.compile(r"""
  (?P<ws>\s+)
| (?P<lc>//[^\n]*)
| (?P<bc>/\*)
| (?P<raw>(?:br|cr|r)\#*")
| (?P<str>[bc]?"(?:[^"\\]|\\.)*")
| (?P<chr>b?'(?:[^'\\\n\r\t]|\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F_]{1,6}\}|[nrt\\0'"]))')
| (?P<life>'(?:r\#)?[^\W\d]\w*)
| (?P<id>(?:r\#)?[^\W\d]\w*)
| (?P<num>\d\w*(?:\.\d\w*)?)
| (?P<p>::|=>|->|\.\.=|\.\.\.|\.\.|[^\s\w])
""", re.X | re.S)
BLOCK_EDGE = re.compile(r"/\*|\*/")
UNSAFE_WORD = re.compile(r"\bunsafe\b")
OPEN, CLOSE = "([{", ")]}"


class Lexed:
    """One file's tokens: parallel lists of kind (i ident, l lifetime, s string, c char, n number,
    p punctuation), text and start offset, the matching delimiter of every bracket, and the
    `unsafe` words seen inside comments and literals."""

    def __init__(self, rel: str, text: str) -> None:
        self.rel = rel
        if text.startswith("﻿"):
            text = text[1:]
        self.text = text
        kinds, texts, starts = [], [], []
        self.comment_unsafe = self.literal_unsafe = 0
        pos, n = 0, len(text)
        if text.startswith("#!") and not text.startswith("#!["):
            pos = text.find("\n") if "\n" in text else n
        while pos < n:
            m = TOKEN.match(text, pos)
            if m is None:
                raise ParseError(f"{rel}:{self.line(pos)}: no token at {text[pos:pos + 20]!r}")
            g = m.lastgroup
            if g == "ws":
                pos = m.end()
                continue
            if g == "lc":
                self.comment_unsafe += len(UNSAFE_WORD.findall(m.group()))
                pos = m.end()
                continue
            if g == "bc":
                depth, p = 1, m.end()
                while depth:
                    e = BLOCK_EDGE.search(text, p)
                    if e is None:
                        raise ParseError(f"{rel}:{self.line(pos)}: unterminated block comment")
                    depth += 1 if e.group() == "/*" else -1
                    p = e.end()
                self.comment_unsafe += len(UNSAFE_WORD.findall(text, pos, p))
                pos = p
                continue
            if g == "raw":
                hashes = m.group().count("#")
                end = text.find('"' + "#" * hashes, m.end())
                if end < 0:
                    raise ParseError(f"{rel}:{self.line(pos)}: unterminated raw string")
                end += 1 + hashes
                self.literal_unsafe += len(UNSAFE_WORD.findall(text, pos, end))
                kinds.append("s"); texts.append(text[pos:end]); starts.append(pos)
                pos = end
                continue
            tok = m.group()
            kind = {"str": "s", "chr": "c", "life": "l", "id": "i", "num": "n", "p": "p"}[g]
            if kind == "s":
                self.literal_unsafe += len(UNSAFE_WORD.findall(tok))
            kinds.append(kind); texts.append(tok); starts.append(pos)
            pos = m.end()
        self.kinds, self.texts, self.starts = kinds, texts, starts
        match = [-1] * len(texts)
        stack = []
        for i, t in enumerate(texts):
            if kinds[i] != "p":
                continue
            if t in OPEN:
                stack.append(i)
            elif t in CLOSE:
                if not stack or OPEN.index(texts[stack[-1]]) != CLOSE.index(t):
                    raise ParseError(f"{rel}:{self.line(starts[i])}: unbalanced {t!r}")
                j = stack.pop()
                match[i], match[j] = j, i
        if stack:
            raise ParseError(f"{rel}:{self.line(starts[stack[-1]])}: unclosed {texts[stack[-1]]!r}")
        self.match = match
        self._nl = None

    def line(self, offset: int) -> int:
        if self._nl is None:
            self._nl = [i for i, ch in enumerate(self.text) if ch == "\n"]
        return bisect.bisect_right(self._nl, offset - 1) + 1

    def tline(self, i: int) -> int:
        return self.line(self.starts[i])


def string_value(tok: str) -> str | None:
    """The value of a plain or raw string literal token (no prefix), or None."""
    if tok.startswith('"') and tok.endswith('"'):
        return re.sub(r"\\(.)", r"\1", tok[1:-1])
    m = re.fullmatch(r'r(#*)"(.*)"\1', tok, re.S)
    return m.group(2) if m else None


