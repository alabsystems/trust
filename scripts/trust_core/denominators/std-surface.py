class Measurement:
    def __init__(self, repo: Path, rev: str, tree=None) -> None:
        self.repo = repo
        if tree is not None:            # --self-test: a DirTree of synthetic files
            self.commit, self.tree = "0" * 40, tree
        else:
            self.commit = (C.git(repo, "rev-parse", "--verify", f"{rev}^{{commit}}") or "").strip()
            if not C.HEX40.match(self.commit):
                raise InputError(f"{rev}: not a commit of {repo}")
            self.tree = C.GitTree(repo, self.commit)
        self.lexed: dict[str, Lexed] = {}
        self.facts: dict[str, FileFacts] = {}
        self.walkers: dict[str, Walker] = {}
        self.sites: list[Site] = []

    def tree_pins(self) -> dict:
        return {root: (C.git(self.repo, "rev-parse", f"{self.commit}:{root}") or "").strip()
                for root in ("library", "library/core", "library/alloc", "library/std", "library/stdarch",
                             "library/portable-simd", "library/backtrace")}

    def run(self) -> None:
        self.tree.prefetch(self.tree.files("library/", (".rs",)))
        for crate in CRATES:
            w = Walker(self.tree, self.lexed, crate)
            w.run()
            self.walkers[crate] = w
        self.api = derive_atomic_api(self.lexed[ATOMIC_RS], self.walkers["core"].lex(INTRINSICS_RS))
        for crate, w in self.walkers.items():
            for rel, ctxs in w.contexts:
                self.classify(crate, self.lexed[rel], ctxs)

    def file_facts(self, lx: Lexed) -> FileFacts:
        if lx.rel not in self.facts:
            self.facts[lx.rel] = FileFacts(lx)
        return self.facts[lx.rel]

    def classify(self, crate: str, lx: Lexed, ctxs: list) -> None:
        t, k, starts = lx.texts, lx.kinds, lx.starts
        api = self.api
        in_sync_file = bool(SYNC_FILES.match(lx.rel))
        facts = None
        for i in range(len(t)):
            ctx = ctxs[i]
            if ctx is None:
                raise ParseError(f"{lx.rel}:{lx.tline(i)}: token {t[i]!r} was not reached by the scanner")
            if k[i] != "i":
                continue
            tok = t[i]
            macro = f"{ctx.macro[0]}:{ctx.macro[1]}" if ctx.macro else ""

            def site(kind, op, detail=""):
                self.sites.append(Site(kind, op, crate, ctx.node, lx.rel, lx.tline(i), starts[i], ctx.cfg, macro,
                                       detail))

            if tok == "unsafe":
                kind, detail = classify_unsafe(lx, i, ctx)
                site("unsafe", kind, detail)
                continue
            if ctx.attr or (i and t[i - 1] == "fn"):
                continue
            op = call_open(lx, i)
            if op is None:
                continue
            prev = t[i - 1] if i else ""
            args = call_args(lx, op)
            path = callee_path(lx, i)
            if tok in api.methods and (prev == "." or (len(path) >= 2 and re.fullmatch(r"Atomic\w*", path[-2]))):
                if facts is None:
                    facts = self.file_facts(lx)
                self.method_site(lx, i, tok, args, 0 if prev == "." else 1, facts, site)
                continue
            if prev == ".":
                continue
            if api.free.get(tok) == "fence":
                site("A-fence", tok, ",".join(ordering_literal(lx, a, b) or "?" for a, b in args))
                continue
            if tok in api.intrinsics or tok in api.free:
                if facts is None:
                    facts = self.file_facts(lx)
                qual = path[-2] if len(path) >= 2 else ""
                if tok in api.intrinsics and (qual == "intrinsics" or (len(path) == 1 and tok in facts.intrinsic_uses)):
                    site("A-intrinsic", tok, ",".join(t[x] for x in range(i + 1, op) if t[x] in ORDERINGS))
                elif tok in api.free and (qual == "atomic" or (len(path) == 1 and lx.rel == ATOMIC_RS)):
                    site("A-wrapper", tok, ",".join(o for o in (ordering_literal(lx, a, b) for a, b in args) if o))
                else:
                    site("A-unresolved", tok, "::".join(path))
                continue
            entry = sync_entry(path, in_sync_file)
            if tok == "syscall" and args and any(t[x].startswith("SYS_futex") for x in range(*args[0])):
                entry = "syscall[SYS_futex]"
            elif tok == "syscall":
                entry = None
            if entry is not None:
                site("S", entry, "::".join(path))
                continue
            if in_sync_file:
                if facts is None:
                    facts = self.file_facts(lx)
                if (len(path) >= 2 and path[-2] in RESIDUE_QUALIFIERS) or (len(path) == 1 and tok in facts.foreign):
                    site("residue", tok, "::".join(path))

    def ordering_arg(self, lx: Lexed, lo: int, hi: int, params: frozenset,
                     facts: FileFacts | None = None, at: int | None = None) -> str | None:
        """An Ordering literal's variant, "param:<name>" for a parameter of the enclosing fn typed
        Ordering, "call:<fn>" for a call of an atomic.rs fn returning Ordering, "local:<name>" for a
        local bound to an Ordering (see PREDICATE A), else None."""
        lit = ordering_literal(lx, lo, hi)
        if lit:
            return lit
        t, k = lx.texts, lx.kinds
        if hi - lo == 1 and k[lo] == "i" and t[lo] in params:
            return f"param:{t[lo]}"
        if hi - lo >= 3 and k[lo] == "i" and t[lo] in self.api.ordering_fns and t[lo + 1] == "(" and \
                lx.match[lo + 1] == hi - 1:
            return f"call:{t[lo]}"
        if hi - lo == 1 and k[lo] == "i" and facts is not None and at is not None:
            binding = facts.local_binding(at, t[lo])
            if binding is not None:
                typed, ilo, ihi = binding
                if typed or self.ordering_value(lx, ilo, ihi, params):
                    return f"local:{t[lo]}"
        return None

    def ordering_value(self, lx: Lexed, lo: int, hi: int, params: frozenset) -> bool:
        """Whether the expression tokens [lo, hi) yield an Ordering: a literal, a parameter, a call
        (ordering_arg's first three forms) or a `match` each of whose arms yields one or diverges."""
        if self.ordering_arg(lx, lo, hi, params):
            return True
        t, m = lx.texts, lx.match
        if hi - lo < 3 or t[lo] != "match" or t[hi - 1] != "}":
            return False
        brace = m[hi - 1]
        if not lo < brace < hi - 1:
            return False
        x, arms = brace + 1, 0
        while x < hi - 1:
            while x < hi - 1 and t[x] != "=>":        # the arm's pattern (and guard)
                x = m[x] + 1 if t[x] in OPEN else x + 1
            if x >= hi - 1:
                return False
            x += 1
            if t[x] == "{":
                rlo, rhi, x = x + 1, m[x], m[x] + 1
                if rhi - rlo and t[rhi - 1] == ";":
                    rhi -= 1
            else:
                rlo = x
                while x < hi - 1 and t[x] != ",":
                    x = m[x] + 1 if t[x] in OPEN else x + 1
                rhi = x
            if x < hi - 1 and t[x] == ",":
                x += 1
            arms += 1
            diverges = (rhi - rlo >= 3 and t[rlo] in ("panic", "unreachable") and t[rlo + 1] == "!"
                        and t[rlo + 2] in OPEN and m[rlo + 2] == rhi - 1)
            if not diverges and not self.ordering_arg(lx, rlo, rhi, params):
                return False
        return arms > 0

    def method_site(self, lx: Lexed, i: int, name: str, args: list, offset: int, facts: FileFacts, site) -> None:
        for arity, positions in sorted(self.api.methods[name]):
            if len(args) != arity + offset:
                continue
            params = facts.ordering_params(i)
            orders = [self.ordering_arg(lx, *args[p + offset], params, facts, i) for p in positions]
            shown = ",".join(o or "?" for o in orders)
            if all(o in ORDERINGS for o in orders):
                site("A-method", name, shown)
            elif all(orders):
                site("A-method", name, shown + ";forwarded")
            else:
                site("A-method-unconfirmed", name, shown)
            return


