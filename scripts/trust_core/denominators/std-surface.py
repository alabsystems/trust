UNSAFE_KINDS = ("block", "fn", "impl", "trait")
UNSAFE_LABELS = ("extern-block", "attribute", "fn-pointer-type", "binder-type", "macro-syntax")


def classify_unsafe(lx: Lexed, i: int, ctx: Ctx) -> tuple[str, str]:
    t, k = lx.texts, lx.kinds
    n = len(t)
    if ctx.attr:
        return "attribute", ""
    j = i + 1
    nxt = t[j] if j < n else ""
    if nxt == "{":
        return "block", ""
    if nxt == "impl":
        return "impl", ""
    if nxt == "trait" or (nxt == "auto" and j + 1 < n and t[j + 1] == "trait"):
        return "trait", ""
    if nxt == "<":
        return "binder-type", ""
    if nxt == "extern":
        j += 1
        if j < n and k[j] == "s":
            j += 1
        if j < n and t[j] == "{":
            return "extern-block", ""
    if j < n and t[j] == "fn":
        after = t[j + 1] if j + 1 < n else ""
        if after == "(":
            return "fn-pointer-type", ""
        if (j + 1 < n and k[j + 1] == "i") or after == "$":
            # a body, or a declaration ending in `;`
            x = j + 1
            m = lx.match
            while x < n and t[x] not in ("{", ";"):
                x = m[x] + 1 if t[x] in ("(", "[") else x + 1
            return "fn", ("decl" if x < n and t[x] == ";" else "body")
    return "macro-syntax", nxt


def call_args(lx: Lexed, open_i: int) -> list[tuple[int, int]]:
    t, m = lx.texts, lx.match
    close = m[open_i]
    args, a, x = [], open_i + 1, open_i + 1
    while x < close:
        if t[x] in OPEN:
            x = m[x] + 1
            continue
        if t[x] == ",":
            args.append((a, x))
            a = x + 1
        x += 1
    if a < close:
        args.append((a, close))
    return args


def ordering_literal(lx: Lexed, lo: int, hi: int) -> str | None:
    t, k = lx.texts, lx.kinds
    if hi <= lo or t[hi - 1] not in ORDERINGS:
        return None
    for x in range(lo, hi):
        if not (k[x] == "i" or t[x] == "::"):
            return None
    return t[hi - 1]


def callee_path(lx: Lexed, i: int) -> list[str]:
    """The path segments ending at identifier i (`a::b::name` -> [a, b, name])."""
    t, k = lx.texts, lx.kinds
    segs = [t[i]]
    x = i - 1
    while x >= 1 and t[x] == "::" and k[x - 1] == "i":
        segs.insert(0, t[x - 1])
        x -= 2
    return segs


def call_open(lx: Lexed, i: int) -> int | None:
    """For identifier i, the index of the `(` that calls it (through an optional turbofish)."""
    t = lx.texts
    n = len(t)
    j = i + 1
    if j + 1 < n and t[j] == "::" and t[j + 1] == "<":
        depth, x = 0, j + 1
        while x < n:
            if t[x] == "<":
                depth += 1
            elif t[x] == ">":
                depth -= 1
                if depth == 0:
                    break
            elif t[x] == "->":
                pass
            elif t[x] in OPEN:
                x = lx.match[x]
            x += 1
        j = x + 1
    return j if j < n and t[j] == "(" else None


class AtomicApi(NamedTuple):
    methods: dict             # name -> frozenset of (arity without self, Ordering positions)
    free: dict                # name -> "fence" | "wrapper"
    intrinsics: frozenset
    ordering_fns: frozenset   # atomic.rs functions returning an Ordering


def fn_signatures(lx: Lexed):
    """(name, params as token ranges, return type tokens, body range or None) of every
    `fn NAME` in a file (macro definition bodies included)."""
    t, k, m = lx.texts, lx.kinds, lx.match
    n = len(t)
    for i in range(n - 2):
        if t[i] != "fn" or k[i + 1] != "i":
            continue
        x = i + 2
        if t[x] == "<":
            depth = 0
            while x < n:
                if t[x] == "<":
                    depth += 1
                elif t[x] == ">":
                    depth -= 1
                    if depth == 0:
                        break
                elif t[x] in OPEN:
                    x = m[x]
                x += 1
            x += 1
        if x >= n or t[x] != "(":
            continue
        params = call_args(lx, x)
        y = m[x] + 1
        ret_lo = y + 1 if y < n and t[y] == "->" else None
        while y < n and t[y] not in ("{", ";", "where"):
            y = m[y] + 1 if t[y] in ("(", "[") else y + 1
        ret = tuple(t[ret_lo:y]) if ret_lo is not None else ()
        while y < n and t[y] not in ("{", ";"):
            y = m[y] + 1 if t[y] in ("(", "[") else y + 1
        body = (y, m[y]) if y < n and t[y] == "{" else None
        yield t[i + 1], params, ret, body


def param_types(lx: Lexed, params: list) -> list[tuple[str, tuple]]:
    """(binding name or "", type tokens) of each parameter."""
    t = lx.texts
    out = []
    for lo, hi in params:
        colon = next((x for x in range(lo, hi) if t[x] == ":"), None)
        if colon is None:
            out.append(("self" if "self" in t[lo:hi] else "", tuple(t[lo:hi])))
        else:
            names = [t[x] for x in range(lo, colon) if lx.kinds[x] == "i" and t[x] != "mut"]
            out.append((names[-1] if names else "", tuple(t[colon + 1:hi])))
    return out


def derive_atomic_api(atomic: Lexed, intrinsics_rs: Lexed) -> AtomicApi:
    t = atomic.texts
    intrinsics = frozenset(name for name, _, _, _ in fn_signatures(intrinsics_rs) if name.startswith("atomic_"))
    methods: dict[str, set] = collections.defaultdict(set)
    free: dict[str, str] = {}
    ordering_fns = set()
    for name, params, ret, body in fn_signatures(atomic):
        if ret == ("Ordering",):
            ordering_fns.add(name)
        typed = param_types(atomic, params)
        ords = tuple(n for n, (_, ty) in enumerate(typed) if ty == ("Ordering",))
        if not ords:
            continue
        if typed and typed[0][0] == "self":
            methods[name].add((len(params) - 1, tuple(o - 1 for o in ords)))
        elif body is not None and any(t[x] == "intrinsics" and t[x + 1] == "::" and t[x + 2] in intrinsics
                                      for x in range(body[0], body[1])):
            free[name] = "wrapper" if name.startswith("atomic_") else "fence"
    return AtomicApi({n: frozenset(s) for n, s in methods.items()}, free, intrinsics, frozenset(ordering_fns))


class FileFacts:
    """Per-file facts the call classification needs: `use`d intrinsic names, locally defined fn
    names, foreign fn names declared in extern blocks, and the Ordering-typed parameters of
    every fn body."""

    def __init__(self, lx: Lexed) -> None:
        t, k, m = lx.texts, lx.kinds, lx.match
        n = len(t)
        self.intrinsic_uses: set[str] = set()
        for i in range(n):
            if t[i] != "use" or k[i] != "i":
                continue
            e = i
            while e < n and t[e] != ";":
                e += 1
            for x in range(i, e - 2):
                if t[x] == "intrinsics" and t[x + 1] == "::":
                    if t[x + 2].startswith("atomic_"):
                        self.intrinsic_uses.add(t[x + 2])
                    elif t[x + 2] == "{":
                        self.intrinsic_uses.update(y for y in t[x + 3:m[x + 2]] if y.startswith("atomic_"))
        self.defined: set[str] = set()
        self.scopes: list[tuple[int, int, frozenset]] = []
        # (let index, name, typed `Ordering`, initializer token range) of every `let NAME` binding
        self.lets: list[tuple[int, str, bool, int, int]] = []
        for name, params, _, body in fn_signatures(lx):
            self.defined.add(name)
            if body is not None:
                ords = frozenset(b for b, ty in param_types(lx, params) if ty == ("Ordering",) and b)
                self.scopes.append((body[0], body[1], ords))
        for i in range(n - 2):
            if t[i] != "let" or k[i] != "i":
                continue
            x = i + 1
            if t[x] == "mut":
                x += 1
            if x + 1 >= n or k[x] != "i" or t[x + 1] not in (":", "="):
                continue  # a pattern, not a plain binding
            bound, y = t[x], x + 1
            typed = False
            if t[y] == ":":
                z = y + 1
                while z < n and t[z] not in ("=", ";"):
                    z = m[z] + 1 if t[z] in OPEN else z + 1
                typed = tuple(t[y + 1:z]) in (("Ordering",), ("atomic", "::", "Ordering"))
                y = z
            if y >= n or t[y] != "=":
                continue
            z = y + 1
            while z < n and t[z] != ";":
                z = m[z] + 1 if t[z] in OPEN else z + 1
            self.lets.append((i, bound, typed, y + 1, z))
        self.foreign: set[str] = set()
        for i in range(n - 1):
            if t[i] == "extern" and k[i] == "i":
                j = i + 1
                if j < n and k[j] == "s":
                    j += 1
                if j < n and t[j] == "{":
                    for x in range(j + 1, m[j] - 1):
                        if t[x] == "fn" and k[x + 1] == "i":
                            self.foreign.add(t[x + 1])

    def scope(self, i: int) -> tuple[int, int, frozenset] | None:
        """The innermost fn body holding token i."""
        best = None
        for sc in self.scopes:
            if sc[0] < i < sc[1] and (best is None or sc[0] > best[0]):
                best = sc
        return best

    def ordering_params(self, i: int) -> frozenset:
        sc = self.scope(i)
        return sc[2] if sc else frozenset()

    def local_binding(self, i: int, name: str) -> tuple[bool, int, int] | None:
        """(typed `Ordering`, initializer range) of the nearest `let name` before token i inside
        the innermost fn body holding i, or None."""
        sc = self.scope(i)
        if sc is None:
            return None
        found = None
        for at, bound, typed, lo, hi in self.lets:
            if bound == name and sc[0] < at < i and hi <= i:
                found = (typed, lo, hi)
        return found


def sync_entry(path: list[str], in_sync_file: bool) -> str | None:
    """The SYNC_BACKEND entry a callee path names, or None."""
    last2 = "::".join(path[-2:])
    for scope, names in SYNC_BACKEND.values():
        if scope == "sync-files" and not in_sync_file:
            continue
        for name in names:
            if ("::" in name and last2 == name) or name == path[-1]:
                return name
    return None


