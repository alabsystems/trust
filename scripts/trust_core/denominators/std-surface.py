def source_tree(rel: str) -> str:
    return next((s.rstrip("/") for s in SOURCE_TREES if rel.startswith(s)), posixpath.dirname(rel))


def tri(vals) -> object:
    vals = list(vals)
    return True if True in vals else (False if vals and all(v is False for v in vals) else None)


def tv(v) -> str:
    return {True: "true", False: "false", None: "undetermined"}[v]


def crate_files(w: Walker) -> list[str]:
    return sorted(set(w.files_reached) | set(w.included))


