def render(lx: Lexed, lo: int, hi: int) -> str:
    out = []
    for i in range(lo, hi):
        t = lx.texts[i]
        if t in (")", ",") or (t == "(" and out):
            out.append(t)
        elif out and out[-1].endswith("("):
            out.append(t)
        elif t == "=" or (out and out[-1] == "="):
            out.append(" " + t)
        elif out and out[-1] == ",":
            out.append(" " + t)
        elif out:
            out.append(" " + t)
        else:
            out.append(t)
    return "".join(out).replace(" (", "(")


CFG_TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"|[^\W\d][\w.]*|\$\w+|[(),=]|\S')


def parse_cfg(text: str):
    toks = CFG_TOKEN.findall(text)
    pos = 0

    def pred():
        nonlocal pos
        if pos >= len(toks):
            raise ValueError(text)
        t = toks[pos]
        pos += 1
        if t.startswith("$"):
            return ("macro", t)
        if pos < len(toks) and toks[pos] == "(":
            pos += 1
            args = []
            while toks[pos] != ")":
                args.append(pred())
                if toks[pos] == ",":
                    pos += 1
            pos += 1
            return (t, args)
        if pos < len(toks) and toks[pos] == "=":
            v = toks[pos + 1]
            pos += 2
            return ("kv", t, v[1:-1] if v.startswith('"') else v)
        return ("name", t)

    tree = pred()
    if pos != len(toks):
        raise ValueError(text)
    return tree


class HostEnv:
    def __init__(self, names: set, pairs: set, unknown: frozenset) -> None:
        self.names, self.pairs, self.unknown = names, pairs, unknown
        self._cache: dict[str, object] = {}

    def eval_text(self, text: str):
        if text not in self._cache:
            try:
                self._cache[text] = self.eval(parse_cfg(text))
            except (ValueError, IndexError):
                self._cache[text] = None
        return self._cache[text]

    def eval(self, tree):
        tag = tree[0]
        if tag == "name":
            n = tree[1]
            if n in ("true", "false"):
                return n == "true"
            return None if n in self.unknown else n in self.names
        if tag == "kv":
            return None if tree[1] in self.unknown else (tree[1], tree[2]) in self.pairs
        if tag == "macro":
            return None
        vals = [self.eval(a) for a in tree[1]]
        if tag == "all":
            return False if False in vals else (True if all(v is True for v in vals) else None)
        if tag == "any":
            return True if True in vals else (False if all(v is False for v in vals) else None)
        if tag == "not" and len(vals) == 1:
            return None if vals[0] is None else not vals[0]
        return None

    def chain(self, chain: tuple):
        vals = [self.eval_text(c) for c in chain]
        return False if False in vals else (True if all(v is True for v in vals) else None)


def host_env(crate: str, features: list[str], build_cfgs: list[str]) -> HostEnv:
    names, pairs = set(), set()
    for line in HOST_PRINT_CFG.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            pairs.add((k, v.strip('"')))
        elif line:
            names.add(line)
    names -= HOST_UNKNOWN
    pairs = {p for p in pairs if p[0] not in HOST_UNKNOWN}
    pairs |= {("feature", f) for f in features}
    names |= set(build_cfgs)
    return HostEnv(names, pairs, HOST_UNKNOWN)


