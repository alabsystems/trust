def build_report(meas: Measurement, host: HostBuild, envs: dict | None, problems: list[str]) -> dict:
    host_ok = envs is not None and not problems and host.problem is None
    reason = host.problem or ("host validation failed: " + "; ".join(problems[:5]) +
                              (f"; and {len(problems) - 5} more" if len(problems) > 5 else "")
                              if problems else None)
    rows, modules, lists, site_files = [], [], [], collections.Counter()
    unreached = {}

    def add(name, kind, crate, value, inputs, breakdown=None, status="measured", why=None):
        pred = PREDICATES[kind].replace("{crate}", crate).replace("{host}", HOST_TARGET)
        pred = pred.replace("{kind}", name.split(".")[-1]) + f"; in `{crate}`"
        row = {"name": name, "value": value, "status": status, "predicate": pred, "inputs": inputs}
        if why:
            row["blocked"] = why
            row["unblock"] = HOST_UNBLOCK
        if breakdown:
            row["breakdown"] = breakdown
        rows.append(row)

    src, hst = ["source"], ["source", "host_build", "host_cfg"]
    # one entry per (crate, kind, file, position); cfg chains of every inclusion kept
    uniq: dict[tuple, list[Site]] = collections.defaultdict(list)
    for s in meas.sites:
        uniq[(s.crate, s.kind, s.file, s.pos)].append(s)
    by_node: dict[tuple, list[Site]] = collections.defaultdict(list)
    for s in meas.sites:
        if s.kind == "unsafe":
            by_node[(s.crate, s.node)].append(s)

    def host_of(crate, sites):
        return tri(envs[crate].chain(s.cfg) for s in sites) if host_ok else None

    for crate in CRATES:
        w = meas.walkers[crate]
        env = envs[crate] if host_ok else None
        # a MODULE is (module path, file, inline path): declarations of one module under exclusive
        # cfg branches (a `doc` arm and a platform arm, say) are one module whose label is the
        # disjunction of their chains
        groups: dict[tuple, list[int]] = collections.defaultdict(list)
        for idx, nd in enumerate(w.nodes):
            groups[(nd.path, nd.file, nd.inline)].append(idx)
        mods = []
        for key, idxs in groups.items():
            q, broad, seen, hvs, hns = [], [], set(), [], []
            for idx in idxs:
                nd = w.nodes[idx]
                sites = by_node.get((crate, idx), [])
                nq = [x for x in sites if x.op in UNSAFE_KINDS]
                for x in sites:
                    if x.pos not in seen and x.op in UNSAFE_KINDS + ("extern-block", "attribute", "macro-syntax"):
                        broad.append(x)
                        if x.op in UNSAFE_KINDS:
                            q.append(x)
                        seen.add(x.pos)
                if env:
                    hn = env.chain(nd.cfg)
                    hq = tri(env.chain(x.cfg) for x in nq)
                    hns.append(hn)
                    hvs.append(False if hn is False else (True if hn is True and hq is True else
                                                          (False if hq is False else None)))
            chains = list(dict.fromkeys(w.nodes[i].cfg for i in idxs))
            mods.append({"key": key, "idxs": idxs, "chains": chains, "q": q, "broad": broad,
                         "host_module": tri(hns) if env else None, "host": tri(hvs) if env else None,
                         "decls": [w.nodes[i].decl for i in idxs if w.nodes[i].decl]})
        unsafe_mods = [x for x in mods if x["q"]]
        units = sorted({(x["key"][1], x["key"][2]) for x in unsafe_mods})

        def gated(x, name=None):
            return all((name in c) if name else bool(c) for c in x["chains"])

        add(f"modules.{crate}", "modules", crate, len(mods), src,
            {"by_source_tree": dict(sorted(collections.Counter(source_tree(x["key"][1]) for x in mods).items())),
             "inline_modules": sum(1 for x in mods if x["key"][2]),
             "cfg_gated": sum(1 for x in mods if gated(x)),
             "declared_under_several_chains": sum(1 for x in mods if len(x["chains"]) > 1)})
        add(f"unsafe_modules.{crate}", "unsafe_modules", crate, len(unsafe_mods), src,
            {"by_source_tree": dict(sorted(collections.Counter(source_tree(x["key"][1]) for x in unsafe_mods).items())),
             "inline_modules": sum(1 for x in unsafe_mods if x["key"][2]),
             "cfg_gated": sum(1 for x in unsafe_mods if gated(x)),
             "cfg_test_gated": sum(1 for x in unsafe_mods if gated(x, "test")),
             "only_in_macro_definitions": sum(1 for x in unsafe_mods
                                              if all(s.macro.startswith("def:") for s in x["q"]))})
        add(f"unsafe_source_units.{crate}", "unsafe_source_units", crate, len(units), src)
        add(f"unsafe_modules_broad.{crate}", "unsafe_modules_broad", crate, sum(1 for x in mods if x["broad"]), src)
        kinds = collections.Counter()
        labels = collections.Counter()
        for (c, kind, _, _), group in uniq.items():
            if c != crate or kind != "unsafe":
                continue
            s = group[0]
            kinds[s.op] += 1
            if s.op == "fn":
                labels["fn", "with_body" if s.detail == "body" else "declaration"] += 1
            labels[s.op, "cfg_gated"] += all(x.cfg for x in group)
            labels[s.op, "in_macro_definitions"] += s.macro.startswith("def:")
            labels[s.op, "in_macro_invocations"] += s.macro.startswith("call:")
            if host_ok:
                labels[s.op, "host_true"] += host_of(crate, group) is True
                labels[s.op, "host_undetermined"] += host_of(crate, group) is None
        for kind in UNSAFE_KINDS + UNSAFE_LABELS:
            order = ("with_body", "declaration", "cfg_gated", "in_macro_definitions", "in_macro_invocations",
                     "host_true", "host_undetermined")
            bd = {lab: labels[kind, lab] for lab in order if (kind, lab) in labels}
            add(f"unsafe_keywords.{crate}.{kind}", "unsafe_keywords", crate, kinds.get(kind, 0), src, bd or None)
        files = crate_files(w)
        com = sum(meas.lexed[f].comment_unsafe for f in files)
        lit = sum(meas.lexed[f].literal_unsafe for f in files)
        add(f"unsafe_words_excluded.{crate}", "unsafe_words_excluded", crate, com + lit, src,
            {"comments": com, "literals": lit})
        if host_ok:
            add(f"modules_host.{crate}", "modules_host", crate, sum(1 for x in mods if x["host_module"] is True), hst,
                {"undetermined": sum(1 for x in mods if x["host_module"] is None)})
            yes = [x for x in unsafe_mods if x["host"] is True]
            add(f"unsafe_modules_host.{crate}", "unsafe_modules_host", crate, len(yes), hst,
                {"undetermined": sum(1 for x in unsafe_mods if x["host"] is None),
                 "by_source_tree": dict(sorted(collections.Counter(source_tree(x["key"][1]) for x in yes).items()))})
        else:
            for name, kind in ((f"modules_host.{crate}", "modules_host"),
                               (f"unsafe_modules_host.{crate}", "unsafe_modules_host")):
                add(name, kind, crate, None, hst, status="blocked", why=reason)
        for x in unsafe_mods:
            path, file, inline = x["key"]
            q = x["q"]
            entry = {
                "module": "::".join((crate,) + path), "file": file, "inline": "::".join(inline),
                "kinds": {kk: sum(1 for s in q if s.op == kk) for kk in UNSAFE_KINDS if any(s.op == kk for s in q)},
                "cfg": " || ".join(f"({' && '.join(c)})" if len(x["chains"]) > 1 and c else " && ".join(c)
                                   for c in x["chains"]),
                "macro_only": all(s.macro.startswith("def:") for s in q),
                "host": tv(x["host"]) if host_ok else "blocked",
            }
            if x["decls"]:
                entry["decl"] = ", ".join(x["decls"])
            modules.append((crate, entry))
        reached = set(files)
        prefix = f"library/{crate}/src/"
        unreached[crate] = sorted(f for f in meas.tree.files(prefix, (".rs",)) if f not in reached)
        add(f"unreached_files.{crate}", "unreached_files", crate, len(unreached[crate]), src)
    for kind in ("A-method", "A-method-unconfirmed", "A-fence", "A-intrinsic", "A-wrapper", "A-unresolved", "S",
                 "residue"):
        for crate in CRATES:
            groups = [g for (c, k, _, _), g in uniq.items() if c == crate and k == kind]
            ops = collections.Counter(g[0].op for g in groups)
            bd = {"by_op": dict(sorted(ops.items()))}
            if kind == "A-method":
                bd["by_ordering"] = dict(sorted(collections.Counter(
                    o for g in groups for o in g[0].detail.split(";")[0].split(",") if o in ORDERINGS).items()))
                bd["forwarded"] = sum(1 for g in groups if g[0].detail.endswith(";forwarded"))
            if kind == "S":
                bd["by_family"] = dict(sorted(collections.Counter(SYNC_NAMES[g[0].op] for g in groups).items()))
            bd["cfg_gated"] = sum(1 for g in groups if all(s.cfg for s in g))
            bd["in_macro_definitions"] = sum(1 for g in groups if g[0].macro.startswith("def:"))
            bd["in_macro_invocations"] = sum(1 for g in groups if g[0].macro.startswith("call:"))
            if host_ok:
                vals = [host_of(crate, g) for g in groups]
                bd["host_true"] = sum(1 for v in vals if v is True)
                bd["host_undetermined"] = sum(1 for v in vals if v is None)
            if kind != "residue" or groups:
                add(f"{kind}.{crate}", kind, crate, len(groups), src, bd)
            for g in groups:
                s = g[0]
                site_files[(crate, kind, s.file)] += 1
                if kind in ("A-method-unconfirmed", "A-unresolved", "residue"):
                    lists.append({"crate": crate, "kind": kind, "op": s.op, "at": f"{s.file}:{s.line}",
                                  "detail": s.detail, "cfg": " && ".join(s.cfg),
                                  "host": tv(host_of(crate, g)) if host_ok else "blocked"})
    for crate in CRATES:
        per = {k: sum(1 for (c, kk, _, _) in uniq if c == crate and kk == k)
               for k in ("A-method", "A-fence", "A-intrinsic", "A-wrapper")}
        add(f"A.{crate}", "A", crate, sum(per.values()), src, {"by_kind": per})
    files = [{"crate": c, "kind": k, "file": f, "sites": n} for (c, k, f), n in sorted(site_files.items())
             if k not in ("unsafe",)]
    return {"rows": rows, "modules": modules, "unreached": unreached, "unconfirmed": lists, "site_files": files}


