BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")


def tstr(v: str) -> str:
    return json.dumps(v, ensure_ascii=False)


def tkey(k: str) -> str:
    return k if BARE_KEY.match(k) else tstr(k)


def tval(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return tstr(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(tval(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{tkey(k)} = {tval(x)}" for k, x in v.items()) + " }" if v else "{}"
    raise TypeError(repr(v))


def source_inputs(meas: Measurement) -> dict:
    listing = C.git(meas.repo, "ls-tree", "-r", "-z", meas.commit, "--", "library/") or ""
    blobs = {}
    for rec in listing.split("\0"):
        if rec:
            meta, _, path = rec.partition("\t")
            blobs[path] = meta.split()[2]
    read = sorted(meas.lexed)
    digest = hashlib.sha256("".join(f"{p}\0{blobs.get(p, '?')}\n" for p in read).encode()).hexdigest()
    marked = [p for p in read if C.TRUST_TAGGED.search(meas.lexed[p].text)]
    return {"commit": meas.commit, "trees": meas.tree_pins(), "files_read": len(read),
            "files_sha256": f"sha256:{digest}", "trust_marked_files": marked}


