# scanning: module structure, cfg chains, macro context
# --------------------------------------------------------------------------


class Ctx(NamedTuple):
    node: int                 # index into Walker.nodes: the module these tokens belong to
    dir: str                  # the module's directory for child `mod NAME;` resolution
    relative: str | None      # rustc's DirOwnership relative: a non-mod-rs file module's name
    cfg: tuple                # the cfg chain (conjunction of predicate texts)
    macro: tuple | None       # ("def", name) inside a macro definition, ("call", name) inside an invocation
    attr: bool                # inside an attribute
    otherwise: str | None = None   # inside std's `cfg_unordered!`: the cfg an `#[else]` item carries


class Node(NamedTuple):
    crate: str
    path: tuple               # module path within the crate
    file: str                 # the file holding the module's tokens (for an inline module, its file)
    inline: tuple             # inline module names within that file
    cfg: tuple                # the module-level gate: the chain at its declaration, then its #![cfg]s
    decl: str                 # file:line of the declaration ("" for the crate root)
    in_macro: str             # the macro invocation a declaration lies in, "" if none
    decl_cfg: tuple           # the chain at the declaration alone: rustc reads the file when it holds


class Site(NamedTuple):
    kind: str
    op: str
    crate: str
    node: int
    file: str
    line: int
    pos: int                  # the keyword's or callee's offset in its file: a site is a source position
    cfg: tuple
    macro: str
    detail: str


def item_head(lx: Lexed, j: int, hi: int) -> int:
    """Skip visibility and item qualifiers from j; the index of the item's keyword."""
    t, m = lx.texts, lx.match
    k = j
    while k < hi:
        x = t[k]
        if x == "pub":
            k += 1
            if k < hi and t[k] == "(":
                k = m[k] + 1
            continue
        if x in ("default", "async", "safe", "auto") and k + 1 < hi and lx.kinds[k + 1] == "i":
            k += 1
            continue
        if x == "unsafe" and k + 1 < hi and t[k + 1] in ("fn", "impl", "trait", "auto", "extern", "mod", "async"):
            k += 1
            continue
        if x == "const" and k + 1 < hi and t[k + 1] in ("fn", "unsafe", "async", "extern"):
            k += 1
            continue
        if x == "extern" and k + 1 < hi and lx.kinds[k + 1] == "s" and k + 2 < hi and t[k + 2] in ("fn", "{", "unsafe"):
            k += 2
            continue
        if x == "extern" and k + 1 < hi and t[k + 1] == "fn":
            k += 1
            continue
        break
    return k


def until(lx: Lexed, k: int, hi: int, stops: tuple, brace_ends: bool, angles: bool = False) -> int:
    """The index after the first stop token or (when brace_ends) the first brace group at depth 0
    from k. With `angles` (an item header), a brace inside `<…>` generic arguments (a const
    argument) is skipped; without it, a brace right after `<`, `,` or `=` is."""
    t, m = lx.texts, lx.match
    x, depth = k, 0
    while x < hi:
        tok = t[x]
        if tok in stops and depth == 0:
            return x + 1
        if tok == "{":
            if brace_ends and (depth == 0 if angles else (x == k or t[x - 1] not in ("<", ",", "="))):
                return m[x] + 1
            x = m[x] + 1
            continue
        if tok in ("(", "["):
            x = m[x] + 1
            continue
        if angles and tok == "<":
            depth += 1
        elif angles and tok == ">" and depth:
            depth -= 1
        x += 1
    return hi


def element_end(lx: Lexed, j: int, hi: int) -> int:
    """The end (exclusive) of the element an outer attribute list ending before j applies to."""
    t, m = lx.texts, lx.match
    if j >= hi:
        return hi
    k = item_head(lx, j, hi)
    if k >= hi:
        return hi
    x = t[k]
    if x == "extern" and k + 1 < hi and t[k + 1] == "crate":
        return until(lx, k, hi, (";",), False)
    if x in ("fn", "mod", "impl", "trait", "enum", "union", "struct", "extern"):
        return until(lx, k, hi, (";",), True, angles=True)
    if x in ("type", "use", "static", "let", "const"):
        if x == "const" and k + 1 < hi and t[k + 1] == "{":
            return m[k + 1] + 1
        return until(lx, k, hi, (";",), False)
    if x == "macro_rules" and k + 3 < hi and t[k + 1] == "!":
        g = k + 3
        if t[g] == "{":
            e = m[g] + 1
            return e + 1 if e < hi and t[e] == ";" else e
        return until(lx, g, hi, (";",), False)
    if x == "macro" and k + 1 < hi and lx.kinds[k + 1] == "i":
        return until(lx, k, hi, (), True, angles=True)
    if x == "{":
        return m[k] + 1
    if x == "unsafe" and k + 1 < hi and t[k + 1] == "{":
        return m[k + 1] + 1
    if x == "if":
        e = until(lx, k, hi, (), True)
        while e < hi and t[e] == "else":
            e = until(lx, e, hi, (), True)
        return e
    if x in ("match", "loop", "while", "for"):
        return until(lx, k, hi, (), True)
    # a macro invocation (possibly through a path)
    y = k
    while y + 2 < hi and lx.kinds[y] == "i" and t[y + 1] == "::":
        y += 2
    if lx.kinds[y] == "i" and y + 2 < hi and t[y + 1] == "!" and t[y + 2] in OPEN:
        g = y + 2
        if t[g] == "{":
            e = m[g] + 1
            return e + 1 if e < hi and t[e] == ";" else e
        return until(lx, g, hi, (";", ","), False)
    # statement, expression, field, variant, argument or match arm
    x2 = k
    while x2 < hi:
        tok = t[x2]
        if tok in (";", ","):
            return x2 + 1
        if tok == "=>":
            if x2 + 1 < hi and t[x2 + 1] == "{":
                e = m[x2 + 1] + 1
                return e + 1 if e < hi and t[e] == "," else e
            x2 += 1
            continue
        if tok in OPEN:
            x2 = m[x2] + 1
            continue
        x2 += 1
    return hi


def gating_macro(lx: Lexed, lo: int, hi: int) -> str | None:
    """P when a macro_rules body [lo, hi) is a cfg gate on P: one rule transcribes to
    `cfg_select! { P => { .. } _ => { .. } }` and every `#[cfg(..)]` in the body is `#[cfg(P)]`
    (std/src/sys/fs/unix.rs's `cfg_has_statx!`). An invocation `NAME! {{ A } else { B }}` then
    gates A on P and B on not(P); any other invocation gates its tokens on P."""
    t, m = lx.texts, lx.match
    pred, cfgs = None, []
    for x in range(lo, hi - 2):
        if t[x] == "cfg_select" and t[x + 1] == "!" and t[x + 2] == "{":
            g, arms, y = x + 2, [], x + 3
            while y < m[g]:
                p = y
                while y < m[g] and t[y] != "=>":
                    y = m[y] + 1 if t[y] in OPEN else y + 1
                if y >= m[g] or t[y + 1] != "{":
                    return None
                arms.append(render(lx, p, y))
                y = m[y + 1] + 1
            if len(arms) != 2 or arms[1] != "_" or arms[0] == "_":
                return None
            pred = arms[0]
        if t[x] == "#" and t[x + 1] == "[" and t[x + 2] == "cfg" and t[x + 3] == "(":
            cfgs.append(render(lx, x + 4, m[x + 3]))
    return pred if pred is not None and all(c == pred for c in cfgs) else None


class Walker:
    """Walks one crate's module tree from lib.rs and records nodes, token contexts and sites."""

    def __init__(self, tree, lexed: dict, crate: str) -> None:
        self.tree, self.lexed, self.crate = tree, lexed, crate
        self.nodes: list[Node] = []
        self.unresolved: list[str] = []
        self.files_reached: dict[str, list[int]] = collections.defaultdict(list)   # file -> nodes (file modules)
        self.included: dict[str, list[tuple]] = collections.defaultdict(list)   # file -> (node, site chain)
        self.contexts: list[tuple[str, list]] = []   # (file, per-token ctx list) per scanned inclusion
        self.all_files = set(tree.files("library/", (".rs",)))
        self.gating: dict[tuple[str, str], str] = {}   # (file, macro) -> the cfg its body gates on

    def lex(self, rel: str) -> Lexed:
        if rel not in self.lexed:
            text = self.tree.text(rel)
            if text is None:
                raise InputError(f"{rel}: unreadable at the pinned commit")
            self.lexed[rel] = Lexed(rel, text)
        return self.lexed[rel]

    def run(self) -> None:
        root = f"library/{self.crate}/src/lib.rs"
        node = self.add_node(Node(self.crate, (), root, (), (), "", "", ()))
        self.scan_file(root, Ctx(node, posixpath.dirname(root), None, (), None, False))

    def add_node(self, node: Node) -> int:
        self.nodes.append(node)
        return len(self.nodes) - 1

    def scan_file(self, rel: str, ctx: Ctx) -> None:
        lx = self.lex(rel)
        if not self.nodes[ctx.node].inline and self.nodes[ctx.node].file == rel:
            self.files_reached[rel].append(ctx.node)
        ctxs = [None] * len(lx.texts)
        self.contexts.append((rel, ctxs))
        includes = []
        self._scan(lx, ctxs, 0, len(lx.texts), ctx, (), True, includes)
        for path, ictx in includes:
            if path not in self.all_files:
                self.unresolved.append(f"include!(\"{path}\") from {rel}: no such file")
                continue
            self.included[path].append((ictx.node, ictx.cfg))
            self.scan_file(path, ictx)

    def mark(self, ctxs: list, lo: int, hi: int, ctx: Ctx) -> None:
        for i in range(lo, hi):
            ctxs[i] = ctx

    def attr_info(self, lx: Lexed, lo: int, hi: int):
        """(cfg predicate text or None, path or None) of one attribute's tokens [lo, hi). The path
        is ("", value) for `#[path = "value"]` and (P, value) for `#[cfg_attr(P, .., path = "value")]`."""
        t, m = lx.texts, lx.match
        if hi - lo >= 3 and t[lo] == "cfg" and t[lo + 1] == "(" and m[lo + 1] == hi - 1:
            return render(lx, lo + 2, hi - 1), None
        if hi - lo == 3 and t[lo] == "path" and t[lo + 1] == "=" and lx.kinds[lo + 2] == "s":
            return None, ("", string_value(t[lo + 2]))
        if hi - lo >= 3 and t[lo] == "cfg_attr" and t[lo + 1] == "(" and m[lo + 1] == hi - 1:
            parts = call_args(lx, lo + 1)
            for a, b in parts[1:]:
                if b - a == 3 and t[a] == "path" and t[a + 1] == "=" and lx.kinds[a + 2] == "s":
                    return None, (render(lx, *parts[0]), string_value(t[a + 2]))
                if t[a] == "path":
                    self.unresolved.append(f"{lx.rel}:{lx.tline(a)}: a cfg_attr path of an unread form")
        return None, None

    def _scan(self, lx: Lexed, ctxs: list, lo: int, hi: int, ctx: Ctx, attrs: tuple, at_start: bool,
              includes: list) -> None:
        t, k, m = lx.texts, lx.kinds, lx.match
        i = lo
        while i < hi:
            tok = t[i]
            if ctx.macro and ctx.macro[0] == "def":
                self.mark(ctxs, i, hi, ctx)
                return
            if tok == "#" and i + 1 < hi and (t[i + 1] == "[" or (t[i + 1] == "!" and i + 2 < hi and t[i + 2] == "[")):
                if t[i + 1] == "!":
                    e = m[i + 2]
                    self.mark(ctxs, i, e + 1, ctx._replace(attr=True))
                    cfg, _ = self.attr_info(lx, i + 3, e)
                    if cfg is not None:
                        ctx = ctx._replace(cfg=ctx.cfg + (cfg,))
                        if at_start:
                            nd = self.nodes[ctx.node]
                            self.nodes[ctx.node] = nd._replace(cfg=nd.cfg + (cfg,))
                    i = e + 1
                    continue
                own = []
                j = i
                while j + 1 < hi and t[j] == "#" and t[j + 1] == "[":
                    e = m[j + 1]
                    self.mark(ctxs, j, e + 1, ctx._replace(attr=True))
                    if e == j + 3 and t[j + 2] == "else" and ctx.otherwise is not None:
                        own.append((ctx.otherwise, None))
                    else:
                        own.append(self.attr_info(lx, j + 2, e))
                    j = e + 1
                end = element_end(lx, j, hi)
                cfgs = tuple(c for c, _ in own if c is not None)
                self._scan(lx, ctxs, j, end, ctx._replace(cfg=ctx.cfg + cfgs), tuple(own), False, includes)
                i = end
                at_start = False
                continue
            at_start = False
            if tok == "mod" and k[i] == "i" and i + 2 < hi and k[i + 1] == "i" and t[i + 2] in ("{", ";"):
                own_attrs = attrs if item_head(lx, lo, hi) == i else ()
                paths = [p for _, p in own_attrs if p is not None]
                path_attr = paths[0][1] if paths and paths[0][0] == "" else None
                name = t[i + 1]
                if name.startswith("r#"):
                    name = name[2:]
                self.mark(ctxs, i, i + 2, ctx)
                if t[i + 2] == ";":
                    ctxs[i + 2] = ctx
                    for chain, alt in self.path_alternatives(paths):
                        self.declare(lx, i, name, alt, ctx._replace(cfg=ctx.cfg + chain))
                    i += 3
                    continue
                if paths and paths[0][0] != "":
                    self.unresolved.append(f"{lx.rel}:{lx.tline(i)}: cfg_attr path on an inline module not followed")
                g = i + 2
                ctxs[g] = ctxs[m[g]] = ctx
                parent = self.nodes[ctx.node]
                if path_attr is not None:
                    ndir, nrel = posixpath.normpath(posixpath.join(ctx.dir, path_attr)), None
                else:
                    base = posixpath.join(ctx.dir, ctx.relative) if ctx.relative else ctx.dir
                    ndir, nrel = posixpath.join(base, name), None
                child = self.add_node(Node(self.crate, parent.path + (name,), lx.rel,
                                           self.inline_of(ctx, lx.rel) + (name,), ctx.cfg,
                                           f"{lx.rel}:{lx.tline(i)}", ctx.macro[1] if ctx.macro else "", ctx.cfg))
                self._scan(lx, ctxs, g + 1, m[g], Ctx(child, ndir, nrel, ctx.cfg, ctx.macro, False), (), True, includes)
                i = m[g] + 1
                continue
            if tok in ("macro_rules", "macro") and k[i] == "i":
                if tok == "macro_rules" and i + 3 < hi and t[i + 1] == "!" and t[i + 3] in OPEN:
                    e = m[i + 3] + 1
                    self.mark(ctxs, i, e, ctx._replace(macro=("def", t[i + 2])))
                    gate = gating_macro(lx, i + 4, e - 1)
                    if gate is not None:
                        self.gating[(lx.rel, t[i + 2])] = gate
                    i = e
                    continue
                if tok == "macro" and i + 2 < hi and k[i + 1] == "i" and t[i + 2] in ("(", "{"):
                    e = until(lx, i, hi, (), True)
                    self.mark(ctxs, i, e, ctx._replace(macro=("def", t[i + 1])))
                    i = e
                    continue
            if k[i] == "i" and i + 2 < hi and t[i + 1] == "!" and t[i + 2] in OPEN and tok not in ("macro_rules",):
                g = i + 2
                self.mark(ctxs, i, i + 2, ctx)
                ctxs[g] = ctxs[m[g]] = ctx
                if tok == "cfg_select" and self.cfg_select(lx, ctxs, g + 1, m[g], ctx, includes):
                    i = m[g] + 1
                    continue
                if tok == "cfg_if" and self.cfg_if(lx, ctxs, g + 1, m[g], ctx, includes):
                    i = m[g] + 1
                    continue
                gate = self.gating.get((lx.rel, tok))
                if gate is not None:
                    inner = ctx._replace(macro=("call", tok))
                    lo2, hi2 = g + 1, m[g]
                    if t[lo2] == "{" and m[lo2] + 2 < hi2 and t[m[lo2] + 1] == "else" and t[m[lo2] + 2] == "{" \
                            and m[m[lo2] + 2] + 1 == hi2:
                        b = m[lo2] + 2
                        for x in (lo2, m[lo2], m[lo2] + 1, b, m[b]):
                            ctxs[x] = ctx
                        self._scan(lx, ctxs, lo2 + 1, m[lo2], inner._replace(cfg=ctx.cfg + (gate,)), (), False,
                                   includes)
                        self._scan(lx, ctxs, b + 1, m[b], inner._replace(cfg=ctx.cfg + (f"not({gate})",)), (), False,
                                   includes)
                    else:
                        self._scan(lx, ctxs, lo2, hi2, inner._replace(cfg=ctx.cfg + (gate,)), (), False, includes)
                    i = m[g] + 1
                    continue
                if tok == "cfg_unordered":
                    # std/src/sys/env_consts.rs: `#[else]` is the negation of every sibling `#[cfg]`
                    preds, x = [], g + 1
                    while x < m[g]:
                        if t[x] == "#" and t[x + 1] == "[":
                            c, _ = self.attr_info(lx, x + 2, m[x + 1])
                            if c is not None:
                                preds.append(c)
                            x = m[x + 1] + 1
                        elif t[x] in OPEN:
                            x = m[x] + 1
                        else:
                            x += 1
                    other = f"not(any({', '.join(preds)}))"
                    self._scan(lx, ctxs, g + 1, m[g], ctx._replace(macro=("call", tok), otherwise=other), (), False,
                               includes)
                    i = m[g] + 1
                    continue
                if tok == "include" and m[g] == g + 2 and k[g + 1] == "s":
                    val = string_value(t[g + 1])
                    ctxs[g + 1] = ctx
                    if val is None or not val.endswith(".rs"):
                        self.unresolved.append(f"{lx.rel}:{lx.tline(i)}: include!({t[g + 1]}) not followed")
                    else:
                        includes.append((posixpath.normpath(posixpath.join(posixpath.dirname(lx.rel), val)), ctx))
                    i = m[g] + 1
                    continue
                if tok == "include":
                    self.unresolved.append(f"{lx.rel}:{lx.tline(i)}: non-literal include! not followed")
                self._scan(lx, ctxs, g + 1, m[g], ctx._replace(macro=("call", tok)), (), False, includes)
                i = m[g] + 1
                continue
            ctxs[i] = ctx
            if tok in OPEN and k[i] == "p":
                e = m[i]
                ctxs[e] = ctx
                self._scan(lx, ctxs, i + 1, e, ctx, (), False, includes)
                i = e + 1
                continue
            i += 1

    def inline_of(self, ctx: Ctx, rel: str) -> tuple:
        nd = self.nodes[ctx.node]
        return nd.inline if nd.file == rel else ()

    def cfg_select(self, lx: Lexed, ctxs: list, lo: int, hi: int, ctx: Ctx, includes: list) -> bool:
        t, m = lx.texts, lx.match
        arms = []
        x = lo
        while x < hi:
            p = x
            while x < hi and t[x] != "=>":
                x = m[x] + 1 if t[x] in OPEN else x + 1
            if x >= hi:
                return False
            pred = (p, x)
            x += 1
            if x < hi and t[x] == "{":
                body = (x + 1, m[x])
                x = m[x] + 1
            else:
                b = x
                while x < hi and t[x] != ",":
                    x = m[x] + 1 if t[x] in OPEN else x + 1
                body = (b, x)
            if x < hi and t[x] == ",":
                ctxs[x] = ctx
                x += 1
            arms.append((pred, body))
        prior = []
        for (plo, phi), (blo, bhi) in arms:
            self.mark(ctxs, plo, phi + 1, ctx._replace(attr=True))
            if blo > 0 and t[blo - 1] == "{":
                ctxs[blo - 1] = ctxs[bhi] = ctx
            wildcard = phi - plo == 1 and t[plo] == "_"
            text = None if wildcard else render(lx, plo, phi)
            chain = ctx.cfg + tuple(f"not({q})" for q in prior) + ((text,) if text else ())
            self._scan(lx, ctxs, blo, bhi, ctx._replace(cfg=chain), (), False, includes)
            if text:
                prior.append(text)
        return True

    def cfg_if(self, lx: Lexed, ctxs: list, lo: int, hi: int, ctx: Ctx, includes: list) -> bool:
        t, m = lx.texts, lx.match
        arms = []
        x = lo
        while x < hi:
            if t[x] == "else":
                ctxs[x] = ctx
                x += 1
            if x < hi and t[x] == "if" and t[x + 1] == "#" and t[x + 2] == "[":
                e = m[x + 2]
                if not (t[x + 3] == "cfg" and t[x + 4] == "(" and m[x + 4] == e - 1):
                    return False
                pred = render(lx, x + 5, e - 1)
                self.mark(ctxs, x, e + 1, ctx._replace(attr=True))
                x = e + 1
            elif x < hi and t[x] == "{":
                pred = None
            else:
                return False
            if t[x] != "{":
                return False
            arms.append((pred, x + 1, m[x]))
            ctxs[x] = ctxs[m[x]] = ctx
            x = m[x] + 1
        prior = []
        for pred, blo, bhi in arms:
            chain = ctx.cfg + tuple(f"not({q})" for q in prior) + ((pred,) if pred else ())
            self._scan(lx, ctxs, blo, bhi, ctx._replace(cfg=chain), (), False, includes)
            if pred:
                prior.append(pred)
        return True

    @staticmethod
    def path_alternatives(paths: list) -> list:
        """rustc uses the first `path` attribute that survives cfg_attr expansion: each
        alternative with the extra cfg chain under which it is the one used; the default
        resolution (None) last, unless an unconditional path precedes or the conditions are a
        predicate and its negation."""
        alts, prior = [], []
        for pred, value in paths:
            nots = tuple(f"not({q})" for q in prior)
            if pred == "":
                alts.append((nots, value))
                return alts
            alts.append((nots + (pred,), value))
            prior.append(pred)
        if any(f"not({q})" in prior for q in prior):
            return alts
        alts.append((tuple(f"not({q})" for q in prior), None))
        return alts

    def declare(self, lx: Lexed, i: int, name: str, path_attr: str | None, ctx: Ctx) -> None:
        where = f"{lx.rel}:{lx.tline(i)}"
        if path_attr is not None:
            target = posixpath.normpath(posixpath.join(ctx.dir, path_attr))
            if target not in self.all_files:
                self.unresolved.append(f"{where}: mod {name} -> #[path] {target}: no such file")
                return
            cdir, crel = posixpath.dirname(target), None
        else:
            base = posixpath.join(ctx.dir, ctx.relative) if ctx.relative else ctx.dir
            first, second = posixpath.normpath(f"{base}/{name}.rs"), posixpath.normpath(f"{base}/{name}/mod.rs")
            has1, has2 = first in self.all_files, second in self.all_files
            if has1 and has2:
                self.unresolved.append(f"{where}: mod {name}: both {first} and {second} exist")
                return
            if not (has1 or has2):
                self.unresolved.append(f"{where}: mod {name}: neither {first} nor {second} exists")
                return
            target = first if has1 else second
            cdir, crel = posixpath.dirname(target), (name if has1 else None)
        parent = self.nodes[ctx.node]
        child = self.add_node(Node(self.crate, parent.path + (name,), target, (), ctx.cfg, where,
                                   ctx.macro[1] if ctx.macro else "", ctx.cfg))
        self.scan_file(target, Ctx(child, cdir, crel, ctx.cfg, None, False))


