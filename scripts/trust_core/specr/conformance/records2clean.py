#!/usr/bin/env python3
"""Turn the exported minitest programs of the selected tests into Clean
conformance theorems (translator v2; v1 was the K8 probe's).

usage: records2clean.py <records.jsonl> <schema.json> <selection.json> <out.lean> <index.json>
                        [--steps N] [--fuel N] [--bound N] [--only test,test,...]

For every recorded program run of an in-slice test this emits

    def k8p_<n> : MR_Program := <the program as a Clean term>
    theorem k8t_<n> : SOut.runLeast <bound> (K8Run.run <steps> <fuel> k8p_<n>) = SOut.ok <expected> := rfl

`K8Run.run` builds the free-monad tree; `SOut.runLeast` is K8's deterministic
oracle (the least candidate of every choice that passes its predicate, among the
first <bound>), one interpretation of that tree.

where <expected> is the outcome the minitest asserts (MachineStop, Ub msg,
IllFormed msg, Abort, MemoryLeak). The theorem is closed by `rfl`: the kernel
evaluates the translated MiniRust interpreter on the program. A test passes
iff every theorem generated from it is accepted.
"""

import json
import sys
from mrjson import ToLean, lean_str

HARNESS = '''-- K8Run: the minitest driver (MiniRust tooling/miniutil/src/run.rs `run`),
-- hand-authored: build the machine, then step until the machine stops.
-- `steps` bounds the number of machine steps and `fuel` the call depth inside
-- one step; exhausting either is the observable outcome `SOut.fuel`.
def K8Run.loop (steps fuel : Nat) (m : MR_Machine) : SOut MR_TerminationInfo :=
  match steps with
  | 0 => SOut.fuel
  | steps + 1 =>
    SOut.bind (α := SRes MR_TerminationInfo Unit × MR_Machine) (β := MR_TerminationInfo) (MRf.Machine.step fuel m) (fun (p : SRes MR_TerminationInfo Unit × MR_Machine) =>
      match p with
      | (r, m2) => match r with
        | SRes.ok _ => K8Run.loop steps fuel m2
        | SRes.err t => SOut.ok t)

def K8Run.run (steps fuel : Nat) (prog : MR_Program) : SOut MR_TerminationInfo :=
  SOut.bind (α := SRes MR_TerminationInfo MR_Machine) (β := MR_TerminationInfo) (MRf.Machine.new fuel prog () () ()) (fun (r : SRes MR_TerminationInfo MR_Machine) =>
    match r with
    | SRes.ok m => K8Run.loop steps fuel m
    | SRes.err t => SOut.ok t)
'''


def expected(rec):
    e = rec['expect']
    k = e['kind']
    if k == 'stop':
        return 'MR_TerminationInfo.MachineStop'
    if k == 'abort':
        return 'MR_TerminationInfo.Abort'
    if k == 'memory_leak':
        return 'MR_TerminationInfo.MemoryLeak'
    if k == 'ub':
        return f'(MR_TerminationInfo.Ub {lean_str(e["msg"])})'
    if k == 'ill_formed':
        return f'(MR_TerminationInfo.IllFormed {lean_str(e["msg"])})'
    raise ValueError(k)


def main():
    args = sys.argv[1:]
    steps, fuel, bound, only = 10000, 10000, 65536, None
    if '--bound' in args:
        i = args.index('--bound'); bound = int(args[i + 1]); del args[i:i + 2]
    if '--steps' in args:
        i = args.index('--steps'); steps = int(args[i + 1]); del args[i:i + 2]
    if '--fuel' in args:
        i = args.index('--fuel'); fuel = int(args[i + 1]); del args[i:i + 2]
    if '--only' in args:
        i = args.index('--only'); only = set(args[i + 1].split(',')); del args[i:i + 2]
    recs_path, schema_path, sel_path, out_path, index_path = args
    recs = [json.loads(l) for l in open(recs_path)]
    schema = json.load(open(schema_path))
    sel = json.load(open(sel_path))
    conv = ToLean(schema)
    out = ['-- GENERATED by records2clean.py (translator v2) from the exported minitest programs.', HARNESS]
    index = []
    n = 0
    for test in sorted(sel['tests']):
        t = sel['tests'][test]
        if not t['in_slice'] or (only is not None and test not in only):
            continue
        for ri in t['records']:
            rec = recs[ri]
            term = conv.term(rec['program'], ('adt', 'Program'))
            out.append(f'-- {test} (record {ri}): expects {rec["expect"]["kind"]}' + (f' {rec["expect"]["msg"]!r}' if rec['expect'].get('msg') else ''))
            out.append(f'def k8p_{n} : MR_Program := {term}')
            out.append(f'theorem k8t_{n} : SOut.runLeast {bound} (K8Run.run {steps} {fuel} k8p_{n}) = SOut.ok {expected(rec)} := rfl')
            out.append('')
            index.append({'n': n, 'test': test, 'record': ri, 'expect': rec['expect'],
                          'reference_result': rec['reference'], 'theorem': f'k8t_{n}'})
            n += 1
    open(out_path, 'w').write('\n'.join(out) + '\n')
    json.dump({'steps': steps, 'fuel': fuel, 'bound': bound, 'theorems': index}, open(index_path, 'w'), indent=1)
    print(json.dumps({'theorems': n, 'tests': len({x['test'] for x in index})}))


if __name__ == '__main__':
    main()
