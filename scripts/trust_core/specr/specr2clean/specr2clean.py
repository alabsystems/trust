#!/usr/bin/env python3
"""K8 probe: translate MiniRust specr sources into Clean.

usage: specr2clean.py <front-end ast.json> <slice.json> <out.lean> <census.json>

The output is deterministic: the same inputs produce byte-identical files.
"""

import json
import sys
import hashlib

import common
from common import *
from items import Program, ADT
from tyres import resolve_adts
from emit_types import TypeInfo, emit_types
from lower import Lowerer
from emit_fns import lower_function, lower_const, emit_all


def main():
    ast_path, cfg_path, out_path, census_path = sys.argv[1:5]
    ast = json.load(open(ast_path))
    cfg = json.load(open(cfg_path))
    common.reset_fresh()
    prog = Program(ast, cfg)
    for name, variants in cfg['library_enums'].items():
        a = ADT(name, 'enum', 'libspecr')
        a.variants = [(v, 'unit', []) for v in variants]
        a.prelude = True
        prog.adts[name] = a
    resolve_adts(prog)
    tinfo = TypeInfo(prog)

    out = []
    out.append('-- GENERATED by specr2clean (K8 probe) from MiniRust ' + cfg['minirust_revision'])
    out.append('-- Input: the specr code blocks of ' + ', '.join(cfg['files']))
    out.append('-- DO NOT EDIT: regenerate and byte-compare instead (design D-1, I-NO-HAND-PATCH).')
    out.append('-- Requires SpecrPrelude.lean (hand-authored) to be loaded first.')
    out.append('')

    type_refusals = []
    try:
        emit_types(prog, tinfo, out, skip=lambda a: getattr(a, 'prelude', False))
    except Refusal as r:
        type_refusals.append(str(r))
        raise

    L = Lowerer(prog, tinfo)
    emitted = []
    for fd in prog.fns:
        emitted.append(lower_function(L, fd))
    for cd in prog.consts:
        emitted.append(lower_const(L, cd))
    groups = emit_all(L, emitted, out)

    text = common.qualify_shadowed('\n'.join(out)) + '\n'
    open(out_path, 'w').write(text)

    census = {
        'minirust_revision': cfg['minirust_revision'],
        'input_files': [{'path': p, 'code_lines': n} for p, n in prog.files],
        'item_kinds': prog.item_counts,
        'adts': len([a for a in prog.adts.values() if not getattr(a, 'prelude', False)]),
        'adt_recursive_groups': [c for c, rec in tinfo.groups if rec],
        'refused_items': [{'item': i, 'construct': c, 'detail': d} for i, c, d in prog.refused_items],
        'functions': [],
        'constructs_supported_uses': dict(sorted(L.census.items())),
        'emission_groups': {'mutual': [c for c, k in groups if k == 'mutual'],
                            'self_recursive': len([1 for c, k in groups if k == 'self-recursive']),
                            'non_recursive': len([1 for c, k in groups if k == 'non-recursive'])},
        'output_sha256': hashlib.sha256(text.encode()).hexdigest(),
        'output_lines': text.count('\n'),
    }
    for e in emitted:
        rec = {'item': e.display, 'lean': e.lean_name, 'file': e.file, 'kind': e.kind, 'status': e.status}
        if e.status in ('refused-body', 'refused-signature'):
            rec['construct'] = e.detail.construct
            rec['detail'] = e.detail.detail
        if e.status == 'translated-with-refused-arms':
            rec['refused_arms'] = [{'arm': i, 'construct': r.construct, 'detail': r.detail} for _, i, r in e.detail]
        if e.status == 'translated-with-refused-expressions':
            rec['refused_expressions'] = [{'construct': c, 'detail': d} for _, c, d in e.detail]
        census['functions'].append(rec)
    json.dump(census, open(census_path, 'w'), indent=1, sort_keys=True)
    if len(sys.argv) > 5:
        # the data-type schema, consumed by the minitest program converter
        schema = {}
        for n, a in sorted(prog.adts.items()):
            schema[n] = {'kind': a.kind, 'prelude': bool(getattr(a, 'prelude', False)),
                         'tuple_struct': a.tuple_struct,
                         'fields': [[f, t] for f, t in a.fields],
                         'variants': [[v, st, [[f, t] for f, t in fs]] for v, st, fs in a.variants]}
        json.dump(schema, open(sys.argv[5], 'w'), indent=1, sort_keys=True)
    counts = {}
    for f in census['functions']:
        counts[f['status']] = counts.get(f['status'], 0) + 1
    print(json.dumps(counts), file=sys.stderr)


if __name__ == '__main__':
    main()
