def md(text: str) -> str:
    """Text for a markdown table cell or list item: no newline, no bare pipe."""
    return " ".join(str(text).split()).replace("|", "\\|")


def sentence(text: str) -> str:
    """`md(text)`, ending with a full stop."""
    text = md(text)
    return text if text.endswith((".", "!", "?")) else text + "."


def shown(row: dict) -> str:
    return str(row["value"]) if isinstance(row.get("value"), int) else "-"


def pin_summary(value, limit: int = 4) -> str:
    pins = pins_in(value)
    text = ", ".join(f"`{p}`" for p in pins[:limit])
    return text + (f" and {len(pins) - limit} more" if len(pins) > limit else "")


def item_block(item: Item, records: dict, owner: dict, readings: list[dict]) -> str:
    keys = list(dict.fromkeys(k for k, _ in item.claims))
    rows = [(k, n, records[k].rows[n]) for k in keys if k in records for n in records[k].rows
            if owner.get((k, n)) == item.id]
    head = [(k, n) for k, n in item.headline if k in records and n in records[k].rows]
    measured = sum(1 for _, _, r in rows if r.get("status") == "measured")
    out = []
    for k in keys:
        if k not in records:
            continue
        rec = records[k]
        out.append(f"Record `{RECORDS_REL}/{k}.toml`, produced by `{SCRIPTS_REL}/{k}.py`, measured at superproject "
                   f"`{rec.data.get('measured_at_commit')}`.")
    out.append(f"This item owns {len(rows)} rows: {measured} measured, {len(rows) - measured} blocked. "
               "The headline rows:")
    out += ["", "| Row | Value | Status |", "|---|---:|---|"]
    out += [f"| `{md(n)}` | {shown(records[k].rows[n])} | {records[k].rows[n].get('status')} |" for k, n in head]
    out += ["", "Their predicates:", ""]
    first: dict[str, str] = {}
    for k, n in head:
        predicate = md(records[k].rows[n].get("predicate", ""))
        out.append(f"* `{md(n)}`: " + (f"the predicate of `{first[predicate]}`." if predicate in first else predicate))
        first.setdefault(predicate, md(n))
    others = [(k, n, r) for k, n, r in rows if (k, n) not in set(head)]
    if others:
        out += ["", "The other rows (each record states every predicate):", ""]
        out.append(", ".join(f"`{md(n)}` {shown(r)}" + (" (blocked)" if r.get("status") == "blocked" else "")
                             for _, n, r in others) + ".")
    out += ["", "Inputs and their pins:", ""]
    for k in keys:
        if k not in records:
            continue
        for name, table in records[k].data.get("inputs", {}).items():
            out.append(f"* `{k}` `inputs.{md(name)}`: {pin_summary(table)}")
    mine = [r for r in readings if r["item"] == item.id]
    out += ["", "Against the design's numbers:", ""]
    if mine:
        for r in mine:
            note = f" ({md(r['note'])})" if r["note"] else ""
            value = r["value"] if isinstance(r["value"], int) else "(blocked)"
            out.append(f"* {r['tag']} {r['number']} (\"{md(r['quote'])}\") against `{md(r['row'])}` = {value}: "
                       f"{md(r['verdict'])}{note}.")
    else:
        out.append("* The design states no number for this item.")
    blocked = [(n, r) for _, n, r in rows if r.get("status") == "blocked"]
    out += ["", "Blocked rows:", ""]
    if blocked:
        for n, r in blocked:
            out.append(f"* `{md(n)}`: {sentence(r.get('blocked', ''))} **Unblock:** {sentence(r.get('unblock', ''))}")
    else:
        out.append("* None.")
    return "\n".join(out)


def pass_block(records: dict, counts: dict) -> str:
    return "\n".join([
        f"* Stage 0.5 items: {counts['items']}, each mapped to its rows ({counts['items_unmapped']} unmapped).",
        f"* Records: {counts['records']}; rows: {counts['rows']} ({counts['measured']} measured, "
        f"{counts['blocked']} blocked).",
        f"* Rows without a predicate: {counts['without_predicate']}. Blocked rows without a reason and an unblock "
        f"condition: {counts['blocked_unexplained']}. Inputs without a pin: {counts['inputs_unpinned']}.",
        f"* Design numbers read against their rows: {counts['readings']}.",
        "* Pins: " + "; ".join(f"`{k}` {records[k].data.get('measured_at_commit', '?')[:12]}" for k in RECORDS
                               if k in records) + ".",
    ])


def blocked_block(records: dict, owner: dict) -> str:
    out = ["| Item | Record | Row |", "|---|---|---|"]
    for item in ITEMS:
        for key in dict.fromkeys(k for k, _ in item.claims):
            if key not in records:
                continue
            for name, row in records[key].rows.items():
                if owner.get((key, name)) == item.id and row.get("status") == "blocked":
                    out.append(f"| {item.id} | `{key}` | `{md(name)}` |")
    return "\n".join(out)


def blocks(records: dict, owner: dict, readings: list[dict], counts: dict) -> dict:
    out = {PASS_BLOCK: pass_block(records, counts), BLOCKED_BLOCK: blocked_block(records, owner)}
    for item in ITEMS:
        out[f"denominators-item-{item.id}"] = item_block(item, records, owner, readings)
    return out


def without_blocks(text: str, names) -> str:
    for name in names:
        span = C.block_span(text, name)
        if span:
            text = text[:span[0]] + text[span[1]:]
    return text


def check_doc(findings: C.Findings, repo: Path, doc: Path, rendered: dict, design: str | None) -> None:
    try:
        text = doc.read_text(encoding="utf-8")
    except OSError as error:
        findings.add("DOC", f"{doc}: {error}")
        return
    for name, body in rendered.items():
        C.check_block(findings, "DOC", text, name, body)
    trees = {"worktree": C.GitTree(repo, "HEAD")}
    if design is not None:
        trees["design"] = C.DirTree(repo, {C.DESIGN_REL: design})
    resolver = C.Resolver(repo, trees)
    C.check_prose(findings, "DOC", DOC_REL, without_blocks(text, rendered), resolver)


def write_doc(doc: Path, rendered: dict) -> None:
    text = doc.read_text(encoding="utf-8")
    for name, body in rendered.items():
        text = C.replace_block(text, name, body)
    doc.write_text(text, encoding="utf-8")


