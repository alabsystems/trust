def artifacts_root(explicit: Path | None) -> Path:
    return Path(explicit or os.environ.get(ARTIFACTS_ENV) or DEFAULT_ARTIFACTS)


def main_checkout(repo: Path) -> Path:
    common = (C.git(repo, "rev-parse", "--path-format=absolute", "--git-common-dir") or "").strip()
    return Path(common).parent if common else repo


def host_build_key(rec: Record) -> str:
    """The cache directory name of std-surface's pinned host build: a digest of its recorded files."""
    table = rec.data.get("inputs", {}).get("host_build", {})
    return "hostbuild-" + hashlib.sha256(C.canonical(table).encode()).hexdigest()[:16]


def run_argv(repo: Path, rec: Record, current: bool, artifacts: Path) -> list[str]:
    script = repo / SCRIPTS_REL / f"{rec.key}.py"
    argv = [sys.executable, str(script), "--check", "--record", str(rec.path)]
    if rec.key == "std-surface":
        # std-surface's --check re-measures at its recorded commit; --current also fails a stale one.
        argv += ["--current"] if current else []
        cached = artifacts / "std-surface" / host_build_key(rec)
        argv += ["--host-build", str(cached if cached.is_dir() else main_checkout(repo) / STD_SURFACE_BUILD)]
    else:
        argv += ["--rev", "HEAD" if current else rec.data.get("measured_at_commit", "HEAD")]
    if rec.key == "imports":
        argv += ["--build-dir", str(main_checkout(repo) / "build")]
        if (artifacts / "imports").is_dir():
            argv += ["--artifact-dir", str(artifacts / "imports")]
    return argv


def run_one(repo: Path, argv: list[str]) -> tuple[int, str, float]:
    start = time.monotonic()
    try:
        run = subprocess.run(argv, cwd=repo, capture_output=True, text=True, stdin=subprocess.DEVNULL,
                             timeout=RUN_TIMEOUT)
        code, out = run.returncode, (run.stdout or "") + (run.stderr or "")
    except subprocess.TimeoutExpired:
        code, out = 124, f"timed out after {RUN_TIMEOUT} s"
    except OSError as error:
        code, out = 127, str(error)
    return code, out, time.monotonic() - start


UNAVAILABLE_EXIT = 3


def run_records(findings: C.Findings, repo: Path, records: dict, current: bool, artifacts: Path, jobs: int,
                unavailable: dict | None = None) -> dict:
    argvs = {key: run_argv(repo, rec, current, artifacts) for key, rec in records.items()}
    with ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
        futures = {key: pool.submit(run_one, repo, argv) for key, argv in argvs.items()}
        runs = {key: futures[key].result() for key in argvs}
    for key, (code, out, _secs) in runs.items():
        if code == UNAVAILABLE_EXIT and unavailable is not None:
            lines = [ln for ln in out.strip().splitlines() if "UNAVAILABLE" in ln]
            unavailable[key] = lines[-1].strip() if lines else f"{key}: a pinned input is not on this host"
        elif code != 0:
            tail = "\n    ".join(out.strip().splitlines()[-12:])
            findings.add("RUN", f"{key}: `{' '.join(Path(a).name if a.endswith('.py') else a for a in argvs[key][1:])}` "
                                f"exited {code}: the record is not reproduced at "
                                f"{'HEAD' if current else 'its pin'}\n    {tail}")
    return runs


