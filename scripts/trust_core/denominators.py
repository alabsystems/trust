def design_text(repo: Path, design: Path | None) -> str:
    if design is not None:
        return design.read_text(encoding="utf-8")
    text = C.git(repo, "show", f"HEAD:{C.DESIGN_REL}")
    if text is None:
        raise OSError(f"cannot read {C.DESIGN_REL} at HEAD of {repo}")
    return text


def stage_items(findings: C.Findings, text: str) -> list[tuple[int, str]]:
    """(line, collapsed text) of every item of the Stage 0.5 list, in order."""
    lines = text.split("\n")
    heads = [i for i, line in enumerate(lines) if line.strip() == STAGE_HEAD]
    if len(heads) != 1:
        findings.add("ITEMS", f"the design holds {len(heads)} lines {STAGE_HEAD!r}; the Stage 0.5 list is not found once")
        return []
    items, current = [], None
    for i in range(heads[0] + 1, len(lines)):
        line = lines[i]
        if line.startswith("* "):
            if current:
                items.append(current)
            if C.collapse(line) == STAGE_EXIT:
                return [(n, C.collapse(" ".join(parts))) for n, parts in items]
            current = (i + 1, [line[2:]])
        elif line.startswith("  ") and current:
            current[1].append(line)
        else:
            break
    findings.add("ITEMS", f"the Stage 0.5 list does not end with {STAGE_EXIT!r}")
    return []


def check_items(findings: C.Findings, text: str) -> dict:
    """item id -> design line."""
    found = stage_items(findings, text)
    by_text = {t: n for n, t in found}
    lines = {}
    for item in ITEMS:
        if item.bullet not in by_text:
            findings.add("ITEMS", f"item {item.id}: the design's Stage 0.5 list has no item {item.bullet!r}")
        else:
            lines[item.id] = by_text[item.bullet]
    mapped = {item.bullet for item in ITEMS}
    for n, t in found:
        if t not in mapped:
            findings.add("ITEMS", f"design:{n}: Stage 0.5 item {t!r} has no denominator (no ITEMS entry)")
    if len({i.id for i in ITEMS}) != len(ITEMS):
        findings.add("ITEMS", "two ITEMS entries share an id")
    return lines


def check_design_pins(findings: C.Findings, repo: Path, text: str, records: dict) -> None:
    """A record that also measures the superproject commit the design header names records it as
    [inputs.design].revision (ui-tests does; hosts and odt use [inputs.design] for quote-checked
    design text, and templates reads a submodule pin, so neither carries `revision`). That
    revision must be the commit the design header in use names. RUN re-reads the header at the
    record's measured_at_commit, so without this an edited header would leave `design-pin`
    readings answered by another commit's lists."""
    named, pinned = C.design_header_pin(repo, text)
    for key, rec in sorted(records.items()):
        table = (rec.data.get("inputs") or {}).get("design")
        if not isinstance(table, dict) or "revision" not in table:
            continue
        recorded = table.get("revision")
        if pinned is None:
            findings.add("MDAGGER", f"{key}: [inputs.design] records the design's pin {recorded!r}, but the design header "
                                    f"names {', '.join(named) or 'no commit'}, which is not one commit of this clone")
        elif recorded != pinned:
            findings.add("MDAGGER", f"{key}: [inputs.design].revision {recorded!r} is not {pinned}, the commit the design "
                                    f"header names; re-measure with {SCRIPTS_REL}/{key}.py --write")


