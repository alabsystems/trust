def pins_in(value) -> list[str]:
    """Every git object id and sha256 digest in a TOML value, in order, once each."""
    found: list[str] = []

    def walk(v):
        if isinstance(v, str):
            found.extend(m.group(0) for m in PIN.finditer(v))
        elif isinstance(v, dict):
            for x in v.values():
                walk(x)
        elif isinstance(v, list):
            for x in v:
                walk(x)
    walk(value)
    return list(dict.fromkeys(found))


def load_records(findings: C.Findings, repo: Path, records_dir: Path, only: tuple) -> dict:
    scripts = {p.stem for p in (repo / SCRIPTS_REL).glob("*.py")}
    tomls = {p.stem for p in records_dir.glob("*.toml")}
    for key in sorted(tomls - set(RECORDS)):
        findings.add("REGISTRY", f"{RECORDS_REL}/{key}.toml is not a registered record (RECORDS)")
    for key in sorted(scripts - set(RECORDS)):
        findings.add("REGISTRY", f"{SCRIPTS_REL}/{key}.py is not a registered record's script (RECORDS)")
    out = {}
    for key in RECORDS:
        if key not in scripts:
            findings.add("REGISTRY", f"record {key}: {SCRIPTS_REL}/{key}.py is missing")
        path = records_dir / f"{key}.toml"
        if key not in tomls:
            findings.add("REGISTRY", f"record {key}: {path} is missing")
            continue
        try:
            data = tomllib.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as error:
            findings.add("SCHEMA", f"{path}: not readable TOML: {error}")
            continue
        out[key] = Record(key, path, data)
    return out


def check_schema(findings: C.Findings, repo: Path, rec: Record) -> None:
    d, where = rec.data, f"{rec.key}.toml"
    for field_, want in (("schema", SCHEMA), ("key", rec.key), ("design", C.DESIGN_REL),
                         ("script", f"{SCRIPTS_REL}/{rec.key}.py"), ("exit", EXIT)):
        if d.get(field_) != want:
            findings.add("SCHEMA", f"{where}: `{field_}` is {d.get(field_)!r}, not {want!r}")
    consumers = d.get("consumers")
    if not isinstance(consumers, list) or not consumers or not all(isinstance(c, str) and c.strip() for c in consumers):
        findings.add("SCHEMA", f"{where}: `consumers` must name what consumes the record (a non-empty list of text)")
    pin = d.get("measured_at_commit")
    if not isinstance(pin, str) or not C.HEX40.match(pin):
        findings.add("SCHEMA", f"{where}: `measured_at_commit` is {pin!r}, not a 40-hex commit (the pin every row is "
                               "re-measured at)")
    elif (C.git(repo, "cat-file", "-t", pin) or "").strip() != "commit":
        findings.add("SCHEMA", f"{where}: measured_at_commit {pin} is not a commit of {repo}")
    elif C.git(repo, "merge-base", "--is-ancestor", pin, "HEAD") is None:
        findings.add("SCHEMA", f"{where}: measured_at_commit {pin} is not in HEAD's history")
    inputs = d.get("inputs")
    if not isinstance(inputs, dict) or not inputs:
        findings.add("SCHEMA", f"{where}: no [inputs.*] tables")
        inputs = {}
    for name, table in inputs.items():
        if not isinstance(table, dict):
            findings.add("SCHEMA", f"{where}: inputs.{name} is not a table")
        elif not pins_in(table):
            findings.add("SCHEMA", f"{where}: inputs.{name} carries no pin (a git object id or a sha256 digest), so "
                                   "nothing says which bytes the rows were measured from")
    rows = d.get("row")
    if not isinstance(rows, list) or not rows:
        findings.add("SCHEMA", f"{where}: no [[row]]")
        rows = []
    good = [r for r in rows if isinstance(r, dict)]
    if len(good) != len(rows):
        findings.add("SCHEMA", f"{where}: a [[row]] is not a table")
    rec.rows = C.unique_rows(findings, "SCHEMA", f"{where} row", good, lambda r: r.get("name"))
    for i, row in enumerate(good):
        name = row.get("name")
        at = f"{where} row {name!r}" if isinstance(name, str) else f"{where} row [{i}]"
        if not isinstance(name, str) or not name:
            findings.add("SCHEMA", f"{at}: no `name`")
        predicate = row.get("predicate")
        if not isinstance(predicate, str) or not predicate.strip():
            findings.add("SCHEMA", f"{at}: no predicate (E0.12: 0 denominators without one)")
        status, value = row.get("status"), row.get("value")
        if status == "measured":
            if not isinstance(value, int) or isinstance(value, bool):
                findings.add("SCHEMA", f"{at}: measured with no integer `value`")
        elif status == "blocked":
            for f in ("blocked", "unblock"):
                if not isinstance(row.get(f), str) or not row[f].strip():
                    findings.add("SCHEMA", f"{at}: blocked with no `{f}` (a blocked row states why, and what "
                                           "would unblock it)")
            if value is not None and (not isinstance(value, int) or isinstance(value, bool)):
                findings.add("SCHEMA", f"{at}: `value` is not an integer")
        else:
            findings.add("SCHEMA", f"{at}: status {status!r} is neither `measured` nor `blocked`")
        named = row.get("inputs")
        if named is not None:
            if not isinstance(named, list) or not all(isinstance(n, str) for n in named):
                findings.add("SCHEMA", f"{at}: `inputs` is not a list of input names")
            else:
                for n in named:
                    if n not in inputs:
                        findings.add("SCHEMA", f"{at}: names input {n!r}, which the record has no [inputs.{n}] for")
                if status == "measured" and not named:
                    findings.add("SCHEMA", f"{at}: measured from no input")


def claim_rows(findings: C.Findings, records: dict) -> dict:
    """(record, row) -> item id; every row claimed exactly once, every headline row present."""
    owner = {}
    for rec in records.values():
        for name in rec.rows:
            items = [item.id for item in ITEMS for key, pattern in item.claims
                     if key == rec.key and re.search(pattern, name)]
            if len(items) != 1:
                findings.add("CLAIM", f"{rec.key}.toml row {name!r} belongs to {len(items)} items {items} (need 1): "
                                      "every row must answer exactly one Stage 0.5 item")
            else:
                owner[(rec.key, name)] = items[0]
    for item in ITEMS:
        for key, name in item.headline:
            if key in records and owner.get((key, name)) != item.id:
                findings.add("CLAIM", f"item {item.id}: headline row {key}.toml {name!r} is not one of its rows")
    return owner


