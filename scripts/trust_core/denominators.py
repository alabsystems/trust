def check(repo: Path = REPO_ROOT, records_dir: Path | None = None, doc: Path | None = None,
          design: Path | None = None, only: tuple = (), run: bool = True, current: bool = False,
          artifacts: Path | None = None, jobs: int = len(RECORDS)) -> Result:
    findings = C.Findings()
    repo = Path(repo)
    records_dir = Path(records_dir or repo / RECORDS_REL)
    text = design_text(repo, design)
    check_items(findings, text)
    records = load_records(findings, repo, records_dir, only)
    for rec in records.values():
        check_schema(findings, repo, rec)
    owner = claim_rows(findings, records)
    readings = check_readings(findings, text, records)
    check_design_pins(findings, repo, text, records)
    rows = [r for rec in records.values() for r in rec.rows.values()]
    counts = {
        "items": len(ITEMS), "items_unmapped": len([f for f in findings.violations if f.startswith("ITEMS:")]),
        "records": len(records), "rows": len(rows),
        "measured": sum(1 for r in rows if r.get("status") == "measured"),
        "blocked": sum(1 for r in rows if r.get("status") == "blocked"),
        "without_predicate": sum(1 for r in rows if not (isinstance(r.get("predicate"), str) and r["predicate"].strip())),
        "blocked_unexplained": sum(1 for r in rows if r.get("status") == "blocked"
                                   and not all(isinstance(r.get(f), str) and r[f].strip() for f in ("blocked", "unblock"))),
        "inputs_unpinned": sum(1 for rec in records.values() for t in rec.data.get("inputs", {}).values()
                               if not pins_in(t)),
        "readings": len(readings),
    }
    rendered = blocks(records, owner, readings, counts)
    check_doc(findings, repo, Path(doc or repo / DOC_REL), rendered, None if design is None else text)
    runs, unavailable = {}, {}
    if run:
        chosen = {k: r for k, r in records.items() if not only or k in only}
        runs = run_records(findings, repo, chosen, current, artifacts_root(artifacts), jobs, unavailable)
    return Result(findings, records, counts, runs, unavailable)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--repo", type=Path, default=REPO_ROOT)
    parser.add_argument("--records", type=Path, help=f"the records directory (default {RECORDS_REL})")
    parser.add_argument("--doc", type=Path, help=f"the document (default {DOC_REL})")
    parser.add_argument("--design", type=Path, help="read the design from this file instead of HEAD")
    parser.add_argument("--artifacts", type=Path, help=f"the artifact cache (default ${ARTIFACTS_ENV} or {DEFAULT_ARTIFACTS})")
    parser.add_argument("--only", action="append", default=[], choices=RECORDS, help="re-measure only these records")
    parser.add_argument("--no-run", action="store_true", help="check the records and the document; re-measure nothing")
    parser.add_argument("--current", action="store_true", help="re-measure at HEAD instead of each record's pin")
    parser.add_argument("--jobs", type=int, default=len(RECORDS), help="records re-measured at once")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write-doc", action="store_true", help="regenerate DENOMINATORS.md's blocks")
    mode.add_argument("--stash", action="store_true", help="copy the pinned non-git inputs into the artifact cache")
    args = parser.parse_args(argv)
    repo = args.repo.resolve()
    try:
        if args.stash:
            findings = C.Findings()
            records = load_records(findings, repo, Path(args.records or repo / RECORDS_REL), ())
            problems = stash(repo, records, artifacts_root(args.artifacts))
            for p in findings.violations + problems:
                print(f"denominators: {p}", file=sys.stderr)
            return 1 if findings.violations or problems else 0
        result = check(repo, args.records, args.doc, args.design, tuple(args.only), run=not (args.no_run or args.write_doc),
                       current=args.current, artifacts=args.artifacts, jobs=args.jobs)
    except OSError as error:
        print(f"denominators: {error}", file=sys.stderr)
        return 2
    if args.write_doc:
        owner = claim_rows(C.Findings(), result.records)
        readings = check_readings(C.Findings(), design_text(repo, args.design), result.records)
        write_doc(Path(args.doc or repo / DOC_REL), blocks(result.records, owner, readings, result.counts))
        print(f"denominators: wrote the generated blocks of {args.doc or DOC_REL}")
        return 0
    for key, (code, _out, secs) in sorted(result.runs.items()):
        verdict = ("reproduced" if code == 0 else "NOT RE-MEASURED on this host" if key in result.unavailable
                   else f"FAILED (exit {code})")
        print(f"  {key:<14} re-measured at {'HEAD' if args.current else 'its pin'}: {verdict} in {secs:.0f} s")
    for violation in result.findings.violations:
        print(violation, file=sys.stderr)
    c = result.counts
    if result.findings.violations:
        print(f"\ndenominators: {len(result.findings.violations)} violation(s)", file=sys.stderr)
        return 1
    if result.unavailable:
        print(f"\ndenominators: NOT RE-MEASURED on this host: {len(result.unavailable)} record(s) need pinned inputs "
              "this host does not hold; no violation was found, and this is not a pass:", file=sys.stderr)
        for key, why in sorted(result.unavailable.items()):
            print(f"  {key}: {why}", file=sys.stderr)
        return UNAVAILABLE_EXIT
    ran = f"{len(result.runs)} re-measured" if result.runs else "none re-measured (--no-run)"
    print(f"\ndenominators: OK (E0.12: {c['items']} Stage 0.5 items, {c['records']} records, {c['rows']} rows: "
          f"{c['measured']} measured, {c['blocked']} blocked, 0 without a predicate; {c['readings']} design "
          f"numbers read; {ran})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
