def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def copy_checked(src: Path, dest: Path, digest: str) -> str | None:
    """Copy src to dest unless dest already holds `digest`; None on success, else the problem."""
    if dest.is_file() and sha256_file(dest) == digest:
        return None
    if not src.is_file():
        return f"{src} does not exist"
    if sha256_file(src) != digest:
        return f"{src} is not the pinned bytes (sha256 {digest})"
    dest.parent.mkdir(parents=True, exist_ok=True)
    partial = dest.with_name(dest.name + ".partial")
    shutil.copyfile(src, partial)
    if sha256_file(partial) != digest:
        partial.unlink()
        return f"{src} changed while it was copied"
    partial.replace(dest)
    return None


def stash(repo: Path, records: dict, artifacts: Path) -> list[str]:
    problems = []
    build = main_checkout(repo) / "build"
    store = (Path(os.environ["ATPKG_BIN"]).parent / "store" if os.environ.get("ATPKG_BIN")
             else Path.home() / "Library/Application Support/aterm/pkg/store")
    roots = {"build": build, "atpkg-store": store}
    imports = records.get("imports")
    for name, inp in (imports.data.get("inputs", {}) if imports else {}).items():
        if not isinstance(inp, dict) or "sha256" not in inp:
            continue
        src = roots.get(inp.get("root"), build) / inp.get("path", "")
        dest = artifacts / "imports" / f"{inp['sha256'][:16]}-{Path(inp.get('path', name)).name}"
        problem = copy_checked(src, dest, inp["sha256"])
        print(f"stash imports {name}: {problem or dest}")
        if problem:
            problems.append(f"imports {name}: {problem}")
    surface = records.get("std-surface")
    if surface:
        table = surface.data.get("inputs", {}).get("host_build", {})
        src_root = main_checkout(repo) / STD_SURFACE_BUILD
        dest_root = artifacts / "std-surface" / host_build_key(surface)
        for crate in ("core", "alloc", "std"):
            info = table.get(crate)
            if not isinstance(info, dict):
                problems.append(f"std-surface: inputs.host_build has no {crate}")
                continue
            for rel_key, digest_key in (("depinfo", "depinfo_sha256"), ("fingerprint", "fingerprint_sha256")):
                rel, digest = info.get(rel_key, ""), info.get(digest_key, "").removeprefix("sha256:")
                problem = copy_checked(src_root / rel, dest_root / rel, digest)
                print(f"stash std-surface {rel}: {problem or dest_root / rel}")
                if problem:
                    problems.append(f"std-surface {rel}: {problem}")
            wanted = {d.removeprefix("sha256:") for d in info.get("build_script_output_sha256", [])}
            copied = set()
            for out in sorted((src_root / "build").glob(f"{crate}-*/output")) if wanted else []:
                digest = sha256_file(out)
                if digest in wanted:
                    rel = out.relative_to(src_root)
                    problem = copy_checked(out, dest_root / rel, digest)
                    print(f"stash std-surface {rel}: {problem or dest_root / rel}")
                    if problem:
                        problems.append(f"std-surface {rel}: {problem}")
                    else:
                        copied.add(digest)
            if wanted - copied:
                problems.append(f"std-surface: no build-script output of {crate} under {src_root / 'build'} has "
                                f"sha256 {sorted(wanted - copied)}")
    return problems


