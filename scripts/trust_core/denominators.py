    for r in READINGS:
        item = next((i for i in ITEMS if i.id == r.item), None)
        where = f"reading {r.item}/{r.row} ({r.number})"
        if item is None:
            findings.add("MDAGGER", f"{where}: no item {r.item}")
            continue
        count = collapsed.count(C.collapse(r.quote))
        if count != 1:
            findings.add("MDAGGER", f"{where}: the quote {r.quote!r} occurs {count} times in the design")
        if (not re.search(r"(?<![0-9])" + re.escape(r.number) + r"(?![0-9])", r.quote)
                or r.tag.rstrip("]") not in r.quote + " " + item.bullet):
            findings.add("MDAGGER", f"{where}: the quote does not hold the number {r.number} with its tag {r.tag}")
        rec = records.get(r.record)
        row = rec.rows.get(r.row) if rec else None
        if row is None:
            findings.add("MDAGGER", f"{where}: record {r.record} has no row {r.row}")
            continue
        value, number = row.get("value"), int(r.number)
        verdict = None
        if r.kind == "blocked":
            if row.get("status") != "blocked" or value is not None or not r.note:
                findings.add("MDAGGER", f"{where}: a `blocked` reading needs a blocked row with no value, and a note")
            else:
                verdict = "not measured: the row that would measure what the design's words name is blocked"
        elif not isinstance(value, int):
            findings.add("MDAGGER", f"{where}: the row has no measured value")
        elif r.kind == "other-predicate":
            if value != number or not r.note:
                findings.add("MDAGGER", f"{where}: an `other-predicate` reading needs the value {number} and a note; "
                                        f"the row measures {value}")
            verdict = "reproduced only under a different predicate than the design's words, not as worded"
        elif r.kind == "not-reproduced":
            if value == number or not r.note:
                findings.add("MDAGGER", f"{where}: a `not-reproduced` reading needs a value other than {number} and "
                                        "a note")
            verdict = f"not reproduced: what the design's words name measures {value}"
        elif r.kind == "equal":
            if value != number:
                findings.add("MDAGGER", f"{where}: the design says {number}, the row measures {value}: not reproduced, "
                                        "and no reading explains it")
            verdict = "reproduced"
        elif r.kind == "design-pin":
            added, removed = row.get("added_since_design_pin"), row.get("removed_since_design_pin")
            if not isinstance(added, list) or not isinstance(removed, list):
                findings.add("MDAGGER", f"{where}: the row records no added_since_design_pin/removed_since_design_pin")
            elif value - len(added) + len(removed) != number or value == number:
                findings.add("MDAGGER", f"{where}: at the design's pin the row gives {value - len(added) + len(removed)}, "
                                        f"at the measured pin {value}; the design says {number}")
            else:
                verdict = (f"reproduced at the design's own pin ({value} - {len(added)} added + {len(removed)} removed "
                           f"= {number}); the measured pin has {value}: the pin moved, not the predicate")
        elif r.kind == "other":
            if value == number or not r.note:
                findings.add("MDAGGER", f"{where}: an `other` reading needs a value other than {number} and a note")
            verdict = f"a different quantity: {value}"
        else:
            findings.add("MDAGGER", f"{where}: unknown kind {r.kind!r}")
        if verdict:
            out.append({"item": r.item, "number": r.number, "tag": r.tag, "quote": r.quote, "record": r.record,
                        "row": r.row, "value": value, "verdict": verdict, "note": r.note})
    for item in ITEMS:
        if "[M†" in item.bullet and not any(r.item == item.id and r.tag == "[M†]" for r in READINGS):
            findings.add("MDAGGER", f"item {item.id}: the design attaches an [M†] number and no reading compares it")
    return out


