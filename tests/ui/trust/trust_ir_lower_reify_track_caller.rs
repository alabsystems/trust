//! Trust (wave-RTC): reifying a `#[track_caller]` function to a fn pointer.
//!
//! `Instance::resolve_for_fn_ptr` rewrites an `Item` that `requires_caller_location`
//! into `Shim(ShimKind::Reify(def, reason))`, because codegen must point the pointer
//! at a wrapper supplying the implicit caller-location argument. The producer refused
//! that shim outright, and the refusal was not free: `core`'s arithmetic impls carry
//! `#[track_caller]` (`library/core/src/ops/arith.rs`, inside `add_impl!`), so every
//! `<i32 as Add<i32>>::add` reification in the corpus wore `Reify(instance shim)`.
//!
//! WHY IT IS ADMISSIBLE. The shim adds no computation — `ShimKind::Reify(def_id, _)`
//! builds a plain forwarding `CallKind::Direct` — so `S(a..) = resolved(a.., L)` for
//! one fixed `L`. And `L` is not spellable in trust-ir: there is no `Location` term,
//! a body whose content is `Location::caller()` lowers to a call to a BODYLESS
//! declaration (havoc), and `assert` carries no location. No trust-ir term can
//! distinguish two values of `L`.
//!
//! The decisive point is that this abstraction ALREADY SHIPS. An ordinary direct call
//! to a `#[track_caller]` function lowers clean today and emits a plain call, so every
//! call site — each with a different `L` — already shares one lowered body, which is
//! therefore already required to be sound for every `L`. The reified pointer is one
//! more caller with one more `L`. Admitting it relies on nothing new; refusing it
//! bought nothing.
//!
//! Under `strict`, so a refusal is a compile error. `check-pass` is the assertion:
//! every body here must lower with no unsupported shape.

#![allow(dead_code)]
use std::ops::Add;

#[track_caller]
pub fn tc(x: i32) -> i32 {
    x + 1
}

pub fn plain(x: i32) -> i32 {
    x + 2
}

// A1 — the core shape. Reifying a `#[track_caller]` fn item as a `const` fn pointer.
pub const CT: fn(i32) -> i32 = tc;

// A2 — the CONTROL that was already clean, kept here so a regression that closes the
// whole reify lane (rather than just this arm) is distinguishable from one that
// closes only the new arm.
pub const CP: fn(i32) -> i32 = plain;

// A3 — the corpus shape: `core`'s `impl Add for i32` is `#[track_caller]`, in both
// `const` and `static` position. This is the one that matters — all 11 corpus bodies
// are `<i32 as Add<i32>>::add` reifications generated by `ufcs-polymorphic-paths.rs`.
//
// The pointers are deliberately NOT CALLED here. Calling THROUGH a fn pointer is a
// separate unsupported shape (`Call(fn-ptr callee unsupported)` plus
// `NamedConst(non-scalar)` on the const itself), so a body that both reifies and calls
// would keep erroring under `strict` for a reason that has nothing to do with this
// lane — and would therefore fail to pin it. An earlier draft did exactly that; the
// fixture asserted `check-pass` and the calls, not the reify, is what refused.
pub const ADD_C: fn(i32, i32) -> i32 = <i32 as Add<i32>>::add;
pub static ADD_S: fn(i32, i32) -> i32 = <i32 as Add<i32>>::add;

// A4 — a `let` binding rather than an item, so the coercion happens inside a body
// rather than in a const initializer. Same reason as A3 for not calling it.
pub fn local_binding() {
    let _f: fn(i32) -> i32 = tc;
}

// A5 — passed as an ARGUMENT, the shape that motivates fn pointers at all, and the one
// that proves the reify is admitted in value position and not only in a const.
pub fn takes(_f: fn(i32) -> i32) {}

pub fn pass_track_caller() {
    takes(tc);
}
