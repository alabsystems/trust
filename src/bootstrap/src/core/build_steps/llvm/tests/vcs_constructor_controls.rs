use super::*;

fn configure(
    builder: &Builder<'_>,
    root: &Path,
    label: &str,
    helper: &Path,
    body: &str,
    recording: Option<&str>,
) -> PathBuf {
    let project = root.join(format!("{label} project"));
    let output = root.join(format!("{label} output"));
    fs::create_dir_all(&project).unwrap();
    let environment = match recording {
        Some(value) => format!("set(ENV{{TRUST_VCS_REQUEST_DECLARATIONS}} {})\n", literal(value)),
        None => "unset(ENV{TRUST_VCS_REQUEST_DECLARATIONS})\n".into(),
    };
    fs::write(project.join("CMakeLists.txt"), format!(
        "cmake_minimum_required(VERSION 3.20)\nproject(VCSControls NONE)\n{environment}\nset(request_helper {})\n{body}\n",
        literal(helper.to_str().unwrap()),
    )).unwrap();
    let mut cmake = cmake::Config::new(&project);
    cmake
        .out_dir(&output)
        .profile("Release")
        .target(&builder.host_target.triple)
        .host(&builder.host_target.triple)
        .generator("Ninja")
        .build_arg("-j")
        .build_arg("1")
        .build_target("observe");
    cmake.build();
    output
}

fn decode(value: &str) -> Vec<u8> {
    let (length, hex) = value.split_once(':').unwrap();
    assert_eq!(hex.len() % 2, 0);
    let bytes: Vec<_> = hex
        .as_bytes()
        .chunks_exact(2)
        .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
        .collect();
    assert_eq!(bytes.len(), length.parse::<usize>().unwrap());
    bytes
}

fn argv(path: &Path) -> Vec<Vec<u8>> {
    let contents = fs::read_to_string(path).unwrap();
    let mut lines = contents.lines();
    let count = lines.next().unwrap().parse::<usize>().unwrap();
    let values: Vec<_> = lines.map(decode).collect();
    assert_eq!(values.len(), count);
    values
}

fn declaration(output: &Path) -> String {
    let directory = output.join("build/.trust-vcs-request-declarations");
    let entries: Vec<_> =
        fs::read_dir(&directory).unwrap().map(|entry| entry.unwrap().path()).collect();
    assert_eq!(entries.len(), 1, "one header declaration, no temporary records");
    assert_eq!(entries[0].extension().unwrap(), "data");
    fs::read_to_string(&entries[0]).unwrap()
}

fn arguments(record: &str) -> Vec<Vec<u8>> {
    assert!(record.starts_with("trust.vcs.raw-construction/v1\nauthority none\n"));
    let count = record
        .lines()
        .find_map(|line| line.strip_prefix("argc "))
        .unwrap()
        .parse::<usize>()
        .unwrap();
    let args: Vec<_> =
        record.lines().filter_map(|line| line.strip_prefix("arg ")).map(decode).collect();
    assert_eq!(args.len(), count);
    args
}

pub(super) fn run(builder: &Builder<'_>, root: &Path, helper: &Path, capture: &Path) {
    // Real child argv and generated bytes must agree, including scalar values
    // that CMake list reconstruction would split or consume as quoting syntax.
    let label = "raw scalars";
    let output = root.join(format!("{label} output"));
    let header = output.join("build/raw.inc");
    let revision = "revision;with\"quote\\suffix\\";
    let repository = "https://example.invalid/repo;with\\slash\"suffix\\";
    let mut observations = Vec::new();
    for refactored in [false, true] {
        let _ = fs::remove_file(&header);
        let _ = fs::remove_file(header.with_extension("inc.argv"));
        let call = if refactored {
            format!("llvm_add_vcs_command({} OUTPUT", literal(header.to_str().unwrap()))
        } else {
            "add_custom_command(OUTPUT".into()
        };
        let body = format!(
            "include(\"${{request_helper}}\")\n{call} {} COMMAND \"${{CMAKE_COMMAND}}\" {} {} {} {} {} -P {} VERBATIM )\nadd_custom_target(observe DEPENDS {})\n",
            literal(header.to_str().unwrap()),
            literal("-DNAMES=LLVM"),
            literal("-DLLVM_SOURCE_DIR="),
            literal(&format!("-DHEADER_FILE={}", header.display())),
            literal(&format!("-DLLVM_FORCE_VC_REVISION={revision}")),
            literal(&format!("-DLLVM_FORCE_VC_REPOSITORY={repository}")),
            literal(capture.to_str().unwrap()),
            literal(header.to_str().unwrap()),
        );
        let built = configure(builder, root, label, helper, &body, None);
        assert!(!built.join("build/.trust-vcs-request-declarations").exists());
        let actual = argv(&header.with_extension("inc.argv"));
        assert!(actual.contains(&format!("-DLLVM_FORCE_VC_REVISION={revision}").into_bytes()));
        assert!(actual.contains(&format!("-DLLVM_FORCE_VC_REPOSITORY={repository}").into_bytes()));
        assert!(actual.contains(&b"-DLLVM_SOURCE_DIR=".to_vec()));
        observations.push((actual, fs::read(&header).unwrap()));
    }
    assert_eq!(observations[0], observations[1], "raw scalar child/header preservation");

    // CMP0116 changes the real generated Ninja depfile command. A function
    // defined under the wrong caller policy changes this observable behavior.
    for policy in ["OLD", "NEW"] {
        let label = format!("policy {policy}");
        let output = root.join(format!("{label} output"));
        let header = output.join("build/policy.inc");
        let opposite = if policy == "OLD" { "NEW" } else { "OLD" };
        let mut behavior = Vec::new();
        for refactored in [false, true] {
            let _ = fs::remove_file(&header);
            let call = if refactored {
                format!("llvm_add_vcs_command({} OUTPUT", literal(header.to_str().unwrap()))
            } else {
                "add_custom_command(OUTPUT".into()
            };
            let body = format!(
                "cmake_policy(SET CMP0116 {opposite})\ninclude(\"${{request_helper}}\")\ncmake_policy(SET CMP0116 {policy})\ninclude(\"${{request_helper}}\")\nfile(WRITE \"${{CMAKE_CURRENT_BINARY_DIR}}/metadata.d\" \"\")\n{call} {} DEPFILE \"metadata.d\" COMMAND \"${{CMAKE_COMMAND}}\" \"-DNAMES=LLVM\" \"-DLLVM_SOURCE_DIR=\" {} \"-DLLVM_FORCE_VC_REVISION=policy\" -P {} )\nadd_custom_target(observe DEPENDS {})\n",
                literal(header.to_str().unwrap()),
                literal(&format!("-DHEADER_FILE={}", header.display())),
                literal(capture.to_str().unwrap()),
                literal(header.to_str().unwrap()),
            );
            configure(builder, root, &label, helper, &body, None);
            let ninja = fs::read_to_string(output.join("build/build.ninja")).unwrap();
            behavior.push(ninja.contains("cmake_transform_depfile"));
        }
        assert_eq!(behavior, [policy == "NEW", policy == "NEW"], "actual {policy} depfile policy");
    }

    // Declared raw inputs are data. Neither invalid bounds nor conflicting
    // declarations may fail an otherwise valid CMake build or become authority.
    let label = "declarations";
    let output = root.join(format!("{label} output"));
    let header = output.join("build/declared.inc");
    let raw = "empty;quote\"backslash\\suffix\\";
    let command = |argument: &str| {
        format!(
            "include(\"${{request_helper}}\")\nllvm_add_vcs_command({} OUTPUT \"unused-output\" COMMAND \"${{CMAKE_COMMAND}}\" \"-E\" \"true\" {} {})\nadd_custom_target(observe)\n",
            literal(header.to_str().unwrap()),
            literal(argument),
            literal(""),
        )
    };
    configure(builder, root, label, helper, &command(raw), Some("OFF"));
    assert!(!output.join("build/.trust-vcs-request-declarations").exists());
    configure(builder, root, label, helper, &command(raw), Some("1"));
    let first = declaration(&output);
    let args = arguments(&first);
    assert!(args.contains(&raw.as_bytes().to_vec()));
    assert_eq!(args.last().unwrap(), &Vec::<u8>::new());
    configure(builder, root, label, helper, &command("reconfigured"), Some("1"));
    let changed = declaration(&output);
    assert_ne!(first, changed);
    assert!(arguments(&changed).contains(&b"reconfigured".to_vec()));
    let conflict = format!(
        "include(\"${{request_helper}}\")\nllvm_add_vcs_command({0} OUTPUT first-output COMMAND \"${{CMAKE_COMMAND}}\" -E true)\nllvm_add_vcs_command({0} OUTPUT second-output COMMAND \"${{CMAKE_COMMAND}}\" -E true)\nadd_custom_target(observe)\n",
        literal(header.to_str().unwrap()),
    );
    configure(builder, root, label, helper, &conflict, Some("1"));
    assert!(declaration(&output).contains("invalid conflicting declaration\n"));
    configure(builder, root, label, helper, &command("after conflict"), Some("1"));
    assert!(arguments(&declaration(&output)).contains(&b"after conflict".to_vec()));
    configure(builder, root, label, helper, &command(&"x".repeat(17000)), Some("1"));
    assert!(declaration(&output).contains("invalid bounds\n"));
    let many = format!(
        "include(\"${{request_helper}}\")\nllvm_add_vcs_command({} OUTPUT many-output COMMAND \"${{CMAKE_COMMAND}}\" -E true {})\nadd_custom_target(observe)\n",
        literal(header.to_str().unwrap()),
        (0..130).map(|_| literal("x")).collect::<Vec<_>>().join(" "),
    );
    configure(builder, root, label, helper, &many, Some("1"));
    assert!(declaration(&output).contains("invalid bounds\n"));
    configure(builder, root, label, helper, &command("after bounds"), Some("1"));
    assert!(arguments(&declaration(&output)).contains(&b"after bounds".to_vec()));
    println!("VCS raw argv, caller policy and declaration lifecycle controls completed");
}
