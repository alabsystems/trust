/// The current format version of [`EncodedDepInfo`].
// Trust: v1 omitted observed manifest paths; v2 could merge dependency names.
// v3 omitted Rust module alternative-path observations; an added competing
// module could therefore leave an invalid program falsely fresh.
// v4 omitted the compiler's tool-input completion record. Keep missing legacy
// producers distinct from explicit unavailable observations; only the caller
// decides whether its negotiated producer must provide the record.
// v5 could normalize an input filename's final CR as a record delimiter.
// Only a complete matching compiler inventory can select raw LF boundaries.
// v6 still omitted an explicit complete-filename observation and could grant
// legacy fallback rows content authority. v7 records unavailable by default.
const CURRENT_ENCODED_DEP_INFO_VERSION: u8 = 7;

// Trust: reserve the versioned protocol family so malformed/future records
// cannot disappear into legacy Makefile comments or fabricate dependencies.
const TOOL_INPUTS_PREFIX_FAMILY: &[u8] = b"# trust-tool-inputs-";

/// Compiler-produced tool-input data, never an execution or freshness grant.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum ToolInputsState {
    #[default]
    Missing,
    Unavailable,
    Observed(ToolInputs),
}

impl ToolInputsState {
    fn from_payload(payload: &[u8]) -> Self {
        if payload == tool_lookup::UNAVAILABLE.as_bytes()
            || payload.len() > tool_lookup::MAX_RECORD_BYTES
        {
            return Self::Unavailable;
        }
        ToolInputs::decode(payload).map_or(Self::Unavailable, Self::Observed)
    }

    fn encoded(&self) -> (u8, Vec<u8>) {
        match self {
            Self::Missing => (0, Vec::new()),
            Self::Unavailable => (1, Vec::new()),
            Self::Observed(inputs) => match inputs.encode() {
                Ok(payload) if payload.len() <= tool_lookup::MAX_RECORD_BYTES => (2, payload),
                // Serialization failure cannot turn successful compilation
                // into a fabricated observation or a new compiler error.
                _ => (1, Vec::new()),
            },
        }
    }
}

/// Trust: the internal read-set format actually written and accepted by this binary.
/// This is software metadata, not the compiler's dep-info wire format or a proof grade.
pub const fn encoded_dep_info_version() -> u8 {
    CURRENT_ENCODED_DEP_INFO_VERSION
}

// Trust: every unavailable read-set remains a cache miss. Preserve the cause
// from the same read/decoder pass rather than probing the file again for labels.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, thiserror::Error)]
#[serde(tag = "kind", rename_all = "kebab-case")]
pub enum DepInfoUnavailable {
    #[error("encoded dep-info file is missing")]
    Missing,
    #[error("encoded dep-info could not be read")]
    Unreadable,
    #[error("encoded dep-info is invalid or unrecognized")]
    Malformed,
    #[error("encoded dep-info format mismatch (recorded {recorded}, current {current})")]
    FormatMismatch { recorded: u8, current: u8 },
    #[error("encoded dep-info names an unavailable relocation root")]
    RelocationRootUnavailable,
    #[error("compiler filename inventory is incomplete or ambiguous")]
    FilenameInventoryIncomplete,
}

/// The representation of the `.d` dep-info file generated by rustc
#[derive(Default)]
pub struct RustcDepInfo {
    /// Trust: whole canonical compiler inventory, never a legacy parse guess.
    pub filename_inventory_complete: bool,
    /// The list of files that the main target in the dep-info file depends on.
    ///
    /// The optional checksums are parsed from the special `# checksum:...` comments.
    pub files: HashMap<PathBuf, Option<(u64, Checksum)>>,
    /// The list of environment variables we found that the rustc compilation
    /// depends on.
    ///
    /// The first element of the pair is the name of the env var and the second
    /// item is the value. `Some` means that the env var was set, and `None`
    /// means that the env var wasn't actually set and the compilation depends
    /// on it not being set.
    ///
    /// These are from the special `# env-var:...` comments.
    pub env: Vec<(String, Option<String>)>,
    /// Trust: opposite Rust module locations observed alongside real source
    /// dependencies. None is unavailable, never authority to reuse.
    pub module_candidates: Vec<(PathBuf, Option<bool>)>,
    /// Trust: strict compiler tool data, with absence preserved for negotiation.
    pub tool_inputs: ToolInputsState,
}

/// Tells the associated path in [`EncodedDepInfo::files`] is relative to package root,
/// target root, or absolute.
#[derive(Debug, Eq, PartialEq, Hash, Copy, Clone)]
pub enum DepInfoPathType {
    /// src/, e.g. src/lib.rs
    PackageRootRelative,
    /// {build-dir}/debug/deps/lib...
    /// or an absolute path /.../sysroot/...
    BuildRootRelative,
    /// Relative to the workspace root (but not in the package root)
    WorkspaceRootRelative,
    /// Trust: an absolute path under a `-Ztrust-relocation-roots` root,
    /// recorded by root token and expanded with the current roots. Encoded as
    /// path type 3, which older Targo and Cargo reject, reading the whole
    /// record as corrupt (stale) rather than misreading the path; records
    /// without such entries have the same layout; this path type does not
    /// require a separate format revision.
    RelocationRootRelative,
}

/// Same as [`RustcDepInfo`] except avoids absolute paths as much as possible to
/// allow moving around the target directory.
///
/// This is also stored in an optimized format to make parsing it fast because
/// Cargo will read it for crates on all future compilations.
///
/// Currently the format looks like:
///
/// ```text
/// marker | version | filename inventory | files | environment | Rust module candidates | tool inputs
/// ```
///
/// Each field represents
///
/// * _Marker_ --- A magic marker to ensure that older Cargoes, which only
///   recognize format v0 (prior to checksum support in [`f4ca7390`]), do not
///   proceed with parsing newer formats. Since [`EncodedDepInfo`] is merely
///   an optimization, and to avoid adding complexity, Cargo recognizes only
///   one version of [`CURRENT_ENCODED_DEP_INFO_VERSION`].
///   The current layout looks like this
///   ```text
///   +----------------------------+
///   | [0x01 0x00 0x00 0x00 0xff] |
///   +----------------------------+
///   ```
///   These bytes will be interpreted as "one file tracked and an invalid
///   [`DepInfoPathType`] variant with 255" by older Cargoes, causing them to
///   stop parsing. This could prevent problematic parsing as noted in
///   rust-lang/cargo#14712.
/// * _Version_ --- The current format version.
/// * _Filename inventory_ --- One strict byte: zero unavailable, one complete.
///   Content reuse requires complete canonical filename boundaries; Cargo
///   mtime parsing remains separate. This is data, not proof authority.
/// * _Number of files/envs_ --- A `u32` representing the number of things.
/// * _File paths_ --- Zero or more paths of files the dep-info file depends on.
///   Each path is encoded as the following:
///
///   ```text
///   +-----------+-------------+------------+---------------+-----------+-------+
///   | path type | len of path | path bytes | cksum exists? | file size | cksum |
///   +-----------+-------------+------------+---------------+-----------+-------+
///   ```
/// * _Env var pairs_ --- Zero or more env vars the dep-info file depends on.
///   Each env key-value pair is encoded as the following:
///   ```text
///   +------------+-----------+---------------+--------------+-------------+
///   | len of key | key bytes | value exists? | len of value | value bytes |
///   +------------+-----------+---------------+--------------+-------------+
///   ```
/// * _Module candidates_ --- A `u32` count followed by each path type, length,
///   raw path bytes and one state byte: zero absent, one present, two unavailable.
///   These observations are cache invalidation data, never source/proof authority.
/// * _Tool inputs_ --- A status byte (zero missing, one unavailable, two observed),
///   a `u32` payload length and bounded canonical shared JSON for observed data.
///   Missing/unavailable statuses require zero length. Unknown statuses, malformed
///   payloads and trailing bytes reject the encoded read-set rather than reuse it.
///
/// [`f4ca7390`]: https://github.com/rust-lang/cargo/commit/f4ca739073185ea5e1148ff100bb4a06d3bf721d
#[derive(Default, Debug, PartialEq, Eq)]
pub struct EncodedDepInfo {
    pub filename_inventory_complete: bool,
    pub files: Vec<(DepInfoPathType, PathBuf, Option<(u64, String)>)>,
    pub env: Vec<(String, Option<String>)>,
    pub module_candidates: Vec<(DepInfoPathType, PathBuf, Option<bool>)>,
    pub tool_inputs: ToolInputsState,
}

impl EncodedDepInfo {
    pub fn parse(mut bytes: &[u8]) -> Result<EncodedDepInfo, DepInfoUnavailable> {
        let mut unavailable = DepInfoUnavailable::Malformed;
        let parsed = (|| {
            let bytes = &mut bytes;
            read_magic_marker(bytes)?;
            let version = read_u8(bytes)?;
            if version != CURRENT_ENCODED_DEP_INFO_VERSION {
                unavailable = DepInfoUnavailable::FormatMismatch {
                    recorded: version,
                    current: CURRENT_ENCODED_DEP_INFO_VERSION,
                };
                return None;
            }

            let filename_inventory_complete = match read_u8(bytes)? {
                0 => false,
                1 => true,
                _ => return None,
            };
            let nfiles = read_usize(bytes)?;
            let mut files = Vec::with_capacity(nfiles);
            for _ in 0..nfiles {
                let ty = match read_u8(bytes)? {
                    0 => DepInfoPathType::PackageRootRelative,
                    1 => DepInfoPathType::BuildRootRelative,
                    2 => DepInfoPathType::WorkspaceRootRelative,
                    // Trust: see `DepInfoPathType::RelocationRootRelative`.
                    3 => DepInfoPathType::RelocationRootRelative,
                    _ => return None,
                };
                let path_bytes = read_bytes(bytes)?;
                let path = paths::bytes2path(path_bytes).ok()?;
                let has_checksum = read_bool(bytes)?;
                let checksum_info = has_checksum
                    .then(|| {
                        let file_len = read_u64(bytes);
                        let checksum_string = read_bytes(bytes)
                            .map(Vec::from)
                            .and_then(|v| String::from_utf8(v).ok());
                        file_len.zip(checksum_string)
                    })
                    .flatten();
                files.push((ty, path, checksum_info));
            }

            let nenv = read_usize(bytes)?;
            let mut env = Vec::with_capacity(nenv);
            for _ in 0..nenv {
                let key = str::from_utf8(read_bytes(bytes)?).ok()?.to_string();
                let val = match read_u8(bytes)? {
                    0 => None,
                    1 => Some(str::from_utf8(read_bytes(bytes)?).ok()?.to_string()),
                    _ => return None,
                };
                env.push((key, val));
            }
            let ncandidates = read_usize(bytes)?;
            // Every entry requires a type, path length and state byte. Bound
            // the new allocation against actual remaining encoded bytes.
            if ncandidates > bytes.len() / 6 {
                return None;
            }
            let mut module_candidates = Vec::with_capacity(ncandidates);
            for _ in 0..ncandidates {
                let ty = match read_u8(bytes)? {
                    0 => DepInfoPathType::PackageRootRelative,
                    1 => DepInfoPathType::BuildRootRelative,
                    2 => DepInfoPathType::WorkspaceRootRelative,
                    3 => DepInfoPathType::RelocationRootRelative,
                    _ => return None,
                };
                let path = paths::bytes2path(read_bytes(bytes)?).ok()?;
                let observed = match read_u8(bytes)? {
                    0 => Some(false),
                    1 => Some(true),
                    2 => None,
                    _ => return None,
                };
                module_candidates.push((ty, path, observed));
            }
            let status = read_u8(bytes)?;
            let payload_len = read_usize(bytes)?;
            // Check the claimed size before slicing or invoking any decoder.
            if payload_len > tool_lookup::MAX_RECORD_BYTES || payload_len > bytes.len() {
                return None;
            }
            let (payload, remaining) = bytes.split_at(payload_len);
            *bytes = remaining;
            let tool_inputs = match status {
                0 if payload.is_empty() => ToolInputsState::Missing,
                1 if payload.is_empty() => ToolInputsState::Unavailable,
                2 => ToolInputsState::Observed(ToolInputs::decode(payload).ok()?),
                _ => return None,
            };
            if !bytes.is_empty() {
                return None;
            }
            Some(EncodedDepInfo {
                filename_inventory_complete,
                files,
                env,
                module_candidates,
                tool_inputs,
            })
        })();
        return parsed.ok_or(unavailable);

        /// See [`EncodedDepInfo`] for why a magic marker exists.
        fn read_magic_marker(bytes: &mut &[u8]) -> Option<()> {
            let _size = read_usize(bytes)?;
            let path_type = read_u8(bytes)?;
            if path_type != u8::MAX {
                // Old depinfo. Give up parsing it.
                None
            } else {
                Some(())
            }
        }

        fn read_usize(bytes: &mut &[u8]) -> Option<usize> {
            let ret = bytes.get(..4)?;
            *bytes = &bytes[4..];
            Some(u32::from_le_bytes(ret.try_into().unwrap()) as usize)
        }

        fn read_u64(bytes: &mut &[u8]) -> Option<u64> {
            let ret = bytes.get(..8)?;
            *bytes = &bytes[8..];
            Some(u64::from_le_bytes(ret.try_into().unwrap()))
        }

        fn read_bool(bytes: &mut &[u8]) -> Option<bool> {
            read_u8(bytes).map(|b| b != 0)
        }

        fn read_u8(bytes: &mut &[u8]) -> Option<u8> {
            let ret = *bytes.get(0)?;
            *bytes = &bytes[1..];
            Some(ret)
        }

        fn read_bytes<'a>(bytes: &mut &'a [u8]) -> Option<&'a [u8]> {
            let n = read_usize(bytes)? as usize;
            let ret = bytes.get(..n)?;
            *bytes = &bytes[n..];
            Some(ret)
        }
    }

    pub fn serialize(&self) -> CargoResult<Vec<u8>> {
        let mut ret = Vec::new();
        let dst = &mut ret;

        write_magic_marker(dst);
        dst.push(CURRENT_ENCODED_DEP_INFO_VERSION);
        dst.push(u8::from(self.filename_inventory_complete));

        write_usize(dst, self.files.len());
        for (ty, file, checksum_info) in self.files.iter() {
            match ty {
                DepInfoPathType::PackageRootRelative => dst.push(0),
                DepInfoPathType::BuildRootRelative => dst.push(1),
                DepInfoPathType::WorkspaceRootRelative => dst.push(2),
                // Trust: see `DepInfoPathType::RelocationRootRelative`.
                DepInfoPathType::RelocationRootRelative => dst.push(3),
            }
            write_bytes(dst, paths::path2bytes(file)?);
            write_bool(dst, checksum_info.is_some());
            if let Some((len, checksum)) = checksum_info {
                write_u64(dst, *len);
                write_bytes(dst, checksum);
            }
        }

        write_usize(dst, self.env.len());
        for (key, val) in self.env.iter() {
            write_bytes(dst, key);
            match val {
                None => dst.push(0),
                Some(val) => {
                    dst.push(1);
                    write_bytes(dst, val);
                }
            }
        }
        write_usize(dst, self.module_candidates.len());
        for (ty, path, observed) in &self.module_candidates {
            dst.push(match ty {
                DepInfoPathType::PackageRootRelative => 0,
                DepInfoPathType::BuildRootRelative => 1,
                DepInfoPathType::WorkspaceRootRelative => 2,
                DepInfoPathType::RelocationRootRelative => 3,
            });
            write_bytes(dst, paths::path2bytes(path)?);
            dst.push(match observed {
                Some(false) => 0,
                Some(true) => 1,
                None => 2,
            });
        }
        let (status, payload) = self.tool_inputs.encoded();
        dst.push(status);
        write_bytes(dst, payload);
        return Ok(ret);

        /// See [`EncodedDepInfo`] for why a magic marker exists.
        ///
        /// There is an assumption that there is always at least a file.
        fn write_magic_marker(dst: &mut Vec<u8>) {
            write_usize(dst, 1);
            dst.push(u8::MAX);
        }

        fn write_bytes(dst: &mut Vec<u8>, val: impl AsRef<[u8]>) {
            let val = val.as_ref();
            write_usize(dst, val.len());
            dst.extend_from_slice(val);
        }

        fn write_usize(dst: &mut Vec<u8>, val: usize) {
            dst.extend(&u32::to_le_bytes(val as u32));
        }

        fn write_u64(dst: &mut Vec<u8>, val: u64) {
            dst.extend(&u64::to_le_bytes(val));
        }

        fn write_bool(dst: &mut Vec<u8>, val: bool) {
            dst.push(u8::from(val));
        }
    }
}

/// Parses the dep-info file coming out of rustc into a Cargo-specific format.
///
/// This function will parse `rustc_dep_info` as a makefile-style dep info to
/// learn about the all files which a crate depends on. This is then
/// re-serialized into the `cargo_dep_info` path in a Cargo-specific format.
///
/// The `pkg_root` argument here is the absolute path to the directory
/// containing `Cargo.toml` for this crate that was compiled. The paths listed
/// in the rustc dep-info file may or may not be absolute but we'll want to
/// consider all of them relative to the `root` specified.
///
/// The `rustc_cwd` argument is the absolute path to the cwd of the compiler
/// when it was invoked.
///
/// If the `allow_package` argument is true, then package-relative paths are
/// included. If it is false, then package-relative paths are skipped and
/// ignored (typically used for registry or git dependencies where we assume
/// the source never changes, and we don't want the cost of running `stat` on
/// all those files). See the module-level docs for the note about
/// `-Zbinary-dep-depinfo` for more details on why this is done.
///
/// The serialized Cargo format will contain a list of files, all of which are
/// relative if they're under `root`. or absolute if they're elsewhere.
///
/// The `env_config` argument is a set of environment variables that are
/// defined in `[env]` table of the `config.toml`.
///
/// Trust: `relocation` holds the `-Ztrust-relocation-roots` roots, if any. An
/// absolute path outside the build, package and workspace roots but under one
/// of them is recorded by root token. Env-dep values are never rewritten: they
/// are compiled into the artifact, so a different value must still rebuild.
pub fn translate_dep_info(
    rustc_dep_info: &Path,
    cargo_dep_info: &Path,
    rustc_cwd: &Path,
    pkg_root: &Path,
    build_root: &Path,
    ws_root: &Path,
    rustc_cmd: &ProcessBuilder,
    allow_package: bool,
    preserve_source_paths: bool,
    env_config: &Arc<HashMap<String, OsString>>,
    relocation: Option<&RelocationRoots>,
) -> CargoResult<()> {
    let depinfo = parse_rustc_dep_info(rustc_dep_info)?;

    let build_root = crate::util::try_canonicalize(build_root)?;
    let pkg_root = crate::util::try_canonicalize(pkg_root)?;
    let ws_root = crate::util::try_canonicalize(ws_root)?;
    let package_in_workspace = pkg_root.starts_with(&ws_root);
    let mut on_disk_info = EncodedDepInfo::default();
    on_disk_info.filename_inventory_complete = depinfo.filename_inventory_complete;
    on_disk_info.env = depinfo.env;
    on_disk_info.tool_inputs = depinfo.tool_inputs;

    // This is a bit of a tricky statement, but here we're *removing* the
    // dependency on environment variables that were defined specifically for
    // the command itself. Environment variables returned by `get_envs` includes
    // environment variables like:
    //
    // * `OUT_DIR` if applicable
    // * env vars added by a build script, if any
    //
    // The general idea here is that the dep info file tells us what, when
    // changed, should cause us to rebuild the crate. These environment
    // variables are synthesized by Cargo and/or the build script, and the
    // intention is that their values are tracked elsewhere for whether the
    // crate needs to be rebuilt.
    //
    // For example a build script says when it needs to be rerun and otherwise
    // it's assumed to produce the same output, so we're guaranteed that env
    // vars defined by the build script will always be the same unless the build
    // script itself reruns, in which case the crate will rerun anyway.
    //
    // For things like `OUT_DIR` it's a bit sketchy for now. Most of the time
    // that's used for code generation but this is technically buggy where if
    // you write a binary that does `println!("{}", env!("OUT_DIR"))` we won't
    // recompile that if you move the target directory. Hopefully that's not too
    // bad of an issue for now...
    //
    // This also includes `CARGO` since if the code is explicitly wanting to
    // know that path, it should be rebuilt if it changes. The CARGO path is
    // not tracked elsewhere in the fingerprint.
    //
    // For cargo#13280, We trace env vars that are defined in the `[env]` config table.
    on_disk_info.env.retain(|(key, _)| {
        ManifestMetadata::should_track(key)
            || ManifestPathEnv::from_key(key, crate::is_targo_invocation()).is_some()
            || (rustc_cmd.has_action_sandbox()
                && crate::compiler::action_command::is_transport_environment(key))
            || env_config.contains_key(key)
            || !rustc_cmd.get_envs().contains_key(key)
            || key == CARGO_ENV
    });

    let serialize_path = |file| {
        let abs_file = rustc_cwd.join(file);
        // Native content records bind the path the compiler opened, not just
        // its current symlink target. Canonicalizing it would leave a later
        // retarget invisible while the original target remains unchanged.
        let tracked_file = if preserve_source_paths {
            abs_file.clone()
        } else {
            crate::util::try_canonicalize(&abs_file).unwrap_or_else(|_| abs_file.clone())
        };

        let (ty, path) = if let Ok(stripped) = tracked_file.strip_prefix(&build_root) {
            (DepInfoPathType::BuildRootRelative, stripped)
        } else if let Ok(stripped) = tracked_file.strip_prefix(&pkg_root) {
            if !allow_package {
                return None;
            }
            (DepInfoPathType::PackageRootRelative, stripped)
        } else if package_in_workspace && let Ok(stripped) = tracked_file.strip_prefix(&ws_root) {
            (DepInfoPathType::WorkspaceRootRelative, stripped)
        } else if let Some(tokenized) = relocation.and_then(|roots| {
            roots
                .tokenize_path(&abs_file)
                .or_else(|| roots.tokenize_path(&tracked_file))
        }) {
            // Trust: see `DepInfoPathType::RelocationRootRelative`.
            return Some((DepInfoPathType::RelocationRootRelative, tokenized));
        } else {
            // It's definitely not target root relative, but this is an absolute path (since it was
            // joined to rustc_cwd) and as such re-joining it later to the target root will have no
            // effect.
            (DepInfoPathType::BuildRootRelative, &*abs_file)
        };
        Some((ty, path.to_owned()))
    };

    let mut candidates = std::collections::BTreeMap::new();
    for (file, checksum_info) in depinfo.files {
        let alternate = preserve_source_paths
            .then(|| super::module_candidates::alternate(&rustc_cwd.join(&file)))
            .flatten();
        let Some((path_type, path)) = serialize_path(file) else {
            continue;
        };
        if let Some(alternate) = alternate
            && let Some(encoded) = serialize_path(alternate.clone())
        {
            candidates.insert(alternate, encoded);
        }
        on_disk_info.files.push((
            path_type,
            path,
            checksum_info.map(|(len, checksum)| (len, checksum.to_string())),
        ));
    }
    for (path, (ty, encoded)) in candidates {
        on_disk_info.module_candidates.push((
            ty,
            encoded,
            super::module_candidates::observe(&path),
        ));
    }
    paths::write(cargo_dep_info, on_disk_info.serialize()?)?;
    Ok(())
}

/// Parse the `.d` dep-info file generated by rustc.
pub fn parse_rustc_dep_info(rustc_dep_info: &Path) -> CargoResult<RustcDepInfo> {
    let contents = paths::read_bytes(rustc_dep_info)?;
    let mut ret = RustcDepInfo::default();
    let mut primary_rhs = None;
    let mut filename_rows_valid = true;
    let mut found_tool_inputs = false;
    // Trust: selected only by a complete canonical phony inventory.
    let mut raw_filename_rows = false;

    for raw_line in contents.split_inclusive(|byte| *byte == b'\n') {
        // Inspect original tool bytes first: JSON may contain `: `, invalid
        // UTF-8 or a trailing CR. Strip only the owning LF before strict decode.
        let tool_line = raw_line.strip_suffix(b"\n").unwrap_or(raw_line);
        if tool_line.starts_with(TOOL_INPUTS_PREFIX_FAMILY) {
            filename_rows_valid &= str::from_utf8(tool_line).is_ok();
            ret.tool_inputs = if found_tool_inputs {
                ToolInputsState::Unavailable
            } else {
                tool_line
                    .strip_prefix(tool_lookup::DEP_INFO_PREFIX.as_bytes())
                    .map_or(ToolInputsState::Unavailable, ToolInputsState::from_payload)
            };
            found_tool_inputs = true;
            continue;
        }
        // Preserve the legacy UTF-8 and CRLF behavior for every other row.
        let line = str::from_utf8(raw_line)?.lines().next().unwrap_or_default();
        if let Some(rest) = line.strip_prefix("# env-dep:") {
            let mut parts = rest.splitn(2, '=');
            let Some(env_var) = parts.next() else {
                continue;
            };
            let env_val = match parts.next() {
                Some(s) => Some(unescape_env(s)?),
                None => None,
            };
            ret.env.push((unescape_env(env_var)?, env_val));
        } else if let Some(pos) = line.find(": ") {
            let physical_rhs = &str::from_utf8(tool_line)?[pos + 2..];
            let legacy_rhs = &line[pos + 2..];
            if let Some(primary) = primary_rhs {
                let rhs = if raw_filename_rows {
                    physical_rhs
                } else {
                    legacy_rhs
                };
                // Trust: every output rule of a canonical compiler inventory
                // uses the same inputs. Retain Cargo's first-rule data only.
                filename_rows_valid &= primary == rhs;
                continue;
            }
            // Trust: rustc also writes each input as a separate phony target.
            // Use those boundaries only when their canonical encoded inventory
            // matches this entire RHS. Otherwise preserve the legacy parser.
            let raw_paths = matching_phony_dependencies(&contents, physical_rhs, true);
            raw_filename_rows = raw_paths.is_some();
            primary_rhs = Some(if raw_filename_rows {
                physical_rhs
            } else {
                legacy_rhs
            });
            if let Some(paths) =
                raw_paths.or_else(|| matching_phony_dependencies(&contents, legacy_rhs, false))
            {
                ret.filename_inventory_complete = true;
                for path in paths {
                    ret.files.entry(path).or_default();
                }
                continue;
            }
            let mut deps = legacy_rhs.split_whitespace();

            while let Some(s) = deps.next() {
                let mut file = s.to_string();
                while file.ends_with('\\') {
                    file.pop();
                    file.push(' ');
                    file.push_str(deps.next().ok_or_else(|| {
                        crate::util::internal("malformed dep-info format, trailing \\")
                    })?);
                }
                ret.files.entry(file.into()).or_default();
            }
        } else if let Some(rest) = (if raw_filename_rows {
            str::from_utf8(tool_line)?
        } else {
            line
        })
        .strip_prefix("# checksum:")
        {
            let mut parts = rest.splitn(3, ' ');
            let Some(checksum) = parts.next().map(Checksum::from_str).transpose()? else {
                continue;
            };
            let Some(Ok(file_len)) = parts
                .next()
                .and_then(|s| s.strip_prefix("file_len:").map(|s| s.parse::<u64>()))
            else {
                continue;
            };
            // Trust: comments use the same space-only filename escaping as
            // dependency rules. Preserve other backslashes and the full path.
            let Some(path) = parts
                .next()
                .map(|path| PathBuf::from(unescape_filename(path)))
            else {
                continue;
            };

            let value = Some((file_len, checksum));
            // Trust: orphan/conflicting checksum keys cannot authenticate a
            // complete inventory, even though Cargo retains its legacy data.
            match ret.files.get(&path) {
                Some(previous) if previous.is_none() || previous == &value => {}
                _ => filename_rows_valid = false,
            }
            ret.files.insert(path, value);
        } else if !line.is_empty() && !line.starts_with("# ") && !line.ends_with(':') {
            // Trust: a literal LF can splice plausible Make records. An
            // unexplained fragment cannot be ignored for content authority.
            filename_rows_valid = false;
        }
    }
    ret.filename_inventory_complete &= filename_rows_valid;
    return Ok(ret);

    // Trust: the producer escapes ASCII spaces only, leaving other backslashes.
    fn unescape_filename(path: &str) -> String {
        path.replace("\\ ", " ")
    }

    fn matching_phony_dependencies(
        contents: &[u8],
        rhs: &str,
        raw_lf_rows: bool,
    ) -> Option<Vec<PathBuf>> {
        let encoded = contents
            .split_inclusive(|byte| *byte == b'\n')
            .filter_map(|line| {
                let line = str::from_utf8(line).ok()?;
                if raw_lf_rows {
                    Some(line.strip_suffix('\n').unwrap_or(line))
                } else {
                    line.lines().next()
                }
            })
            .filter(|line| !line.starts_with("# ") && !line.contains(": "))
            .filter_map(|line| line.strip_suffix(':'))
            .collect::<Vec<_>>();
        if encoded.is_empty()
            || encoded.iter().any(|path| path.is_empty())
            || encoded.join(" ") != rhs
        {
            return None;
        }
        encoded
            .into_iter()
            .map(|path| {
                let raw = unescape_filename(path);
                // Reject unescaped multi-target syntax, rather than reading it
                // as the compiler's one-path record. Never consult the filesystem.
                (raw.replace(' ', "\\ ") == path).then(|| PathBuf::from(raw))
            })
            .collect()
    }

    // rustc tries to fit env var names and values all on a single line, which
    // means it needs to escape `\r` and `\n`. The escape syntax used is "\n"
    // which means that `\` also needs to be escaped.
    fn unescape_env(s: &str) -> CargoResult<String> {
        let mut ret = String::with_capacity(s.len());
        let mut chars = s.chars();
        while let Some(c) = chars.next() {
            if c != '\\' {
                ret.push(c);
                continue;
            }
            match chars.next() {
                Some('\\') => ret.push('\\'),
                Some('n') => ret.push('\n'),
                Some('r') => ret.push('\r'),
                Some(c) => bail!("unknown escape character `{}`", c),
                None => bail!("unterminated escape character"),
            }
        }
        Ok(ret)
    }
}

/// Parses Cargo's internal [`EncodedDepInfo`] structure that was previously
/// serialized to disk.
///
/// Note that this is not rustc's `*.d` files.
///
/// Also note that rustc's `*.d` files are translated to Cargo-specific
/// `EncodedDepInfo` files after compilations have finished in
/// [`translate_dep_info`].
///
/// Trust: every unavailable outcome requires rebuilding. A format mismatch
/// describes only the recognized header, never the validity of an old payload.
/// Relocation tokens must still name a current root before the read-set is usable.
pub fn parse_dep_info(
    pkg_root: &Path,
    build_root: &Path,
    ws_root: &Path,
    dep_info: &Path,
    relocation: Option<&RelocationRoots>,
) -> Result<RustcDepInfo, DepInfoUnavailable> {
    let data = std::fs::read(dep_info).map_err(|error| {
        if error.kind() == io::ErrorKind::NotFound {
            DepInfoUnavailable::Missing
        } else {
            DepInfoUnavailable::Unreadable
        }
    })?;
    let info = EncodedDepInfo::parse(&data)?;
    let mut ret = RustcDepInfo::default();
    ret.filename_inventory_complete = info.filename_inventory_complete;
    ret.env = info.env;
    ret.tool_inputs = info.tool_inputs;
    for (ty, path, checksum_info) in info.files {
        let Some(path) = make_absolute_path(ty, pkg_root, build_root, ws_root, relocation, &path)
        else {
            tracing::debug!(
                "dep-info at {:?} names an unknown relocation root: {:?}",
                dep_info,
                relocation_roots::display_path(&path)
            );
            return Err(DepInfoUnavailable::RelocationRootUnavailable);
        };
        ret.files.insert(
            path,
            checksum_info.and_then(|(file_len, checksum)| {
                Checksum::from_str(&checksum).ok().map(|c| (file_len, c))
            }),
        );
    }
    for (ty, path, observed) in info.module_candidates {
        let Some(path) = make_absolute_path(ty, pkg_root, build_root, ws_root, relocation, &path)
        else {
            return Err(DepInfoUnavailable::RelocationRootUnavailable);
        };
        ret.module_candidates.push((path, observed));
    }
    Ok(ret)
}

// Trust: `None` for a relocation root token that names no current root.
fn make_absolute_path(
    ty: DepInfoPathType,
    pkg_root: &Path,
    build_root: &Path,
    ws_root: &Path,
    relocation: Option<&RelocationRoots>,
    path: &Path,
) -> Option<PathBuf> {
    let relative_to = match ty {
        DepInfoPathType::PackageRootRelative => pkg_root,
        // N.B. path might be absolute here in which case the join below will have no effect
        DepInfoPathType::BuildRootRelative => build_root,
        DepInfoPathType::WorkspaceRootRelative => ws_root,
        DepInfoPathType::RelocationRootRelative => {
            return relocation_roots::expand_path(path, relocation).map(|path| path.into_owned());
        }
    };

    if path.as_os_str().is_empty() {
        // Joining with an empty path causes Rust to add a trailing path separator. On Windows, this
        // would add an invalid trailing backslash to the .d file.
        return Some(relative_to.to_path_buf());
    }

    Some(relative_to.join(path))
}

/// Some algorithms are here to ensure compatibility with possible rustc outputs.
/// The presence of an algorithm here is not a suggestion that it's fit for use.
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
pub enum ChecksumAlgo {
    Sha256,
    Blake3,
}

impl ChecksumAlgo {
    fn hash_len(&self) -> usize {
        match self {
            ChecksumAlgo::Sha256 | ChecksumAlgo::Blake3 => 32,
        }
    }
}

impl FromStr for ChecksumAlgo {
    type Err = InvalidChecksum;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "sha256" => Ok(Self::Sha256),
            "blake3" => Ok(Self::Blake3),
            _ => Err(InvalidChecksum::InvalidChecksumAlgo),
        }
    }
}

impl fmt::Display for ChecksumAlgo {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            ChecksumAlgo::Sha256 => "sha256",
            ChecksumAlgo::Blake3 => "blake3",
        })
    }
}

#[derive(Copy, Clone, Debug, Eq, PartialEq)]
pub struct Checksum {
    algo: ChecksumAlgo,
    /// If the algorithm uses fewer than 32 bytes, then the remaining bytes will be zero.
    value: [u8; 32],
}

impl Checksum {
    pub fn new(algo: ChecksumAlgo, value: [u8; 32]) -> Self {
        Self { algo, value }
    }

    pub fn compute(algo: ChecksumAlgo, contents: impl Read) -> Result<Self, io::Error> {
        // Buffer size is the recommended amount to fully leverage SIMD instructions on AVX-512 as per
        // blake3 documentation.
        let mut buf = vec![0; 16 * 1024];
        let mut ret = Self {
            algo,
            value: [0; 32],
        };
        let len = algo.hash_len();
        let value = &mut ret.value[..len];

        fn digest<T>(
            mut hasher: T,
            mut update: impl FnMut(&mut T, &[u8]),
            finish: impl FnOnce(T, &mut [u8]),
            mut contents: impl Read,
            buf: &mut [u8],
            value: &mut [u8],
        ) -> Result<(), io::Error> {
            loop {
                let bytes_read = contents.read(buf)?;
                if bytes_read == 0 {
                    break;
                }
                update(&mut hasher, &buf[0..bytes_read]);
            }
            finish(hasher, value);
            Ok(())
        }

        match algo {
            ChecksumAlgo::Sha256 => {
                digest(
                    Sha256::new(),
                    |h, b| {
                        h.update(b);
                    },
                    |mut h, out| out.copy_from_slice(&h.finish()),
                    contents,
                    &mut buf,
                    value,
                )?;
            }
            ChecksumAlgo::Blake3 => {
                digest(
                    blake3::Hasher::new(),
                    |h, b| {
                        h.update(b);
                    },
                    |h, out| out.copy_from_slice(h.finalize().as_bytes()),
                    contents,
                    &mut buf,
                    value,
                )?;
            }
        }
        Ok(ret)
    }

    pub fn algo(&self) -> ChecksumAlgo {
        self.algo
    }

    pub fn value(&self) -> &[u8; 32] {
        &self.value
    }
}

impl FromStr for Checksum {
    type Err = InvalidChecksum;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let mut parts = s.split('=');
        let Some(algo) = parts.next().map(ChecksumAlgo::from_str).transpose()? else {
            return Err(InvalidChecksum::InvalidFormat);
        };
        let Some(checksum) = parts.next() else {
            return Err(InvalidChecksum::InvalidFormat);
        };
        let mut value = [0; 32];
        if hex::decode_to_slice(checksum, &mut value[0..algo.hash_len()]).is_err() {
            return Err(InvalidChecksum::InvalidChecksum(algo));
        }
        Ok(Self { algo, value })
    }
}

impl fmt::Display for Checksum {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut checksum = [0; 64];
        let hash_len = self.algo.hash_len();
        hex::encode_to_slice(&self.value[0..hash_len], &mut checksum[0..(hash_len * 2)])
            .map_err(|_| fmt::Error)?;
        write!(
            f,
            "{}={}",
            self.algo,
            str::from_utf8(&checksum[0..(hash_len * 2)]).unwrap_or_default()
        )
    }
}

impl Serialize for Checksum {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        serializer.serialize_str(&self.to_string())
    }
}

impl<'de> serde::Deserialize<'de> for Checksum {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let s = String::deserialize(deserializer)?;
        s.parse().map_err(serde::de::Error::custom)
    }
}

#[derive(Debug, thiserror::Error)]
pub enum InvalidChecksum {
    #[error("algorithm portion incorrect, expected `sha256`, or `blake3`")]
    InvalidChecksumAlgo,
    #[error("expected {} hexadecimal digits in checksum portion", .0.hash_len() * 2)]
    InvalidChecksum(ChecksumAlgo),
    #[error("expected a string with format \"algorithm=hex_checksum\"")]
    InvalidFormat,
}

