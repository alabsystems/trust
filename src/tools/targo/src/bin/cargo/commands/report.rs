use crate::command_prelude::*;

use targo::CargoResult;
use targo::compiler::future_incompat::OnDiskReports;
use targo::compiler::future_incompat::REPORT_PREAMBLE;
use targo::drop_println;
use targo::ops;

pub fn cli() -> Command {
    subcommand("report")
        .about("Generate and display various kinds of reports")
        // Trust: the footer names the binary the user actually invoked; see
        // `command_help_footer` in `bin/cargo/main.rs`.
        .after_help(crate::command_help_footer("report"))
        .subcommand_required(true)
        .arg_required_else_help(true)
        .subcommand(
            subcommand("future-incompatibilities")
                .alias("future-incompat")
                .about("Reports any crates which will eventually stop compiling")
                .arg(
                    opt(
                        "id",
                        "identifier of the report generated by a Cargo command invocation",
                    )
                    .value_name("id"),
                )
                .arg_package("Package to display a report for")
                .after_help(crate::command_help_footer(
                    "report future-incompatibilities",
                )),
        )
        .subcommand(
            subcommand("timings")
                .about("Reports the build timings of previous sessions (unstable)")
                .arg_manifest_path()
                .arg(flag("open", "Opens the timing report in a browser"))
                .arg(opt("id", "Session ID to report on").value_name("ID")),
        )
        .subcommand(
            subcommand("sessions")
                .about("Reports the previous sessions (unstable)")
                .arg_manifest_path()
                .arg(
                    opt("limit", "Limit the number of results")
                        .value_name("N")
                        .value_parser(clap::value_parser!(u64).range(1..))
                        .default_value("10"),
                ),
        )
        .subcommand(
            subcommand("rebuilds")
                .about("Reports rebuild reasons from previous sessions (unstable)")
                .arg_manifest_path()
                .arg(opt("id", "Session ID to report on").value_name("ID"))
                .arg(flag(
                    "json",
                    "Print observed rebuild classifications as JSON",
                )),
        )
        // Trust: metadata-only report; JSON costs require complete evidence.
        .subcommand(
            subcommand("cache-work")
                .about("Reports build-script input capture work (unstable)")
                .arg_manifest_path()
                .arg(opt("id", "Session ID to report on").value_name("ID"))
                .arg(flag("json", "Print a complete machine-readable report")),
        )
        // Trust: actual native queue outcomes, separate from input scan work.
        .subcommand(
            subcommand("execution")
                .about("Reports compilation queue outcomes (unstable)")
                .arg_manifest_path()
                .arg(opt("id", "Session ID to report on").value_name("ID"))
                .arg(flag("json", "Print a machine-readable execution report")),
        )
}

pub fn exec(gctx: &mut GlobalContext, args: &ArgMatches) -> CliResult {
    match args.subcommand() {
        Some(("future-incompatibilities", args)) => report_future_incompatibilities(gctx, args),
        Some(("timings", args)) => {
            gctx.cli_unstable().fail_if_stable_command(
                gctx,
                "report timings",
                15844,
                "build-analysis",
                gctx.cli_unstable().build_analysis,
            )?;
            let opts = timings_opts(gctx, args)?;
            // Trust: an invalid explicit manifest must remain an error rather
            // than silently selecting a session outside the requested workspace.
            let ws = if args.get_raw("manifest-path").is_some() {
                Some(args.workspace(gctx)?)
            } else {
                args.workspace(gctx).ok()
            };
            ops::report_timings(gctx, ws.as_ref(), opts)?;
            Ok(())
        }
        Some(("sessions", args)) => {
            gctx.cli_unstable().fail_if_stable_command(
                gctx,
                "report sessions",
                15844,
                "build-analysis",
                gctx.cli_unstable().build_analysis,
            )?;
            let ws = args.workspace(gctx).ok();
            let opts = sessions_opts(args)?;
            ops::report_sessions(gctx, ws.as_ref(), opts)?;
            Ok(())
        }
        Some(("rebuilds", args)) => {
            gctx.cli_unstable().fail_if_stable_command(
                gctx,
                "report rebuilds",
                15844,
                "build-analysis",
                gctx.cli_unstable().build_analysis,
            )?;
            // Trust: preserve an explicit workspace error instead of silently
            // turning a failed manifest lookup into an unscoped log query.
            let ws = if args.get_raw("manifest-path").is_some() {
                Some(args.workspace(gctx)?)
            } else {
                args.workspace(gctx).ok()
            };
            let opts = rebuilds_opts(args)?;
            ops::report_rebuilds(gctx, ws.as_ref(), opts)?;
            Ok(())
        }
        Some((name @ ("cache-work" | "execution"), args)) => {
            gctx.cli_unstable().fail_if_stable_command(
                gctx,
                &format!("report {name}"),
                15844,
                "build-analysis",
                gctx.cli_unstable().build_analysis,
            )?;
            // Trust: an invalid explicit workspace must not become an unscoped
            // session query. Outside a workspace, an ID can still be queried.
            let ws = if args.get_raw("manifest-path").is_some() {
                Some(args.workspace(gctx)?)
            } else {
                args.workspace(gctx).ok()
            };
            let id = args
                .get_one::<String>("id")
                .map(|id| id.parse())
                .transpose()?;
            if name == "execution" {
                ops::report_execution(
                    gctx,
                    ws.as_ref(),
                    ops::ReportExecutionOptions { id, json: args.get_flag("json") },
                )?;
            } else {
                ops::report_cache_work(
                    gctx,
                    ws.as_ref(),
                    ops::ReportCacheWorkOptions { id, json: args.get_flag("json") },
                )?;
            }
            Ok(())
        }
        Some((cmd, _)) => {
            unreachable!("unexpected command {}", cmd)
        }
        None => {
            unreachable!("unexpected command")
        }
    }
}

fn report_future_incompatibilities(gctx: &GlobalContext, args: &ArgMatches) -> CliResult {
    let ws = args.workspace(gctx)?;
    let reports = OnDiskReports::load(&ws)?;
    let id = args
        .value_of_u32("id")?
        .unwrap_or_else(|| reports.last_id());
    let krate = args.get_one::<String>("package").map(String::as_str);
    let report = reports.get_report(id, krate)?;
    drop_println!(gctx, "{}", REPORT_PREAMBLE);
    drop(gctx.shell().print_ansi_stdout(report.as_bytes()));
    Ok(())
}

fn timings_opts<'a>(
    gctx: &'a GlobalContext,
    args: &ArgMatches,
) -> CargoResult<ops::ReportTimingsOptions<'a>> {
    let open_result = args.get_flag("open");
    let id = args
        .get_one::<String>("id")
        .map(|s| s.parse())
        .transpose()?;

    Ok(ops::ReportTimingsOptions {
        open_result,
        gctx,
        id,
    })
}

fn sessions_opts(args: &ArgMatches) -> CargoResult<ops::ReportSessionsOptions> {
    let limit = *args.get_one::<u64>("limit").unwrap_or(&10);
    let limit = limit.min(usize::MAX as u64) as usize;

    Ok(ops::ReportSessionsOptions { limit })
}

fn rebuilds_opts(args: &ArgMatches) -> CargoResult<ops::ReportRebuildsOptions> {
    let id = args
        .get_one::<String>("id")
        .map(|s| s.parse())
        .transpose()?;

    Ok(ops::ReportRebuildsOptions {
        id,
        json: args.get_flag("json"),
    })
}
